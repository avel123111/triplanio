-- TRIP-296: вычистить легаси-аватары dicebear на ИСТОЧНИКЕ.
--
-- Симптом: у одного и того же пользователя на экранах трипа один аватар, а в
-- шапке и профиле другой. Причина не в вёрстке — в двух путях чтения одного
-- поля users.avatar_url:
--   * шапка/профиль берут профиль через AuthContext, где стоял санитайзер
--     «если ссылка ведёт на api.dicebear.com — считать, что аватара нет»
--     (рисуются канонические инициалы на градиенте);
--   * экраны трипа и чат берут те же данные через edge resolveProfiles, который
--     отдаёт avatar_url КАК ЕСТЬ → там оставалась картинка dicebear.
-- То есть правило жило только на одном из двух путей.
--
-- Правильный слой — данные: dicebear это генерируемая картинка-заглушка эпохи
-- base44, наш канон отсутствующего аватара — инициалы на градиенте (<Avatar>).
-- Ни один writer в коде такие ссылки больше не создаёт (проверено: единственное
-- упоминание было в самом санитайзере), поэтому после зачистки правило не нужно
-- ни в одном из путей чтения — санитайзер в AuthContext удалён этим же PR.
--
-- Объём на момент миграции: dev 1 строка из 29, prod проверится при накатывании.
update public.users
   set avatar_url = null
 where avatar_url like '%api.dicebear.com%';
