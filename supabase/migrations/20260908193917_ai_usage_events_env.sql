-- `ai_usage_events.env` — окружение, в котором произошёл вызов модели.
--
-- ЗАЧЕМ. Строки usage со всех сред складываются в ОДНУ таблицу (единственный
-- писатель — n8n-субворкфлоу «AI Usage save», один на инстанс n8n), поэтому в
-- отчётах стоимости dev-прогоны неотличимы от прода и завышают счёт. Колонка
-- разделяет их на чтении.
--
-- NULLABLE НАМЕРЕННО: метку несут не все пути. Три web/inapp-флоу получают её
-- на входе (`planTripWithAi` / `parseBookingWithAi` / `callTriplanioAi` шлют
-- `env: envTag()`, см. `_shared/envTag.ts`), а TG-бот и TG-напоминания живут
-- только на проде и env на проводе не имеют вовсе. Ни один вызов «AI Usage
-- save» сегодня env не передаёт — вся история и всё, что не прокинули, остаётся
-- NULL, и это честнее выдуманного дефолта.
--
-- Тип — домен `public.short_text` (text с кэпом 300, TRIP-169): слой
-- целостности ввода в БД, а не сырой безразмерный text. Перечня допустимых
-- значений НЕТ намеренно — writer внешний (n8n), и упавший на CHECK insert
-- потерял бы строку учёта; на чтении значение группируют как есть.
alter table public.ai_usage_events
  add column if not exists env public.short_text;

comment on column public.ai_usage_events.env is
  'Окружение, породившее вызов модели (метка с провода, `_shared/envTag.ts`: production | development). NULL = флоу метку не передал (TG-пути, историческая часть).';
