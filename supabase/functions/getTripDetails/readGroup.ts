/**
 * Чтение результата одной include-группы getTripDetails (TRIP-399).
 *
 * Сборщик раньше брал `.data ?? []` и МОЛЧА игнорировал `error`: упавший SELECT
 * (напр. `trip_documents`) выглядел как «данных нет», и экран рисовал ПУСТО
 * вместо «ошибка загрузки» — пользователь грузил документы заново (дубли). Здесь
 * сбой под-запроса — НЕ пустой ответ: бросаем → `withHandler` отдаёт 5xx
 * (ретраится, летит в Sentry), ровно как делал прежний прямой запрос экрана,
 * который на ошибке бросал. Пустой успешный ответ остаётся `[]`.
 *
 * Пуро и без I/O — поэтому пинится `readGroup_test.ts` (сбой обязан быть виден
 * красным под мутацией).
 */
export function readGroup(result: { data: unknown[] | null; error: unknown }): unknown[] {
  if (result.error) throw result.error;
  return result.data ?? [];
}
