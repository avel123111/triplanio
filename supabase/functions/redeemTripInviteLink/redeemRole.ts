/**
 * Роль, с которой человек оказывается в трипе после редима ссылки-приглашения.
 *
 * Правило одно и неочевидное: **ссылка не понижает уже выданное приглашение.**
 * Админ позвал человека админом персонально; тот, не приняв приглашение, зашёл
 * по общей viewer-ссылке — и без этого правила молча стал бы зрителем, а
 * пригласивший об этом не узнал бы никак.
 *
 * Вынесено из обработчика чистой функцией, чтобы правило можно было запинить
 * тестом: внутри async-ветки с запросами к БД оно непроверяемо (TRIP-274 Ф1.4).
 *
 * Ролей ровно три, у ссылки — две: CHECK на trip_invite_links допускает только
 * 'viewer' | 'admin' (owner ссылкой не выдаётся никогда — владение это
 * trips.created_by, а не строка членства).
 */

/** Роль существующей строки членства, которую редим активирует (или null, если
 *  строки нет), и роль, зашитая в ссылку. */
export function resolveRedeemRole(existingRole: string | null, linkRole: string): string {
  // Только 'admin' переживает редим. Белый список, а не «не viewer»: незнакомая
  // или пустая роль в строке не должна вдруг оказаться сильнее ссылки.
  return existingRole === 'admin' ? 'admin' : linkRole;
}
