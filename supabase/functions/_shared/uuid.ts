/**
 * `isUuid` — один предикат на все edge-функции (TRIP-513).
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, а не «импортируй из того места, где он уже лежал».
 * Жил он в `mutateRules.ts` — и это правильный дом для ШВА ЗАПИСИ, но не для
 * общего примитива: `mutateRules` тянет за собой десять `resources/*` (весь
 * реестр ресурсов). Функции, которая в нашу БД ничего не пишет, этот вес не
 * нужен, а `http.ts` рядом прямо просит: «Tiny by design (Deno cold-start)».
 * Импорт ради одной регулярки удвоил бы холодный старт.
 *
 * Копия регулярки — тоже не выход: она уже была в двух местах (`mutateRules` и
 * `emailPrefs`), и гард 3c `check-one-helper` такую пару НЕ ловит — он сверяет
 * тела хелперов, а константа плюс инлайновый `.test()` телом не выглядит.
 *
 * `mutateRules.ts` реэкспортирует имя отсюда, поэтому оба его потребителя
 * (`resources/tripRoute.ts` и он сам) не тронуты.
 */

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** Строка ли это UUID. Регистр не важен — Postgres и Resend отдают в разном. */
export function isUuid(value: unknown): value is string {
  return typeof value === 'string' && UUID_RE.test(value);
}
