import React from 'react';

/* Слой текста превью — новые классы и позиции из данных (апрув Pavel 28.08.2026,
   план «текст карточки становится текстом»):
   floor-exempt: classes +2 — `.sc-txt` и `.sc-txt__i`, слой текста превью
   floor-exempt: inline +2 — координаты и облик строки приезжают раскладкой с edge
   floor-exempt: triage +2 — семья заводится под ревью, как и положено новой
   floor-exempt: dsshare +3 — у «строка постера на своей координате» примитива ДС
     нет и быть не должно: канон `.t-*` описывает типографику ПРИЛОЖЕНИЯ, а тут
     облик задаёт раскладка карточки, и подменять её шкалой значило бы развести
     превью с готовой картинкой
*/
/**
 * Текст share-карточки в превью — обычным текстом страницы поверх кадра.
 *
 * ЗАЧЕМ ОН ОТДЕЛЬНЫМ СЛОЕМ. Раньше текст жил внутри кадра — `<text>` в SVG,
 * который вставляется в документ строкой. На iOS 26 такой текст ТЕРЯЛ РАСКЛАДКУ:
 * строка приходила с верными ширинами и через полторы секунды обнулялась, а
 * названия городов пропадали (замер: t0 237/171 → t1 0/0, Sentry TRIPLANIO-2Z;
 * узел, созданный после этого момента, был цел — то есть раскладка протухала, и
 * пересчитать её было некому). Обычный текст страницы этой болезни не
 * подвержен. Он же нужен, чтобы карточку можно было ПРАВИТЬ: строку городов
 * правят одним полем, а не двумя текстами с фигурой между ними.
 *
 * ПОЗИЦИИ НЕ СЧИТАЮТСЯ ЗДЕСЬ. Всё приезжает готовым из `buildCardText` на edge —
 * теми же числами, которыми та же строка нарисована в финальной карточке. Второй
 расчёт того же макета на клиенте — это ровно тот механизм, которым превью
 * расходится с готовой карточкой; заводить его нельзя.
 *
 * МАСШТАБ — КОНТЕЙНЕРНЫЕ ЕДИНИЦЫ, а не JS. Координаты приходят в единицах
 * КАРТОЧКИ (1080 × высота формата), а сцена превью на телефоне ~380 px. Слой
 * объявлен контейнером, и одна переменная `--sc-txt-u` = «одна единица карточки»
 * переводит все числа разом. Поэтому пересчитывать на ресайз нечего: ни
 * обработчика, ни наблюдателя размера.
 */
export default function ShareCardText({ items, cardW = 1080 }) {
  // ★ ПРОВЕРКА ЧЕРЕЗ `?.`, А НЕ ЧЕРЕЗ УМОЛЧАНИЕ ПАРАМЕТРА. Умолчание срабатывает
  // только на `undefined`; `null` проходит мимо него — и `null.length` роняет
  // весь диалог. Ровно это и случилось на dev: раскладки в ответе ещё не было
  // (фронт выкатился раньше функции), вызыватель передал пустоту, и карточка
  // перестала открываться. Отсутствие раскладки — ЗАКОННОЕ состояние: пока
  // функция не обновлена или ответ без текста, слой просто не рисуется.
  if (!items?.length) return null;
  return (
    // Единица карточки в контейнерных процентах — величина ИЗ ДАННЫХ (ширина
    // формата), классом её не выразить.
    <div className="sc-txt" style={{ '--sc-txt-u': `calc(100cqw / ${cardW})` /* inline-style-exempt: ширина формата приезжает с оверлеем */ }}>
      {items.map((t, i) => (
        <span
          key={`${t.kind}-${i}`}
          className="sc-txt__i"
          // Позиция, кегль, вес и трекинг — ДАННЫЕ раскладки, у каждой строки
          // свои; классом выражается только то, что у всех одинаково (тень,
          // семейство, цвет, запрет переноса).
          style={{
            // inline-style-exempt: раскладка строки приезжает с edge
            left: `calc(${t.x} * var(--sc-txt-u))`,
            top: `calc(${t.top} * var(--sc-txt-u))`,
            fontSize: `calc(${t.size} * var(--sc-txt-u))`,
            fontWeight: t.weight, // design-token-exempt: вес приезжает раскладкой карточки, не шкалой приложения
            ...(t.tracking ? { letterSpacing: `calc(${t.tracking} * var(--sc-txt-u))` } : null), // design-token-exempt: трекинг из раскладки карточки, не шкала приложения
            // `anchor: middle` у SVG — это выключка по центру относительно точки:
            // в DOM тот же смысл даёт сдвиг на половину собственной ширины.
            ...(t.anchor === 'middle' ? { transform: 'translateX(-50%)' } : null),
          }}
        >
          {t.value}
        </span>
      ))}
    </div>
  );
}
