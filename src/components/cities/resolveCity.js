// @ts-check
import { tzFromCoords } from '@/lib/timezone';
import { localizeCountry } from '@/lib/i18n/format';

/**
 * ДОВЕДЕНИЕ СТРОКИ ГАЗЕТТИРА ДО ГОРОДА — ОДНО МЕСТО НА ВСЕ ФАСАДЫ.
 *
 * ★ ПОЧЕМУ ЭТО ОБЯЗАНО БЫТЬ ОДНОЙ ФУНКЦИЕЙ. `search_gazetteer` отдаёт строку
 * СПРАВОЧНИКА, а не готовый узел маршрута: `mapGazCity` кладёт `country: null`
 * (у газеттира есть только код страны) и таймзоны не кладёт вовсе — её считают
 * из координат. То есть между «человек ткнул в строку» и «город лёг в маршрут»
 * есть обязательный шаг, и он был написан у ОДНОГО фасада из двух: `CityPicker`
 * обогащал, `CitySearch` отдавал строку как есть.
 *
 * ⚠️ ЦЕНОЙ БЫЛА НЕ ПОДПИСЬ, А ДАННЫЕ. Пока `CitySearch` кормил только «сообщи и
 * очистись», это сходило с рук. Как только на него сел общий композер города,
 * каждый добавленный им город поехал в сохранение БЕЗ ТАЙМЗОНЫ (а `timezone`
 * едет в `create_trip_with_route` и определяет, как сервер раскладывает время) и
 * без названия страны — в обзоре маршрута на месте страны стоял прочерк.
 * Пропущенная подпись была видна, пропущенная таймзона — нет.
 *
 * Поэтому шаг переехал СЮДА, а фасады его зовут: у города один способ стать
 * городом, и добавить пятый вход, забыв обогащение, больше нельзя.
 *
 * @param {any} row строка газеттира (`searchCities`)
 * @param {string} lang язык, на котором показывается страна
 */
export function resolveCity(row, lang) {
  if (!row) return row;
  return {
    ...row,
    // Газеттир знает код страны, но не её имя: имя зависит от языка зрителя и
    // берётся из `Intl` (TRIP-223), а не хранится строкой.
    country: row.country || localizeCountry(row.country_code, lang) || '',
    // Таймзона выводится из координат — своего поля у неё в справочнике нет.
    timezone: row.timezone || tzFromCoords(row.latitude, row.longitude),
  };
}
