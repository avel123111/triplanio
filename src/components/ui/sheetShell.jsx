import { createContext, useCallback, useContext, useEffect, useRef, useState } from 'react';
import { Drawer } from 'vaul';
import { useKeyboardMine } from '@/lib/keyboardOpen';
import { SurfaceCrashGuard } from '@/components/ui/surfaceCrashGuard';

/**
 * sheetShell — ЕДИНСТВЕННЫЙ ДОМ vaul В ПРИЛОЖЕНИИ.
 *
 * Мобильная шторка была написана четыре раза (`ui/Sheet`, `ui/LpSheet`,
 * `ui/dialog` ≤640, `stats/VisitPanel` ≤640) — четыре копии одной обвязки,
 * то есть четыре места под следующую правку жеста, и одно из них о ней не
 * узнает. Здесь контракт объявлен один раз: шов владеет ДВИЖЕНИЕМ (жест,
 * слайд, портал, подложка, клавиатура, грип), вызыватель — СКИНОМ.
 *
 * ★ `repositionInputs={false}` — не вкус. Вьюпорт объявлен
 * `interactive-widget=resizes-content`: раскладка уже сжимается над клавиатурой,
 * и приклеенный к низу шит встаёт над ней сам. Позволить vaul поднять его ВТОРОЙ
 * раз — это «улетающий» шит при фокусе в поле.
 *
 * ⚠️ ЦЕНА ПАРЫ: `resizes-content` перекладывает страницу под шитом на
 * Chrome/Android (на iOS-движке директива не поддерживается и раскладку не
 * трогает). Обратная пара (`overlays-content` + подъём средствами vaul) это
 * снимает, но трогает КАЖДЫЙ экран с полем ввода на обеих платформах — отдельная
 * задача со своей проверкой на устройстве.
 *
 * НЕ сюда: `PeekSheet` — немодальный шит с детентами, намеренно не на vaul
 * (vaul лочит страницу и ставит `touch-action: none` на всю поверхность, что
 * несовместимо с постоянным шитом над живой картой; разбор в его шапке).
 */

/**
 * ГЛУБИНА ВЛОЖЕННОСТИ ШТОРОК. Шторка над шторкой — не экзотика, а норма: окно
 * события и окно «добавить место» САМИ являются шторками на телефоне, и пикер
 * города, открытый из них, обязан лечь ПОВЕРХ. У vaul для этого отдельный корень
 * (`Drawer.NestedRoot`), и выбирать между ним и обычным нужно ПО ФАКТУ ДЕРЕВА, а
 * не пропом вызывателя: проп означал бы, что каждый пикер обязан знать, кто его
 * открыл, и соврал бы ровно в тот день, когда экран переставили.
 *
 * ⚠️ ОШИБКА ЗДЕСЬ НЕ ПАДАЕТ, А ТИХО МЕНЯЕТ ПОВЕДЕНИЕ — и это единственная причина,
 * по которой выбор стоит того, чтобы быть автоматическим. Проверено на месте:
 * `NestedRoot` вне родителя НЕ бросает, хотя и содержит `throw`, — у vaul в
 * дефолтном значении контекста `onNestedDrag` объявлен заглушкой, и условие
 * никогда не выполняется. Значит цена промаха такая:
 *   • `NestedRoot` на глубине 0 → в `Root` уезжает `nested: true`, а закрытие и
 *     перетаскивание привязаны к заглушкам родителя, которого нет;
 *   • обычный `Root` на глубине >0 → родитель не узнаёт об открытии ребёнка и
 *     продолжает считать себя верхней поверхностью.
 * Ни то, ни другое не даёт ни исключения, ни красного теста.
 *
 * Контекст течёт СКВОЗЬ портал (React), поэтому вложенная шторка видит родителя,
 * хотя физически живёт в `document.body`. Глубина растёт только внутри
 * отрисованного содержимого: закрытая шторка портал не монтирует, и её потомков
 * в дереве нет.
 */
const SheetDepth = createContext(0);

/**
 * Корень шторки. Открытость контролирует вызыватель — как у `Drawer.Root`.
 * @param {{ open?: boolean, onOpenChange?: (v: boolean) => void, children?: any }} p
 */
export function SheetRoot({ children, ...props }) {
  const depth = useContext(SheetDepth);
  const Root = depth > 0 ? Drawer.NestedRoot : Drawer.Root;
  return (
    <SheetDepth.Provider value={depth + 1}>
      {/* Граница краха поверхности (TRIP-515): краш внутри шита закрывает шит
          (onOpenChange(false)), а не убивает приложение. Стоит здесь, в КОРНЕ шва
          — у него в руках onOpenChange; SheetSurface/Content его не видят. */}
      <Root repositionInputs={false} {...props}>
        <SurfaceCrashGuard open={props.open} onClose={() => props.onOpenChange?.(false)}>
          {children}
        </SurfaceCrashGuard>
      </Root>
    </SheetDepth.Provider>
  );
}

/**
 * ПОЛНОРОСТНАЯ ПОВЕРХНОСТЬ ЗАЯВЛЯЕТСЯ ОДНИМ ФАКТОМ, И ПРОИЗВОДИТ ЕГО ШОВ
 * (TRIP-494). Таких поверхностей в приложении ТРИ — шторка пикера, оболочка
 * панелей редактора и окно с полями (TRIP-499), — и это одна и та же вещь: экран
 * во весь вьюпорт, коробка от раскладки, краска общая, бровь общая, клавиатура
 * резервирует место внутри. Третья добавилась ОДНИМ пропом и не потребовала
 * ничего от шва — ради этого признак и заводили.
 *
 * ★ ПОЧЕМУ ПРИЗНАК, А НЕ КЛАСС. «Я экран» — это РОЛЬ поверхности, а не её скин;
 * до сведения роль была записана ДВАЖДЫ и по-разному: у шторки классом
 * `.sheet--full` (его вешал проп `full`), у панели — самим фактом скина
 * `.lp-sheet`. Два способа сказать одно — развилка, на которой третья
 * поверхность объявит роль третьим способом и не получит ни краски, ни резерва
 * под клавиатуру. Теперь способ один: поверхность просит `full` у шва, шов
 * ставит признак, CSS адресует признак. Классы остаются тем, чем и были, —
 * скинами (`.sheet` рисует лист, `.lp-sheet` держит карточку панели).
 */
export const SHEET_FULL_ATTR = 'data-sheet-full';

/**
 * СКРОЛЛЕР ПОЛНОРОСТНОЙ ПОВЕРХНОСТИ НАЗЫВАЕТ СЕБЯ САМ (TRIP-494).
 *
 * ⚠️ ЧТО БЫЛО. Резерв под клавиатуру шов раздавал ПОИМЁННО:
 * `.sheet--full .ss-list, .lp-sheet .lp-b { padding-bottom: var(--kb-h) }` — то
 * есть правило знало, как зовут скроллер у двух чужих скинов. Третья поверхность
 * со своим скроллером не получила бы резерва МОЛЧА, и её автор об этом не узнал
 * бы: ничего не ломается, поле просто оказывается под клавиатурой.
 *
 * Теперь скроллер объявляет, ЧТО ОН ЕСТЬ (`{...sheetScroller}`), а решает, кому
 * это важно, СЕМЬЯ (`[data-sheet-full] [data-sheet-scroller]`). Поэтому признак
 * ставится и там, где поверхность не полноростная (тело окна): он говорит про
 * САМ элемент, а не про его место в дереве, — то же правило, по которому скин
 * адресуют по объекту, а не по соседям (CLAUDE.md #6). Лишним он там не
 * становится: правило семьи до него не дотягивается.
 */
export const sheetScroller = { 'data-sheet-scroller': '' };

/**
 * ПОЛЕ ПРИШПИЛЕНО — СВОЙСТВО ПОВЕРХНОСТИ, И ОНО ОБЯЗАНО БЫТЬ НЕПОДВИЖНЫМ.
 *
 * Поверхность с пришпиленным полем въезжает иначе: едут заливка и лист, а хром и
 * поле проявляются на месте — иначе каретке достаётся 840 px пути за полсекунды.
 * Приём перебивает СОБСТВЕННЫЙ въезд vaul (`animation-name: none`), и вот это
 * перебивание обязано держаться ВСЁ ВРЕМЯ, пока поверхность открыта.
 *
 * ⚠️ ЖИВОЙ ЗАПРОС ПО СОДЕРЖИМОМУ ЗДЕСЬ — ДЕФЕКТ, И ОН БЫЛ ПОСТАВЛЕН. Условие
 * стояло как `:has(.ss-search)`, то есть «у поверхности сейчас есть поле». У
 * композера города поле живёт только на ПЕРВОЙ фазе: выбрал город — поле ушло,
 * `:has()` перестал совпадать, перебивание отвалилось, и vaul проиграл свой
 * въезд ЗАНОВО. Снаружи это читалось как «шит закрылся и открылся второй такой
 * же, но с плитками». Замер на живом билде: с полем `animation-name: none`, без
 * поля `slideFromBottom` + событие `animationstart`.
 * Поэтому факт объявляет ВЛАДЕЛЕЦ поверхности и один раз: содержимое внутри
 * меняется, способ въезда — нет.
 */
export const SHEET_PINNED_ATTR = 'data-sheet-pinned';

/**
 * ★★ РОСТ ПОЛНОРОСТНОЙ ПОВЕРХНОСТИ — ЭТО ВТОРОЕ ЕЁ СВОЙСТВО, И ОНО НЕ БУЛЕВО.
 *
 * `full` отвечает на вопрос «я экран или карточка над экраном»: коробка от
 * раскладки, краска страницы, резерв под клавиатуру. Это ОДНА роль, и она
 * осталась прежней. Вопрос «на какой рост поверхность встаёт при открытии» —
 * ДРУГОЙ, и до сих пор ответа у него не было вовсе: любая полноростная
 * поверхность занимала экран целиком.
 *
 * Значений два:
 *   `screen` (умолчание) — экран целиком. Шторка пикера и окно с полями: обе
 *      просят у человека ввод, а ввод занимает экран.
 *   `scene`  — рост СЦЕНЫ, на которой поверхность открылась (`--scene-rise`,
 *      публикует шит сцены, см. `ui/PeekSheet`). Панель города/события,
 *      открытая поверх шита маршрута, встаёт ТОЙ ЖЕ высотой: тап по городу
 *      раскрывает подробность, а не подменяет экран.
 *
 * ★ ПОЧЕМУ ПРИЗНАК, А НЕ КЛАСС, — по той же причине, что и у `full`: это роль
 * поверхности, а не её скин, и объявляет её ВЛАДЕЛЕЦ поверхности один раз.
 * Выводить рост из содержимого (какая панель сейчас внутри) нельзя — на этом
 * уже ломался способ въезда: свойство, выведенное из содержимого, отваливается
 * ровно тогда, когда содержимое сменилось.
 */
/* Признак ставится, только когда рост ОТЛИЧАЕТСЯ от экрана: атрибут со
   значением по умолчанию на каждой поверхности — шум, который следующий
   читатель примет за принятое решение. */
export const SHEET_RISE_ATTR = 'data-sheet-rise';

/**
 * ★★ «МНЕ НУЖЕН ВЕСЬ ЭКРАН» — ЗАЯВКА СОДЕРЖИМОГО, А НЕ ЗАПРОС ПОВЕРХНОСТИ О НЁМ.
 *
 * Форма правки/создания обязана занимать экран целиком: у неё поля, а под полем
 * встаёт клавиатура. Но живёт форма ГЛУБОКО внутри панели (`EventEditDialog`
 * приезжает и как режим правки просмотра, и как вкладка «у меня есть бронь»), и
 * поверхность про неё не знает. Знать и не должна: `:has()`-запрос по
 * содержимому — ровно тот дефект, что уже стоил перезапуска въезда шторки.
 *
 * Поэтому направление обратное: содержимое ЗАЯВЛЯЕТ потребность (`useScreenRise`),
 * поверхность её исполняет. Заявка живёт, пока смонтирован заявитель, — ушла
 * форма, поверхность вернулась на рост сцены. Счётчик, а не флаг: две формы в
 * стопке не должны гасить друг друга, снимая заявку соседа.
 */
const ScreenRiseClaim = createContext(/** @type {null | (() => () => void)} */ (null));

/** Заявки принимает САМА поверхность (`SheetSurface`), а не её вызыватель:
 *  вызыватель объявляет рост один раз пропом и о содержимом ничего не знает. */
function useScreenRiseHost() {
  const [claims, setClaims] = useState(0);
  const claim = useCallback(() => {
    setClaims((n) => n + 1);
    return () => setClaims((n) => n - 1);
  }, []);
  return /** @type {[boolean, () => () => void]} */ ([claims > 0, claim]);
}

/**
 * Содержимое объявляет: пока я здесь, поверхности нужен весь экран. Вне
 * поверхности с заявками (десктоп, модалка) — тишина, а не ошибка: потребность
 * та же, исполнять её просто некому.
 * @param {boolean} [active]
 */
export function useScreenRise(active = true) {
  const claim = useContext(ScreenRiseClaim);
  useEffect(() => {
    if (!active || !claim) return undefined;
    return claim();
  }, [active, claim]);
}

/**
 * Грип — «бровь» шторки: affordance и ничего больше (тянется вся поверхность,
 * это делает vaul), поэтому обработчиков на нём нет. Единственная разметка
 * грипа в приложении; функциональный грип `PeekSheet` — не отсюда.
 */
export function SheetGrip() {
  return <div className="sheet-grip" aria-hidden><i /></div>;
}

/**
 * Поверхность шторки: портал + подложка + перетаскиваемый лист.
 *
 * `className` — СКИН вызывателя (`.sheet`, `.lp-sheet`, `.dlg-modal`): шов не
 * решает, как поверхность выглядит. `grip={false}` — тем, кто рисует грип сам
 * внутри своей карточки (модалка кладёт его в `.dlg`) или у кого его нет
 * (полноэкранная панель редактора). Остаток пропов уезжает в `Drawer.Content`
 * — там `aria-describedby`, `onOpenAutoFocus` и прочий контракт Radix.
 *
 * ⚠️ БАЗА АННОТАЦИИ = ТО, КУДА УЕЗЖАЕТ ОСТАТОК, а он уезжает в `Drawer.Content`.
 * Закрытый объект из пяти ключей (первая редакция) запечатывал именно то, ради
 * чего остаток и пробрасывается: у `Drawer.Content` есть `onCloseAutoFocus`,
 * `onOpenAutoFocus`, `onEscapeKeyDown`, `onPointerDownOutside` — весь контракт
 * Radix, — и законный вызов краснел. Тот же виток ошибки разобран в
 * `design/props.test.js`; здесь он повторился шестым.
 *
 * @param {{ className: string, backdropClassName?: string, grip?: boolean,
 *   contentRef?: any, children?: any }
 *   & import('react').ComponentPropsWithoutRef<typeof Drawer.Content>} p
 */
/**
 * @param {{ className?: string, backdropClassName?: string, grip?: boolean,
 *   full?: boolean, rise?: 'screen' | 'scene', pinned?: boolean,
 *   contentRef?: any, children?: any }} p
 */
export function SheetSurface({
  className,
  backdropClassName = 'sheet-backdrop',
  grip = true,
  full = false,
  rise = 'screen',
  pinned = false,
  contentRef,
  children,
  ...rest
}) {
  // Рост, о котором просит содержимое, перебивает объявленный: форма занимает
  // экран, пока она здесь. Поверхность без заявок (пикер, окно) этого не
  // замечает — она и так `screen`.
  const [screenAsked, claimScreen] = useScreenRiseHost();
  // ★★ ВТОРАЯ ЗАЯВКА — САМА КЛАВИАТУРА, И ОНА НЕ ДУБЛЬ ПЕРВОЙ. Форма просит
  // экран ЗАРАНЕЕ (иначе она открылась бы ростом сцены и прыгала на первом тапе
  // в поле); клавиатура — страховка для полей, живущих где угодно ещё: фильтр
  // цены в витрине отелей, поиск в списке. Без неё поверхность ростом в
  // две трети экрана оставляет поле под клавиатурой, и сделать с этим изнутри
  // нечего — резерв у скроллера места не добавляет, он его только отдаёт.
  // ⚠️ «МОЯ» здесь так же несуще, как у шита: клавиатуру часто поднимает шторка,
  // легшая ПОВЕРХ, и на глобальный флаг эта поверхность прыгала бы под ней.
  const surfaceRef = useRef(/** @type {any} */ (null));
  const typingHere = useKeyboardMine(surfaceRef);
  // Ref СТАБИЛЕН (`useCallback`): новая функция на каждый рендер заставляла бы
  // React отцеплять и прицеплять узел заново — а узел здесь чужой (`Drawer.Content`).
  // Ref вызывателя при этом не теряется: шов ведёт свой и передаёт тот же узел
  // дальше, в обеих формах (функция и объект).
  const setSurface = useCallback((node) => {
    surfaceRef.current = node;
    if (typeof contentRef === 'function') contentRef(node);
    else if (contentRef) contentRef.current = node;
  }, [contentRef]);
  const effectiveRise = screenAsked || typingHere ? 'screen' : rise;
  return (
    <Drawer.Portal>
      <Drawer.Overlay className={backdropClassName} />
      {/* Фокус на открытии vaul гасит ПО УМОЛЧАНИЮ (`autoFocus = false` -> он
          зовёт `preventDefault()`), поэтому шторка открывается с опущенной
          клавиатурой. Это умолчание, а не запрет: поверхности, которой поле
          нужно в фокусе, достаточно передать штатный `onOpenAutoFocus` — он
          уезжает в `Drawer.Content` вместе с остатком пропов. Сегодня этого не
          делает НИКТО, и это вывод, а не пробел: на тач-платформе программный
          фокус ставит каретку, но не поднимает клавиатуру (разбор — в шапке
          `ui/PickerSheet`). */}
      <Drawer.Content
        ref={setSurface}
        className={className}
        {...(full ? { [SHEET_FULL_ATTR]: '' } : null)}
        {...(full && effectiveRise !== 'screen' ? { [SHEET_RISE_ATTR]: effectiveRise } : null)}
        {...(pinned ? { [SHEET_PINNED_ATTR]: '' } : null)}
        {...rest}
      >
        {grip ? <SheetGrip /> : null}
        <ScreenRiseClaim.Provider value={claimScreen}>{children}</ScreenRiseClaim.Provider>
      </Drawer.Content>
    </Drawer.Portal>
  );
}

