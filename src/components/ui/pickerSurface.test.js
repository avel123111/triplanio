test('★★ ОТКРЫТОСТЬ ПОВЕРХНОСТИ — ФАКТ, А НЕ ЛИТЕРАЛ', () => {
  /* ★ ЧТО ЛОМАЛОСЬ (TRIP-496). Панель редактора открывалась своим
     `<LpSheet open …>`: «шторка открыта» выражалось тем, что элемент вообще
     отрисован, а проп стоял ЛИТЕРАЛОМ. Пока слой был один, это сходило с рук; со
     стопкой (город → переезд) сломалось так: свайп вниз по верхнему слою vaul
     считает закрытием ПОВЕРХНОСТИ, дотягивает коробку до низа и сообщает
     `onOpenChange(false)`, а обработчик снимал только верхний слой — под ним
     оставался город, элемент оставался отрисованным, `open` не менялся НИКОГДА.
     vaul считал, что закрыл; экран считал, что ничего не произошло; шторка
     оставалась там, где её бросил палец. Замер модели: `translate3d(0px, 460px,
     0px)`, и через 2.4 с — то же самое.
     Литерал здесь — не стилистика: он делает состояние поверхности НЕВЫРАЗИМЫМ,
     то есть чинить нечего, пока он стоит. */
  const SHELLS = ['LpSheet', 'Sheet', 'PickerSheet', 'EventDrawerHost', 'PeekSheet'];
  /* ⚠️ ЗНАЧЕНИЕ ПРОПА ВЫРЕЗАЕТСЯ ПЕРЕД РАЗБОРОМ. Первая редакция искала `open`,
     за которым нет `=`, — и краснела на ВЕРНОМ `open={open}`: голое слово стоит
     там внутри фигурных скобок, как значение. Сначала убираем все `{…}` (с
     вложенностью), потом ищем АТРИБУТ. Окно фиксированной длины, а не «до первого
     `>`»: в пропах живут стрелочные функции. */
  const stripBraces = (txt) => {
    let out = '', depth = 0;
    for (const ch of txt) {
      if (ch === '{') depth += 1;
      else if (ch === '}') depth = Math.max(0, depth - 1);
      else if (depth === 0) out += ch;
    }
    return out;
  };
  const guilty = [];
  for (const f of jsxFiles(SRC)) {
    const src = codeOf(f);
    for (const shell of SHELLS) {
      for (const m of src.matchAll(new RegExp(`<${shell}\\b`, 'g'))) {
        const tag = stripBraces(src.slice(m.index, m.index + 400));
        if (/\bopen\s*[/>\s]/.test(tag.replace(/^<\w+/, '')) && !/\bopen\s*=/.test(tag)) {
          guilty.push(`${f.slice(SRC.length)} → <${shell} open>`);
        }
      }
    }
  }
  assert.deepEqual(guilty, [],
    `открытость поверхности задана литералом — состояние невыразимо, и дисмисс залипает: ${guilty.join(', ')}`);
});

