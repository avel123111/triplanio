/** Файлы дерева `src/` с нужным расширением — периметр, в котором проверяемое
 *  могло бы всплыть вторым экземпляром.
 *
 *  ⚠️ САМИ ТЕСТЫ ИЗ ПЕРИМЕТРА ИСКЛЮЧЕНЫ, И ЭТО НЕ УДОБСТВО. Проверка ищет строки
 *  кода, а этот файл их ЦИТИРУЕТ — то есть без исключения он находил бы сам себя
 *  и краснел на собственном утверждении. Поймано трижды подряд (на `autoFocus`,
 *  на `transitionend`, на `setProperty`), поэтому вырезано ОДИН раз здесь, а не
 *  заплаткой в каждой проверке. Периметр — это продуктовый исходник. */
function filesWithExt(dir, ext, acc = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) filesWithExt(full, ext, acc);
    else if (name.endsWith(ext) && !/\.test\.[jt]sx?$/.test(name)) acc.push(full);
  }
  return acc;
}
const jsxFiles = (dir) => filesWithExt(dir, '.jsx');
const jsFiles = (dir) => filesWithExt(dir, '.js');
const cssFiles = (dir) => filesWithExt(dir, '.css');

/** Код без комментариев. ⚠️ Отдельная функция, а не `includes` по файлу: имя
 *  скина УПОМИНАЕТСЯ в прозе тех файлов, что о нём рассказывают (движок пикера
 *  объясняет, кто задаёт геометрию встроенному режиму), и грубый греп читал бы
 *  объяснение как второго носителя. Это ровно та же грабля, что уже поймана в
 *  `sentry.test.js`: проверять надо КОД, а не текст. */
const codeOf = (file) => readFileSync(file, 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, ' ')
  .replace(/(^|[^:])\/\/.*$/gm, '$1');

test('★★ роль «я экран» ставит ШОВ, и носитель у неё ОДИН', () => {
  /* ★ ЧТО ЗДЕСЬ ИЗМЕНИЛОСЬ (TRIP-494). Роль полноростной поверхности была
     записана ДВАЖДЫ и по-разному: у шторки классом `.sheet--full` (его вешал
     проп `full`), у панели редактора — самим фактом скина `.lp-sheet`. Два
     способа сказать одно — развилка, на которой третья поверхность объявит роль
     третьим способом и не получит ни краски, ни резерва под клавиатуру. Теперь
     способ один: обе просят `full` у шва, шов ставит признак, CSS адресует
     признак. Пиннится и то, и другое: что класса-двойника больше нет, и что
     признак производит РОВНО шов. */
  const classCarriers = jsxFiles(SRC).concat(cssFiles(SRC))
    .filter((f) => codeOf(f).includes('sheet--full')).map((f) => f.slice(SRC.length));
  assert.deepEqual(classCarriers, [],
    'класс-двойник роли вернулся: роль объявляется признаком семьи, а не именем скина');

  /* ⚠️ ИМЯ БЕЗ КАВЫЧЕК, И ЭТО НЕ ПРИДИРКА. Первая редакция искала литерал
     `'data-sheet-full'` в одинарных кавычках — и мутация «оболочка ставит признак
     сама» (`data-sheet-full=''` прямо в JSX) прошла ЗЕЛЁНОЙ: написание другое,
     нарушение то же. Проверяется имя, а не способ его записать. */
  const attrCarriers = jsxFiles(SRC)
    .filter((f) => /data-sheet-full/.test(codeOf(f))).map((f) => f.slice(SRC.length));
  assert.deepEqual(attrCarriers, ['components/ui/sheetShell.jsx'],
    'признак семьи обязан рождаться в шве: второй носитель = второй способ заявить роль');

  // Обе оболочки просят роль у шва — а не рисуют её сами.
  assert.match(codeOf(join(UI, 'PickerSheet.jsx')), /full=\{full\}/,
    'шторка пикера обязана проводить роль к шву, а не вешать класс');
  assert.match(codeOf(join(UI, 'LpSheet.jsx')), /<SheetSurface[^>]*\bfull\b/,
    'оболочка панелей редактора — та же полноростная поверхность, и роль у неё та же');
});

