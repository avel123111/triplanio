test('НИ ОДИН пикер не вешает текстовое поле-триггер на страницу', () => {
  // ★ ЧТО ИМЕННО ПИННИТСЯ И ПОЧЕМУ. Текстовое поле НА СТРАНИЦЕ, открывающее
  // шторку, тревожит саму страницу, и неизбежно: тап фокусирует его, платформа
  // поднимает клавиатуру, вьюпорт раскладки ужимается и браузер доскролливает
  // страницу к полю — ВСЁ ЭТО ДО того, как шторка появилась. Шторка накрывает уже
  // уехавшую страницу, на закрытии та возвращается. Симптом читается как «шторка
  // раздёргивает страницу», хотя внутри шторки не двигается ничего, и полный рост
  // против него бессилен: дёргается не она, а то, что под ней.
  // Прошлая редакция ЭТОГО ЖЕ ТЕСТА пинила обратное («триггер обязан быть
  // настоящим полем») — она закрепляла разбор симптома, принятый за причину.
  // Панели города и события (`.lp-sheet`) страницу не тревожили никогда просто
  // потому, что их открывают кликом по строке.
  const branchOf = (file, from, to) => {
    const src = readFileSync(file, 'utf8')
      .replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
    const a = src.indexOf(from);
    assert.ok(a >= 0, `ветка ${from} не найдена в ${file} — тест обязан читать то, что проверяет`);
    const b = src.indexOf(to, a);
    return src.slice(a, b > a ? b : undefined);
  };

  const engines = [
    ['Autocomplete', branchOf(join(UI, '../common/Autocomplete.jsx'), 'if (isPhone)', '<PickerSheet')],
    ['SearchSelect', branchOf(join(UI, 'SearchSelect.jsx'), 'const trigger =', ');')],
  ];

  for (const [name, branch] of engines) {
    assert.match(branch, /as="button"/,
      `${name}: триггер обязан быть КНОПКОЙ — у поля ввода клавиатура поднимается на СТРАНИЦЕ`);
    assert.ok(!/onFocus=/.test(branch),
      `${name}: открытие по фокусу возвращает поле-триггер вместе со всей его ценой`);
    // `value=`/`placeholder=` на триггере означали бы, что контрол снова `<input>`:
    // у кнопки нет ни того, ни другого, подпись приезжает детьми.
    assert.ok(!/\bvalue=/.test(branch), `${name}: у кнопки-триггера нет value — подпись идёт детьми`);
  }
});

test('директива вьюпорта и подъём vaul — ПАРА, и обе половины на месте', () => {
  // ★ ЭТО ОДНО РЕШЕНИЕ, РАЗНЕСЁННОЕ ПО ДВУМ ФАЙЛАМ, И ИМЕННО ПОЭТОМУ ОНО
  // РАЗЪЕДЕТСЯ МОЛЧА. Половины:
  //   `overlays-content`  — клавиатура ложится ПОВЕРХ, вьюпорт РАСКЛАДКИ не
  //     меняется, и страница под шторкой не перекладывается. Замер (390 px,
  //     клавиатура сжала видимое до 480): при `resizes-content` вся страница
  //     ехала 0..844 → 0..480 и возвращалась — шапка, тело и нижний док вместе;
  //     при `overlays-content` двигается ТОЛЬКО шторка.
  //   подъём vaul        — цена первой половины: низ приклеенного к низу шита
  //     сам над клавиатурой не встанет. `repositionInputs` (умолчание vaul)
  //     ставит ему `bottom` = высоте клавиатуры.
  // Вернуть `resizes-content`, оставив подъём, — это «улетающий шит» (подъём
  // станет вторым). Выключить подъём, оставив `overlays-content`, — это низ
  // формы под клавиатурой. Ни то, ни другое не даёт ни исключения, ни красного
  // теста, поэтому пара пиннится здесь.
  const html = readFileSync(fileURLToPath(new URL('../../../index.html', import.meta.url)), 'utf8');
  assert.match(html, /interactive-widget=overlays-content/,
    'директива вьюпорта: клавиатура обязана ложиться ПОВЕРХ, иначе страница под шторкой перекладывается');

  const seam = readFileSync(join(UI, 'sheetShell.jsx'), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
  assert.ok(!/repositionInputs=\{false\}/.test(seam),
    'шов не смеет выключать подъём ОПТОМ: приклеенный к низу шит поднимает vaul, и это единственное, что его поднимает');

  // Выключают его поштучно и только те, чья коробка УЖЕ равна видимой полосе.
  for (const [file, expect] of [['PickerSheet.jsx', /repositionInputs=\{!search\}/], ['LpSheet.jsx', /repositionInputs=\{false\}/]]) {
    assert.match(readFileSync(join(UI, file), 'utf8'), expect,
      `${file}: полноэкранная поверхность обязана отказаться от подъёма — для неё он второй`);
  }
});

test('поверхность реагирует ТОЛЬКО на СВОЮ клавиатуру', () => {
  // ★ ЦЕНА ГЛОБАЛЬНОГО ФЛАГА, ЗАМЕРЕННАЯ НА УСТРОЙСТВЕ. `useKeyboardOpen()` —
  // признак документа: «клавиатура где-то поднята». `PeekSheet` (трёхдетентный
  // шит над картой в планировщике и редакторе маршрута) считал его СВОИМ и на
  // любую клавиатуру прыгал на верхний детент, а заодно пересчитывал детенты от
  // сжатой видимой области. Правило писалось, когда поле ввода жило ВНУТРИ шита,
  // и тогда «открыта» и «моя» совпадали.
  // Поле уехало в шторку, которая ложится ПОВЕРХ, — и шит стал дёргаться от
  // ЧУЖОЙ клавиатуры. Снаружи это «экран позади шторки раздёргивается и
  // поднимается»; четыре захода правили шторку и не могли этого вылечить,
  // потому что двигалась не она.
  // Предикат — владение фокусом: клавиатуру физически поднимает сфокусированное
  // поле. Пиннится ОБА места: детент и пересчёт вьюпорта — второе двигает шит,
  // даже не трогая первое.
  const src = readFileSync(join(UI, 'PeekSheet.jsx'), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

  assert.ok(!/\bindex\s*=\s*keyboard\s*\?/.test(src),
    'детент не смеет зависеть от ГОЛОГО флага документа — только от своей клавиатуры');
  assert.match(src, /keyboardMine\s*=\s*keyboardOpen\s*&&\s*isMine\(/,
    'признак «клавиатура моя» = открыта И фокус в моём поддереве');
  assert.match(src, /index\s*=\s*keyboardMine\s*\?/,
    'на верхний детент поднимает СВОЯ клавиатура');

  // Вторая половина: `vh`/`vTop` под чужой клавиатурой не обновляются. Детенты —
  // доли от `vh`, поэтому одна усадка меняет и высоту шита, и его положение.
  // Границу берём ПОСЛЕ начала среза: `useLayoutEffect` стоит ещё и в импорте, и
  // поиск от нуля давал ПУСТУЮ строку — тест зеленел бы, ничего не проверив.
  const from = src.indexOf('const measure =');
  assert.ok(from > 0, 'measure не найден — тест обязан читать то, что проверяет');
  const measure = src.slice(from, src.indexOf('useLayoutEffect(', from));
  assert.ok(measure.includes('isMine('),
    'пересчёт вьюпорта обязан спрашивать, чья клавиатура: иначе шит едет и без смены детента');
});

test('каретку ставит ШТАТНЫЙ хук диалога, а не ручная машинерия', () => {
  const surface = readFileSync(join(UI, 'PickerSheet.jsx'), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
  // У задачи «поле в фокусе при открытии» есть штатный хук Radix. vaul гасит
  // автофокус диалога по умолчанию, и, пока шов не пробрасывал хук, поверх
  // подавления фокус ставился руками — эффектом, потом синхронным коммитом,
  // потом ещё и повторной попыткой на кадре. Три захода воевали с настройкой,
  // которую достаточно было не включать.
  assert.ok(surface.includes('onOpenAutoFocus='), 'фокус при открытии — штатный хук, не эффект');
  assert.ok(!/useEffect|useLayoutEffect|requestAnimationFrame|setTimeout/.test(surface),
    'ручная постановка фокуса вернулась — значит хук снова обходят, а не используют');

  // Хук обязан ЗАБРАТЬ решение у Radix: иначе фокус уйдёт первому подходящему
  // элементу шторки, а первый там — крестик закрытия.
  // ⚠️ Срез ограничен СВОИМ обработчиком: сквозная регулярка дотягивалась до
  // `preventDefault()` соседнего `onCloseAutoFocus` и зеленела, даже когда из
  // этого хука его убрали (поймано мутацией).
  const openHook = surface.slice(surface.indexOf('onOpenAutoFocus='), surface.indexOf('onCloseAutoFocus='));
  assert.ok(openHook.includes('preventDefault()'),
    'без этого Radix отдаст фокус первому подходящему элементу — крестику закрытия');
});

