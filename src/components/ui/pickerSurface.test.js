/** Полноэкранная поверхность приложения. Их ДВЕ — шторка пикера с поиском и
 *  оболочка панелей редактора, — и это одна и та же вещь, поэтому и субъект в
 *  CSS один: признак роли, который ставит шов (TRIP-494). До сведения субъекта
 *  было два (`.sheet--full` и `.lp-sheet`), и каждое общее правило приходилось
 *  перечислять поимённо — то есть помнить обе. */
const FULL_SURFACES = ['[data-sheet-full]'];

/** Правила, объявляющие КОРОБКУ (`top`/`bottom`/`height`) у названного субъекта.
 *  Субъект — точное совпадение части селектора: `.lp-sheet > .lp` это ПОТОМОК,
 *  у него своя коробка (`height: 100%`) и к вьюпорту она отношения не имеет.
 *  Комментарии снимаются до разбора: маркеры обходов сами содержат `{…}`. */
function boxRules(css, subjects) {
  const bare = css.replace(/\/\*[\s\S]*?\*\//g, '');
  return [...bare.matchAll(/([^{}]+)\{([^{}]*)\}/g)]
    .map(([, sel, body]) => ({ sel: sel.trim(), body }))
    .filter((r) => r.sel.split(',').some((s) => subjects.includes(s.trim()))
      && /(^|[;{\s])(top|bottom|height)\s*:/.test(r.body));
}

test('коробка ПОЛНОЭКРАННОЙ поверхности НЕ зависит от клавиатуры, и правило ОДНО', () => {
  const css = readFileSync(join(SRC, 'design/app.css'), 'utf8');
  const rules = boxRules(css, FULL_SURFACES);

  // ★ ЕДИНСТВЕННОСТЬ — ЭТО И ЕСТЬ ПРОВЕРЯЕМОЕ. Поверхностей две, и они уже
  // разъезжались: коробку от визуального вьюпорта получила только шторка пикера,
  // а панель редактора осталась на раскладке и на iOS уходила за оба края
  // видимой полосы (замер: панель 0→844 при видимом 120→600, поле в её низу — под клавиатурой).
  assert.equal(rules.length, 1,
    `коробку полноэкранной поверхности объявляет ровно одно правило; найдено ${rules.length}: ${rules.map((r) => r.sel).join(' | ')}`);

  const [rule] = rules;
  assert.equal(rule.sel, FULL_SURFACES[0],
    'коробку берёт СЕМЬЯ по признаку роли: перечисление скинов поимённо и есть та форма, из которой они разъезжаются');

  // ⚠️ НАЗВАНИЕ ЭТОГО ТЕСТА РАНЬШЕ ГОВОРИЛО «от ВИЗУАЛЬНОГО вьюпорта» — то есть
  // ПРОТИВОПОЛОЖНОЕ тому, что он проверяет (`height: 100dvh` — это раскладочный).
  assert.ok(!/--vv-h|--vv-top/.test(rule.body),
    'высота коробки от клавиатуры пересчитывает процентный трансформ въезда — каретка едет вместе с поверхностью');
  assert.match(rule.body, /height:\s*100dvh/, 'коробка — вьюпорт раскладки и только он');

  const bareCss = css.replace(/\/\*[\s\S]*?\*\//g, '');
  assert.match(bareCss, /padding-bottom:\s*var\(--kb-h/,
    'клавиатура обязана резервировать место внутри неподвижной коробки, у скроллера');
});

test('★★ КРАСКА у полноростной поверхности ОДНА, и это цвет страницы', () => {
  /* ★ ЧТО ЛОМАЛОСЬ (TRIP-494). Полноростных поверхностей две, и красились они
     РАЗНО: шторка пикера — `--surface` (цвет карточки), панель редактора — `--bg`
     (цвет страницы). Замер на 390x844 в обеих темах: в светлой разница едва
     заметна, в тёмной это ступень, а не оттенок — два полноэкранных экрана
     одного приложения разного цвета.
     Цена была не только в разнобое: карточки ВНУТРИ шторки красятся `--surface`,
     то есть совпадали с ней БАЙТ-В-БАЙТ (замер на `.te-add-type`: тот же цвет,
     что у поверхности) и держались на одной рамке.
     Правильный ответ — цвет СТРАНИЦЫ: полноростная поверхность это экран, а не
     карточка над экраном; так уже красятся панель (`.lp`) и окно (`.dlg`). */
  const css = readFileSync(join(SRC, 'design/app.css'), 'utf8');
  const bare = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const painters = [...bare.matchAll(/([^{}]+)\{([^{}]*)\}/g)]
    .map(([, sel, body]) => ({ sel: sel.trim(), body }))
    .filter((r) => r.sel.includes('[data-sheet-full]') && /(^|[;{\s])background\s*:\s*var\(/.test(r.body));
  assert.equal(painters.length, 1,
    `краску полноростной поверхности объявляет ровно одно правило; найдено ${painters.length}: ${painters.map((r) => r.sel).join(' | ')}`);
  assert.match(painters[0].sel, /::before/,
    'краска — отдельный слой: у шторки пикера она ЕДЕТ без содержимого, и это её единственный способ ехать');
  assert.match(painters[0].body, /background:\s*var\(--bg\)/,
    'полноростная поверхность — экран, и красится цветом страницы, как панель и окно');

  /* ★ ВТОРОГО КРАСИЛЬЩИКА НЕТ. Карточка панели внутри полноростной поверхности
     обязана краску ОТДАТЬ: два слоя одного факта разъезжаются молча — ровно так
     и разъехались фоны шторки и панели. */
  assert.match(bare, /\.lp-sheet > \.lp \{[^}]*background:\s*transparent/,
    'карточка панели красит поверх краски семьи = второй владелец одного факта');
});

