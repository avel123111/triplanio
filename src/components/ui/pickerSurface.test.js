test('★★ ховер плиток вида гейтнут по УКАЗАТЕЛЮ — иначе на тач видно две активные', () => {
  // ★ ЧТО ВИДЕЛ ЧЕЛОВЕК. На тач `:hover` ЗАЛИПАЕТ на последнем нажатом элементе
  // до следующего тапа. Плитка, по которой только что ткнули, оставалась в
  // brand-рамке РЯДОМ с настоящей выбранной (`aria-pressed`): две активные из
  // четырёх, и какая выбрана — непонятно.
  /* ⚠️ БЕЗ КОММЕНТАРИЕВ. Первый поиск нашёл не правило, а СОБСТВЕННЫЙ маркер
     обхода в комментарии app.css — там селектор упомянут прозой, — и обход
     скобок честно доложил, что вокруг ничего нет.
     ⚠️⚠️ И САМУ СТРОКУ МАРКЕРА ЗДЕСЬ ЦИТИРОВАТЬ НЕЛЬЗЯ: гард 2p собирает маркеры
     из ДОБАВЛЕННЫХ строк всего периметра, включая тесты, и цитата становится для
     него настоящим маркером — либо холостым, либо неразобранным. Наступлено
     трижды за одну задачу; поэтому здесь ни одного литерала. */
  const css = readFileSync(join(SRC, 'design/app.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, ' ');
  const i = css.indexOf('.te-add-type:hover');
  assert.ok(i > 0, 'правило ховера плиток не найдено — тест обязан читать то, что проверяет');
  /* ⚠️ ОБХОД СКОБОК, А НЕ «БЛИЖАЙШИЙ @media ВЫШЕ». Первая редакция искала
     `lastIndexOf('@media')` и мерила вложенность самодельной эвристикой — и
     МОЛЧА проходила мутацию «снять гейт»: выше по файлу медиа-запросов много, и
     любой из них годился. Тест, не краснеющий на мутации, не тест. */
  const stack = [];
  let from = 0;
  for (let k = 0; k < i; k++) {
    if (css[k] === '{') { stack.push(css.slice(from, k)); from = k + 1; }
    else if (css[k] === '}') { stack.pop(); from = k + 1; }
    else if (css[k] === ';') from = k + 1;
  }
  const enclosing = stack.filter((pre) => pre.includes('@media')).join(' ');
  assert.match(enclosing, /hover:\s*hover/,
    'гейт обязан быть по НАЛИЧИЮ курсора: на тач ховер залипает и читается как выбор');
});
