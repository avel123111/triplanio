// @ts-check
import { useLayoutEffect, useRef, useState } from 'react';
import { Sheet } from '@/components/ui/Sheet';

/**
 * PickerSheet — МОБИЛЬНАЯ ПОВЕРХНОСТЬ ПИКЕРА (TRIP-484 §4).
 *
 * В приложении два движка выбора и они останутся двумя: `SearchSelect` знает
 * закрытый список и фильтрует его на клиенте, `Autocomplete` спрашивает сервер
 * по мере ввода. Логика данных у них разная по существу. А вот ПОВЕРХНОСТЬ на
 * телефоне у них одна и та же, и раньше её не было ни у одного: `SearchSelect`
 * собирал шторку сам, `Autocomplete` на телефоне вообще оставался якорным
 * попапом, привязанным к полю посреди скроллящегося экрана.
 *
 * Здесь эта поверхность объявлена один раз, вместе с ЕДИНСТВЕННЫМ правилом,
 * которое её задаёт:
 *
 *   ЕСТЬ ПОИСК  -> шторка во весь рост, поле ПРИШПИЛЕНО сверху, скроллит только
 *                  лист. Высота больше не зависит от содержимого, поэтому
 *                  фильтрация и клавиатура перестают двигать коробку.
 *   НЕТ ПОИСКА  -> шторка по содержимому (как была). Клавиатуры нет, менять
 *                  высоте нечего, а три роли во весь экран - модальный экран
 *                  ради трёх строк.
 *
 * Правило живёт ЗДЕСЬ, а не в двух движках: записанное дважды, оно разъедется
 * на первой же правке, и разъедется молча - у поверхности нет теста, который бы
 * это поймал. Скин полного роста - `.sheet--full` (app.css, там же разбор,
 * почему порядок правил в файле имеет значение).
 *
 * Поиск передаётся УЗЛОМ, а не строкой-плейсхолдером: у двух движков это разные
 * поля (контролируемый фильтр против поля с кольцом загрузки и очисткой), и
 * поверхности незачем про это знать. Она отвечает за геометрию, не за ввод.
 *
 * Шторка над шторкой (пикер города из окна события) работает без единого слова
 * здесь: вложенность разбирает шов `ui/sheetShell` по факту дерева.
 *
 * ★★ ФОКУС ПОВЕРХНОСТЬ НЕ СТАВИТ — НИ ХУКОМ, НИ РУКАМИ, И ЭТО РЕШЕНИЕ, А НЕ ДЫРА.
 * На тач-платформе клавиатуру поднимает ТОЛЬКО настоящий тап в настоящее
 * текстовое поле. Программный `focus()` каретку поставит, а клавиатуру — нет; а
 * поставленный посреди въезда vaul он вдобавок рисует каретку ОТДЕЛЬНО от поля
 * (WebKit), и она догоняет его по кадрам. Так это и выглядело на устройстве.
 * Поэтому фокус здесь не переносится, а НЕ ТЕРЯЕТСЯ: поле, по которому тапнули,
 * само едет в шторку (`usePickerFlight` ниже) — тап нативный, каретка родилась в
 * этом узле и осталась в нём. Переносить нечего.
 * Там, где полю не в чем прилететь, — `SearchSelect`: его триггер показывает
 * СОБРАННОЕ значение (флаг, код, название), полем такое не нарисовать, значит
 * поле поиска живёт внутри шторки и его тапают, ровно как в системных пикерах.
 * Это свойство триггера, а не пробел поверхности.
 * vaul гасит автофокус диалога своим умолчанием, поэтому «не ставить» — это
 * ничего не передавать: ни `onOpenAutoFocus`, ни `onCloseAutoFocus`.
 * ДЕСКТОП НЕ ЗАТРОНУТ: там пикер — попап, а не эта поверхность, и своё
 * `autoFocus` он держит сам.
 */

/**
 * ПЕРЕЛЁТ ПОЛЯ — ОДИН ДОМ ПРАВИЛА.
 *
 * Поле у пикера ОДНО. Тапнул по нему в строке — клавиатуру поднял НАТИВНЫЙ тап,
 * каретка родилась в этом же узле, а сам узел поехал к верху экрана и сел в слот
 * шторки. Второго поля нет, значит нет и задач, которые мы решали пять заходов:
 * ловить жест синхронным коммитом, переносить фокус, объяснять каретке, где
 * встать. Их не возникает.
 *
 * ★ ЛЕТИТ РАСКЛАДКОЙ, А НЕ ТРАНСФОРМОМ. Трансформ уводит элемент в композитный
 * слой, а каретку WebKit рисует мимо него — отсюда был прыжок «встала в поле,
 * улетела, опять встала». Скин полёта — `.ss-fly` (app.css), там же разбор.
 *
 * ★ ОБЕ РАМКИ ЗАМЕРЕНЫ, А НЕ ЗАДАНЫ ЧИСЛАМИ. Начальная снимается В ЖЕСТЕ, до
 * открытия (`capture`): после него поле уже `fixed`, и мерить будет нечего.
 * Конечная — рамка ПУСТОГО слота `.ss-search` в шторке, то есть настоящее место,
 * а не подогнанная константа: подвинется вёрстка шторки — перелёт поедет за ней.
 *
 * ★ ОБРАТНЫЙ ПУТЬ ТОЖЕ ПЕРЕЛЁТ. Класс снимается не на закрытии, а по
 * `transitionend`: иначе поле не возвращается, а телепортируется в строку.
 */
export function usePickerFlight(open) {
  const flyRef = useRef(/** @type {any} */ (null));
  const slotRef = useRef(/** @type {any} */ (null));
  const fromRef = useRef(/** @type {any} */ (null));
  const [closing, setClosing] = useState(false);

  /** Снять стартовую рамку — ТОЛЬКО пока поле ещё в потоке строки. */
  const capture = () => { fromRef.current = flyRef.current?.getBoundingClientRect() || null; };

  useLayoutEffect(() => {
    const el = flyRef.current;
    if (!el) return undefined;
    const put = (r) => {
      if (!r) return;
      el.style.setProperty('--fly-top', `${Math.round(r.top)}px`);
      el.style.setProperty('--fly-left', `${Math.round(r.left)}px`);
      el.style.setProperty('--fly-right', `${Math.round(window.innerWidth - r.right)}px`);
    };
    if (open) {
      // Стартовая рамка — ДО первой отрисовки: layout-фаза идёт перед кадром,
      // поэтому поле не мигает в левом верхнем углу.
      put(fromRef.current);
      // Цель — слот шторки; он появляется вместе с порталом, то есть кадром позже.
      const id = requestAnimationFrame(() => put(slotRef.current?.getBoundingClientRect()));
      return () => cancelAnimationFrame(id);
    }
    if (!fromRef.current) return undefined;
    setClosing(true);
    put(fromRef.current);
    const done = () => setClosing(false);
    el.addEventListener('transitionend', done, { once: true });
    return () => el.removeEventListener('transitionend', done);
  }, [open]);

  return { flyRef, slotRef, capture, flying: open || closing };
}

/**
 * @param {{ open: boolean, onOpenChange: (v: boolean) => void, title?: any,
 *   search?: any, children?: any }} p
 */
export function PickerSheet({ open, onOpenChange, title, search = null, children }) {
  return (
    <Sheet
      open={open}
      onOpenChange={onOpenChange}
      title={title}
      className={search ? 'sheet--full' : ''}
    >
      {search}
      {children}
    </Sheet>
  );
}

export default PickerSheet;
