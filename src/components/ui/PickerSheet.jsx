// @ts-check
import { useEffect, useRef } from 'react';
import { flushSync } from 'react-dom';
import { Sheet } from '@/components/ui/Sheet';

/**
 * PickerSheet — МОБИЛЬНАЯ ПОВЕРХНОСТЬ ПИКЕРА (TRIP-484 §4).
 *
 * В приложении два движка выбора и они останутся двумя: `SearchSelect` знает
 * закрытый список и фильтрует его на клиенте, `Autocomplete` спрашивает сервер
 * по мере ввода. Логика данных у них разная по существу. А вот ПОВЕРХНОСТЬ на
 * телефоне у них одна и та же, и раньше её не было ни у одного: `SearchSelect`
 * собирал шторку сам, `Autocomplete` на телефоне вообще оставался якорным
 * попапом, привязанным к полю посреди скроллящегося экрана.
 *
 * Здесь эта поверхность объявлена один раз, вместе с ЕДИНСТВЕННЫМ правилом,
 * которое её задаёт:
 *
 *   ЕСТЬ ПОИСК  -> шторка во весь рост, поле ПРИШПИЛЕНО сверху, скроллит только
 *                  лист. Высота больше не зависит от содержимого, поэтому
 *                  фильтрация и клавиатура перестают двигать коробку.
 *   НЕТ ПОИСКА  -> шторка по содержимому (как была). Клавиатуры нет, менять
 *                  высоте нечего, а три роли во весь экран - модальный экран
 *                  ради трёх строк.
 *
 * Правило живёт ЗДЕСЬ, а не в двух движках: записанное дважды, оно разъедется
 * на первой же правке, и разъедется молча - у поверхности нет теста, который бы
 * это поймал. Скин полного роста - `.sheet--full` (app.css, там же разбор,
 * почему порядок правил в файле имеет значение).
 *
 * Поиск передаётся УЗЛОМ, а не строкой-плейсхолдером: у двух движков это разные
 * поля (контролируемый фильтр против поля с кольцом загрузки и очисткой), и
 * поверхности незачем про это знать. Она отвечает за геометрию, не за ввод.
 *
 * Шторка над шторкой (пикер города из окна события) работает без единого слова
 * здесь: вложенность разбирает шов `ui/sheetShell` по факту дерева.
 *
 * ★★ ФОКУС СТАВИТСЯ РОВНО ОДИН РАЗ И РОВНО В ЖЕСТЕ. На тач-платформе клавиатуру
 * поднимает только `focus()`, вызванный внутри пользовательского жеста, в поле,
 * которое уже в DOM. Поэтому вход один — тап, и он синхронный (`usePickerFocus`
 * ниже). Фокус ПОСЛЕ жеста — эффектом, `onOpenAutoFocus`, следующим кадром —
 * даёт каретку без клавиатуры; проверено на устройстве.
 * ДЕСКТОП НЕ ЗАТРОНУТ: там пикер — попап, а не эта поверхность.
 *
 * ★★ «ПОЛЕ УЛЕТАЕТ НАВЕРХ» — ИДЕЯ ЖИВА, НО НЕ В ТОМ ВИДЕ, В КАКОМ ПРОБОВАЛИ.
 * Поле остаётся полем, тап поднимает клавиатуру нативно, а узел едет к верху
 * экрана. На устройстве конструкция развалилась ДВАЖДЫ, и оба раза по одной
 * причине: поле города живёт ВНУТРИ `PeekSheet`, а тот `position: fixed` +
 * `transform: translateY(var(--sheet-y))`.
 *   1. ТРАНСФОРМИРОВАННЫЙ ПРЕДОК СТАНОВИТСЯ КОНТЕЙНЕРОМ ДЛЯ `position: fixed`.
 *      Рамка снималась `getBoundingClientRect()` (координаты вьюпорта), а `top`
 *      летящего поля отсчитывался от коробки `PeekSheet`, сдвинутой на
 *      `--sheet-y`. Поле уезжало мимо экрана — «в шторке нет инпута».
 *   2. КЛАВИАТУРА СТАНОВИЛАСЬ «СВОЕЙ» ДЛЯ `PeekSheet`: летящее поле остаётся его
 *      потомком, где бы его ни рисовали, и предикат владения фокусом отвечает
 *      ПРАВИЛЬНО. Шит уходил на верхний детент — «шит улетает в небо».
 * Портал не спасает: перенос узла в `document.body` снимает фокус, а с ним и
 * клавиатуру — то есть ровно то, ради чего перелёт затевался.
 * Опровергнута КОНСТРУКЦИЯ, а не замысел; его настоящая цена — два новых
 * понятия (координаты в системе содержащего блока + «узел, поднятый в оверлей,
 * перестал быть моим содержимым» у `PeekSheet`), то есть перелёт стоит ДОРОЖЕ,
 * чем поле внутри поверхности. Поэтому сейчас поле поиска живёт ВНУТРИ шторки.
 *
 */

/**
 * ДИСЦИПЛИНА ФОКУСА У ПИКЕРА — ОДИН ДОМ НА ОБА ДВИЖКА.
 *
 * Правило целиком: «поверхность открывается и её поле получает фокус В ОДНОМ
 * ЖЕСТЕ; выбор сделан — поле отпускает фокус». Оно платформенное, а не про
 * данные, поэтому принадлежит ПОВЕРХНОСТИ, а не тому, откуда берутся строки.
 * Движка два (`SearchSelect` — закрытый список, `Autocomplete` — запрос к
 * серверу), и записать это правило у каждого значило бы завести второй экземпляр
 * — ровно тот дубль, который в этой же ветке схлопывался у `CityPicker` и у
 * кнопки-в-облике-поля. Здесь оно одно, движки его ЗОВУТ.
 *
 * ★ ПОЧЕМУ «В ОДНОМ ЖЕСТЕ» — НЕСУЩЕЕ. WebKit (а на iOS это ЛЮБОЙ браузер,
 * включая Chrome) поднимает клавиатуру, только если `focus()` вызван внутри
 * пользовательского жеста и поле УЖЕ в DOM. Фокус после жеста — эффектом,
 * штатным хуком открытия, следующим кадром — даёт КАРЕТКУ БЕЗ КЛАВИАТУРЫ;
 * проверено на устройстве, каретка появлялась и ввода за ней не было.
 * `flushSync` тут не обход React, а его штатная дверь для событий, где важен
 * порядок относительно браузера: без него поля в момент тапа ещё нет.
 *
 * ★ ВХОД У ПОВЕРХНОСТИ РОВНО ОДИН — ТАП. Второй («открыться на монтировании»)
 * существовал и НЕ РАБОТАЛ: поле живёт в портале vaul, портал монтируется не в
 * том же кадре, и фокусить в layout-фазе ещё нечего — а когда поле появится,
 * жест уже кончился. Он удалён, а не подпёрт: правило «на телефоне шторка не
 * открывает себя сама» живёт в движке (`common/Autocomplete`).
 *
 * ★ ОТПУСКАТЬ ФОКУС ОБЯЗАНЫ ТОЖЕ МЫ — но НЕ ЗДЕСЬ, а на закрытии поверхности
 * (разбор у `PickerSheet` ниже). Раньше это делал `release()` из этого хука,
 * который звал движок в `pick()`: замер показал, что так накрыта ОДНА дверь из
 * четырёх. Отпускание переехало к переходу `open -> false` и накрыло все.
 * Почему отпускать обязаны МЫ: иначе клавиатура гаснет тогда, когда vaul снимет
 * портал с выходной анимацией, а это деталь реализации, и она РАЗНАЯ у обычного
 * и вложенного корня — из-за неё один и тот же пикер вёл себя по-разному на двух
 * экранах.
 *
 */
/**
 * ⚠️ ТИП ВОЗВРАТА ОБЪЯВЛЕН ЯВНО, И ЭТО НЕ УКРАШЕНИЕ. В JS-файле TypeScript не
 * ругается на обращение к НЕСУЩЕСТВУЮЩЕМУ свойству ВЫВЕДЕННОГО объекта — это
 * его штатная поблажка динамическим паттернам. Ровно из-за неё удалённый отсюда
 * `release` продолжал вызываться в `SearchSelect` и падал у каждого на клике по
 * пункту: ни eslint, ни `tsc` его не видели (Sentry TRIPLANIO-33). С объявленным
 * типом это ошибка компиляции — проверено мутацией.
 * @returns {{ searchRef: any, openInGesture: (setOpen: any) => void }}
 */
export function usePickerFocus() {
  const searchRef = useRef(/** @type {any} */ (null));
  const focus = () => searchRef.current?.focus({ preventScroll: true });

  return {
    /** Ссылка на поле поиска ВНУТРИ шторки. */
    searchRef,
    /** Открыть поверхность и сфокусировать её поле, не выходя из жеста. */
    openInGesture: (setOpen) => { flushSync(() => setOpen(true)); focus(); },
  };
}

/**
 * ★★ ЗАКРЫТИЕ СНИМАЕТ ФОКУС — ЗДЕСЬ, А НЕ У ВЫЗЫВАТЕЛЯ. ЗАМЕР, НЕ ОСТОРОЖНОСТЬ.
 *
 * Клавиатуру физически держит СФОКУСИРОВАННОЕ ПОЛЕ. Значит «шторка закрывается»
 * и «клавиатура уходит» — одно событие, и снять фокус обязан тот, кто знает про
 * закрытие. Знает поверхность.
 *
 * Раньше блюр стоял у движка, в `pick()`. Прогон на живом компоненте (витрина
 * /kit, покадрово) показал цену: закрытий у шторки ЧЕТЫРЕ — выбор, Esc, тап
 * мимо, свайп вниз, — и блюр накрывал ровно одно. На остальных поле оставалось
 * в фокусе ВСЕ 500 мс выходной анимации и уходило из DOM на 543-м мс. Полсекунды
 * из жалобы «шит уехал, а клавиатура через полсекунды» — это ровно оно.
 *
 * `useEffect` на переходе, а не обработчик: обработчик пришлось бы вешать на
 * каждую из четырёх дверей, то есть завести правило четырежды. Переход
 * `open -> false` один, какой бы дверью его ни вызвали.
 *
 * Блюрим ТОЛЬКО СВОЁ (`contains`): иначе шторка сбивала бы фокус, который Radix
 * штатно возвращает на триггер, — а тот живёт на странице, вне поверхности.
 *
 * @param {{ open: boolean, onOpenChange: (v: boolean) => void, title?: any,
 *   search?: any, children?: any }} p
 */
export function PickerSheet({ open, onOpenChange, title, search = null, children }) {
  const boxRef = useRef(/** @type {any} */ (null));
  useEffect(() => {
    if (open) return;
    const el = /** @type {any} */ (document.activeElement);
    if (el && boxRef.current?.contains(el) && typeof el.blur === 'function') el.blur();
  }, [open]);

  return (
    <Sheet
      open={open}
      onOpenChange={onOpenChange}
      title={title}
      className={search ? 'sheet--full' : ''}
      contentRef={boxRef}
    >
      {search}
      {children}
    </Sheet>
  );
}

export default PickerSheet;
