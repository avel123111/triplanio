// @ts-check
import { useEffect, useRef } from 'react';
import { flushSync } from 'react-dom';
import { Sheet } from '@/components/ui/Sheet';
/**
 * PickerSheet — МОБИЛЬНАЯ ПОВЕРХНОСТЬ ПИКЕРА (TRIP-484 §4).
 *
 * Движка выбора два и они останутся двумя: `SearchSelect` фильтрует закрытый
 * список на клиенте, `Autocomplete` спрашивает сервер. Логика данных у них
 * разная по существу — поверхность на телефоне одна и та же, и живёт здесь.
 *
 * ЕДИНСТВЕННОЕ ПРАВИЛО ГЕОМЕТРИИ:
 *   есть поиск -> шторка во весь рост, поле пришпилено сверху, скроллит лист;
 *   нет поиска  -> шторка по содержимому (три роли во весь экран — модальный
 *                  экран ради трёх строк).
 * Скин полного роста — `.sheet--full` (app.css, там же разбор анимации).
 * Поиск передаётся УЗЛОМ: у двух движков это разные поля, а поверхность отвечает
 * за геометрию, не за ввод.
 *
 * ★ ФОКУС СТАВИТСЯ РОВНО В ЖЕСТЕ. WebKit (а на iOS это любой браузер) поднимает
 * клавиатуру только на `focus()` внутри пользовательского жеста, в поле, которое
 * уже в DOM. Фокус после жеста — эффектом, `onOpenAutoFocus`, следующим кадром —
 * даёт каретку без клавиатуры. Отсюда синхронный `openInGesture` ниже.
 *
 * ⚠️ «ПОЛЕ УЛЕТАЕТ НАВЕРХ» ЗДЕСЬ НЕ РАБОТАЕТ, И ЭТО СВОЙСТВО ДЕРЕВА. Поле города
 * живёт внутри `PeekSheet`, а тот `position: fixed` + `transform`. Значит (а) он
 * становится контейнером для `position: fixed` — рамка из
 * `getBoundingClientRect()` уводит поле мимо экрана; (б) он справедливо считает
 * клавиатуру своей — летящее поле остаётся его потомком. Портал не спасает:
 * перенос узла снимает фокус. Цена замысла — два новых понятия, поэтому поле
 * поиска живёт ВНУТРИ шторки, а в строке стоит триггер.
 *
 * Шторка над шторкой работает без единого слова здесь: вложенность разбирает
 * шов `ui/sheetShell` по факту дерева.
 */

/**
 * ⚠️ ТИП ВОЗВРАТА ОБЪЯВЛЕН ЯВНО, И ЭТО НЕ УКРАШЕНИЕ. В JS-файле TypeScript не
 * ругается на обращение к несуществующему свойству ВЫВЕДЕННОГО объекта. Из-за
 * этого удалённый отсюда `release` продолжал вызываться в `SearchSelect` и падал
 * у каждого на клике по пункту (Sentry TRIPLANIO-33): его не видели ни eslint,
 * ни `tsc`. С объявленным типом это ошибка компиляции — проверено мутацией.
 * @returns {{ searchRef: any, openInGesture: (setOpen: any) => void }}
 */
export function usePickerFocus() {
  const searchRef = useRef(/** @type {any} */ (null));
  const focus = () => searchRef.current?.focus({ preventScroll: true });

  return {
    /** Ссылка на поле поиска ВНУТРИ шторки. */
    searchRef,
    /** Открыть поверхность и сфокусировать её поле, не выходя из жеста. */
    openInGesture: (setOpen) => { flushSync(() => setOpen(true)); focus(); },
  };
}

/**
 * `full` — «поиск у меня ВНУТРИ, а не в слоте». Правило геометрии не меняется
 * («есть поиск -> полный рост»), меняется способ его заявить: поверхность с
 * НЕСКОЛЬКИМИ фазами (композер города: найти город -> выбрать вид точки) не может
 * отдать поле в отдельный слот — на второй фазе поля нет вовсе, а коробка обязана
 * остаться той же. Сжать её между фазами нельзя: меняющаяся высота коробки — это
 * ровно тот дефект, ради которого полный рост и заведён.
 *
 * ЗАКРЫТИЕ СНИМАЕТ ФОКУС — ЗДЕСЬ, А НЕ У ВЫЗЫВАТЕЛЯ. Клавиатуру держит
 * сфокусированное поле, значит «шторка закрывается» и «клавиатура уходит» — одно
 * событие, и знает про него поверхность. Дверей у закрытия ЧЕТЫРЕ (выбор, Esc,
 * тап мимо, свайп); пока правило стояло у движка в `pick()`, оно накрывало одну,
 * и на остальных поле оставалось в фокусе все 500 мс выезда — это и была
 * «клавиатура отстаёт от шторки». `useEffect` на переходе, а не обработчик:
 * переход один, обработчиков пришлось бы вешать четыре. Блюрим только СВОЁ
 * поддерево (`contains`) — фокус, возвращённый Radix на триггер, не наш.
 *
 * @param {{ open: boolean, onOpenChange: (v: boolean) => void, title?: any,
 *   search?: any, full?: boolean, children?: any }} p
 */
export function PickerSheet({ open, onOpenChange, title, search = null, full = false, children }) {
  const boxRef = useRef(/** @type {any} */ (null));
  useEffect(() => {
    if (open) return;
    const el = /** @type {any} */ (document.activeElement);
    if (el && boxRef.current?.contains(el) && typeof el.blur === 'function') el.blur();
  }, [open]);

  return (
    <Sheet
      open={open}
      onOpenChange={onOpenChange}
      title={title}
      className={(search || full) ? 'sheet--full' : ''}
      contentRef={boxRef}
    >
      {search}
      {children}
    </Sheet>
  );
}

export default PickerSheet;
