// ОДНА дверь для всех CTA неавторизованной зоны: куда ведёт кнопка, что она
// сообщает аналитике и как ведёт себя клик (TRIP-445, PR 7).
//
// ── ЧТО БЫЛО ────────────────────────────────────────────────────────────────
// Шесть кнопок одного смысла («иди в продукт»), и каждая своя:
//   • `const APP_URL = '/login'`                             — ЧЕТЫРЕ копии
//   • `isAuthenticated ? '/trips' : withVisitCampaign(…)`    — ТРИ копии
//   • `e.preventDefault(); track(…); nav(target)`            — ЧЕТЫРЕ копии
// с РАЗНЫМ содержимым события: герой слал `{location:'hero'}` без страницы,
// вторая кнопка героя не слала ничего, шапка и оба пункта бургера — тоже
// ничего. То есть верхние ступени воронки не считались вовсе, а нижние не
// различались между лендингом и демо. Это не «забыли дописать»: это следствие
// того, что контракт события заполнялся руками в шести местах.
//
// ── ЧТО СТАЛО ───────────────────────────────────────────────────────────────
// Хук отдаёт готовую пару `{ href, onClick }` — её раскрывают на `<a>`, и
// больше на месте кнопки не остаётся НИ ОДНОГО решения: ни адреса, ни ветки по
// авторизации, ни метки страницы, ни обработки модификаторов. Вызывающий
// сообщает ровно то, чего не знает никто, кроме него, — МЕСТО кнопки.
//
// `surface` не параметр намеренно (см. `zoneSurface.js`): страница выводится из
// адреса, поэтому её нельзя ни забыть, ни перепутать.

import { useNavigate, useLocation } from 'react-router-dom';
import { track, withVisitCampaign } from '@/lib/analytics';
import { zoneSurface } from '@/lib/zoneSurface';
import { GUEST_PLANNER_PATH } from '@/lib/routePaths';
import { DEMO_PATH } from '@/pages/Demo/demoPath';
import { LOGIN_PATH, SIGNUP_PATH, guestEntryPath } from '@/lib/authEntry';

/* Какой ВИД экрана входа открыть — не наше решение: его держит `authEntry.js`
   рядом с тем, кто адрес читает (`Login`). Здесь только двери зоны. */

/**
 * Обычный левый клик — тот, который мы имеем право перехватить.
 *
 * Cmd/Ctrl-клик, средняя кнопка и Shift — это «открой отдельно»: перехват
 * сломал бы «открыть в новой вкладке» на КАЖДОЙ кнопке зоны. Предикат общий у
 * CTA и у клика по лого (`useBrandNav`) — до этого он существовал только у
 * второго, поэтому Cmd-клик по кнопке «Начать бесплатно» не открывал ничего.
 */
export function isPlainLeftClick(e) {
  return !(e.defaultPrevented || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey);
}

/**
 * Адрес главной с меткой кампании этого визита — для ссылки на лого со страниц,
 * которые не лендинг. Был тремя одинаковыми константами (демо, публичка, юр).
 *
 * Ленивая, а не константа модуля: `withVisitCampaign` читает снимок входного
 * адреса, и на верхнем уровне он считался бы в момент разбора модуля — до того,
 * как снимок сделан. Значение вычисляется один раз: снимок за сессию не
 * меняется.
 */
let home;
export function zoneHome() {
  home ??= withVisitCampaign(`${window.location.origin}/`);
  return home;
}

/**
 * Адрес планировщика с меткой кампании этого визита — куда ведёт кнопка
 * «начать» неавторизованной зоны (TRIP-505).
 *
 * ★ БЕЗ ВЕТКИ ПО АВТОРИЗАЦИИ, И ЭТО РЕШЕНИЕ, А НЕ УПРОЩЕНИЕ. «Начать
 * планировать» и «Войти» — РАЗНЫЕ кнопки с разным смыслом, слитые до этого в
 * одну развилку `isAuthenticated ? '/trips' : '/login'`. Для кнопки входа
 * развилка верна и остаётся (`menu_signin`), для кнопки «начать» — нет:
 * планировщик открыт обоим, и вошедшему он нужен ровно так же. Один адрес на
 * оба состояния означает, что ссылку можно вести в рекламу НАПРЯМУЮ, минуя
 * лендинг, и она не сломается ни для кого.
 *
 * Ленивая по той же причине, что `zoneHome`. ВНУТРЕННИЙ путь, а не абсолютный
 * адрес (в отличие от `zoneHome`): его ведёт роутер, а полная перезагрузка
 * выбросила бы снимок кампании вместе с документом — гард 2ad про это же.
 */
let plan;
export function zonePlan() {
  plan ??= withVisitCampaign(GUEST_PLANNER_PATH);
  return plan;
}

/**
 * Адрес готового примера поездки — дверь «что это вообще» (TRIP-505).
 *
 * Была тремя копиями `withVisitCampaign(DEMO_PATH)` по вызывателям (герой,
 * финальный блок, а в бургере её не было вовсе — там пункт с подписью про демо
 * вёл во вход). Теперь адрес называется один раз, как `zonePlan` и `zoneHome`.
 */
let demo;
export function zoneDemo() {
  demo ??= withVisitCampaign(DEMO_PATH);
  return demo;
}

/**
 * Адрес входа с меткой кампании — дверь «я уже пользуюсь».
 *
 * Четвёртая и последняя дверь зоны, названная здесь по той же причине, что три
 * предыдущие: до этого `withVisitCampaign('/login')` был выписан руками в трёх
 * местах (`App.jsx`, здесь, планировщик), и метка кампании держалась на том,
 * что все трое написали одно и то же.
 */
let login;
export function zoneLogin() {
  login ??= withVisitCampaign(LOGIN_PATH);
  return login;
}

/**
 * Адрес экрана входа, открытого на форме РЕГИСТРАЦИИ, с меткой кампании.
 *
 * Нужен тем, кто ведёт в авторизацию не кнопкой зоны: гостевой планировщик
 * отправляет туда человека, который только что собрал маршрут и аккаунта у него
 * заведомо нет. Форма входа встретила бы его заголовком для вернувшегося — тем
 * самым, из-за которого 48 из 49 не находили регистрацию (замер PR #1130).
 */
let signup;
export function zoneSignup() {
  signup ??= withVisitCampaign(SIGNUP_PATH);
  return signup;
}

/**
 * @param {string} location МЕСТО кнопки — единственное, чего не знает хук:
 *   `header` · `header_signin` · `menu` · `menu_demo` · `menu_signin` · `hero` ·
 *   `hero_demo` · `final` · `final_demo`. `final` и `final_demo` уже живут в
 *   аналитике — не переименовывать. Оно же решает, регистрация это или вход
 *   (`guestEntryPath`), поэтому суффикс `_signin` несёт смысл, а не только
 *   метку в аналитике.
 * @param {string} [to] Адрес двери, если она ведёт НЕ в авторизацию: планировщик
 *   (`zonePlan`) и пример поездки (`zoneDemo`). Без него — авторизация, и вид
 *   экрана выбирает суффикс места.
 * @returns {{href: string, onClick: (e: MouseEvent) => void}} раскрыть на `<a>`.
 */
export function useZoneCta(location, to) {
  const nav = useNavigate();
  const { pathname } = useLocation();
  // Метка кампании визита едет НА адрес: gtag читает её из строки запроса
  // (TRIP-407 PR5).
  //
  // ★ ВЕТКИ ПО АВТОРИЗАЦИИ ЗДЕСЬ БОЛЬШЕ НЕТ (TRIP-505). Она отвечала на вопрос
  // «вошёл ли он» в компоненте, который рисуется РАНЬШЕ ответа: `isAuthenticated`
  // стартует ложной, поэтому у вошедшего адрес кнопки на первом кадре был
  // гостевым и молча подменялся на втором. Пока подписи у обоих состояний
  // совпадали, это никого не задевало; отдельная дверь «Войти» показала бы
  // подмену глазами. Развилку держит сам `/login`: живой сессии он отдаёт
  // `postLoginPath()`, то есть вошедший попадает в «Мои поездки» одним
  // переходом — и делает это ОДНО место, а не каждая кнопка зоны.
  //
  // Вид экрана по-прежнему решает место кнопки (`guestEntryPath`): «начать» —
  // регистрация, `_signin` — форма входа (замер воронки, PR #1130).
  const href = to ?? withVisitCampaign(guestEntryPath(location));
  const onClick = (e) => {
    if (!isPlainLeftClick(e)) return;
    e.preventDefault();
    track('cta_clicked', { location, surface: zoneSurface(pathname) });
    // Через роутер, а не голым href: полная перезагрузка выбросила бы снимок
    // кампании визита вместе с документом (гард 2ad про то же).
    nav(href);
  };
  return { href, onClick };
}
