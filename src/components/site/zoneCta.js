// ОДНА дверь для всех CTA неавторизованной зоны: куда ведёт кнопка, что она
// сообщает аналитике и как ведёт себя клик (TRIP-445, PR 7).
//
// ── ЧТО БЫЛО ────────────────────────────────────────────────────────────────
// Шесть кнопок одного смысла («иди в продукт»), и каждая своя:
//   • `const APP_URL = '/login'`                             — ЧЕТЫРЕ копии
//   • `isAuthenticated ? '/trips' : withVisitCampaign(…)`    — ТРИ копии
//   • `e.preventDefault(); track(…); nav(target)`            — ЧЕТЫРЕ копии
// с РАЗНЫМ содержимым события: герой слал `{location:'hero'}` без страницы,
// вторая кнопка героя не слала ничего, шапка и оба пункта бургера — тоже
// ничего. То есть верхние ступени воронки не считались вовсе, а нижние не
// различались между лендингом и демо. Это не «забыли дописать»: это следствие
// того, что контракт события заполнялся руками в шести местах.
//
// ── ЧТО СТАЛО ───────────────────────────────────────────────────────────────
// Хук отдаёт готовую пару `{ href, onClick }` — её раскрывают на `<a>`, и
// больше на месте кнопки не остаётся НИ ОДНОГО решения: ни адреса, ни ветки по
// авторизации, ни метки страницы, ни обработки модификаторов. Вызывающий
// сообщает ровно то, чего не знает никто, кроме него, — МЕСТО кнопки.
//
// `surface` не параметр намеренно (см. `zoneSurface.js`): страница выводится из
// адреса, поэтому её нельзя ни забыть, ни перепутать.

import { useNavigate, useLocation } from 'react-router-dom';
import { useAuth } from '@/lib/AuthContext';
import { useI18n } from '@/lib/i18n/I18nContext';
import { track, withVisitCampaign } from '@/lib/analytics';
import { zoneSurface } from '@/lib/zoneSurface';
import { guestEntryPath } from '@/lib/authEntry';
import { withLangPath } from '@/lib/routePaths';

/** Куда ведёт CTA уже вошедшего. Одно место на всю зону.
 *
 * Адрес ГОСТЯ парной константой здесь больше не лежит — его решает
 * `guestEntryPath` (`src/lib/authEntry.js`): кнопки зоны обещают НАЧАТЬ, и
 * вести их надо на регистрацию, а не на форму входа. Правило живёт рядом с тем,
 * кто этот адрес читает (`Login`), — здесь оно было бы половиной контракта, и
 * вторая половина уехала бы молча. */
const APP_PATH = '/trips';

/**
 * Обычный левый клик — тот, который мы имеем право перехватить.
 *
 * Cmd/Ctrl-клик, средняя кнопка и Shift — это «открой отдельно»: перехват
 * сломал бы «открыть в новой вкладке» на КАЖДОЙ кнопке зоны. Предикат общий у
 * CTA и у клика по лого (`useBrandNav`) — до этого он существовал только у
 * второго, поэтому Cmd-клик по кнопке «Начать бесплатно» не открывал ничего.
 */
export function isPlainLeftClick(e) {
  return !(e.defaultPrevented || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey);
}

/**
 * ★★ ВНУТРЕННИЙ АДРЕС ЗОНЫ НА ЯЗЫКЕ ОТКРЫТОЙ СТРАНИЦЫ (TRIP-520).
 *
 * У лендинга и демо по три адреса, по одному на язык. Значит и ссылки между
 * ними — «домой», «посмотреть демо» — обязаны вести на адрес ТОГО ЖЕ языка,
 * иначе язык теряется на первом же клике внутри зоны.
 *
 * ★ ХУК, А НЕ ФУНКЦИЯ, И ЭТО НЕСУЩЕЕ. Язык теперь МЕНЯЕТСЯ БЕЗ ПЕРЕЗАГРУЗКИ
 * ДОКУМЕНТА: переключатель уводит на соседний адрес роутером, чтобы человека не
 * выбрасывало в начало страницы. Любое значение, посчитанное один раз за
 * загрузку, после такой смены остаётся от прежнего языка.
 *
 * Ровно это и случилось с прежней парой `zonePath()` + `zoneHome()`: вторая
 * считала адрес главной ОДИН РАЗ на весь документ (`home ??= …`) и раздавала его
 * в `brandHref`. На демо это выглядело так: открыл `/ru/d/…`, переключил на
 * испанский — страница испанская, а логотип по-прежнему ведёт на `/ru`.
 *
 * Имя с `use` — не украшение: вызвать хук вне рендера запрещает штатный
 * `react-hooks/rules-of-hooks`, то есть прежний кэш теперь невозможен по
 * построению, а не по договорённости.
 *
 * ★ ЛОКАЛЬ БЕРЁТСЯ У СЛОЯ i18n, А НЕ ИЗ АДРЕСА ПОД РУКОЙ. Страницы зоны
 * рисуются под ПОДМЕНЁННОЙ локацией — `<Routes location>` в `App.jsx` снимает
 * языковой префикс, чтобы таблица маршрутов была одна, — поэтому здешний
 * `useLocation()` префикса уже не видит. Прежний код обходил это чтением
 * `window.location.pathname`; оно нереактивно, доступно вне рендера, и ровно оно
 * позволило закэшировать адрес главной на весь документ. Владелец факта один —
 * `useRouteLocale` кладёт его в слой i18n из корня роутера, где путь настоящий.
 *
 * @param {string} path путь без языкового префикса
 * @returns {string}
 */
export function useZonePath(path) {
  const { routeLocale, lang } = useI18n();
  // ★★ НЕТ ЛОКАЛИ У АДРЕСА — БЕРЁМ ЯЗЫК, КОТОРЫЙ ЧЕЛОВЕК СЕЙЧАС ВИДИТ, А НЕ
  // АНГЛИЙСКИЙ ПО УМОЛЧАНИЮ (TRIP-520).
  //
  // Локаль есть только у переведённых страниц (`localeOf` → лендинг и демо). У
  // юр-документов её нет и быть не может — они английские по решению TRIP-465
  // §7, — но ОБВЯЗКА у них переведена и язык там честно берётся из профиля или
  // из выбора посетителя. Фолбэк на `DEFAULT_LANG` этот язык терял, и терял
  // молча, ровно на выходе:
  //
  //     /ru  →  «Terms»  →  /terms (обвязка русская)  →  логотип  →  /  (английский)
  //
  // То есть тот самый дефект, ради которого заведён `zonePath`, оставался на
  // единственном пути, где язык лежит НЕ в адресе. `lang` — уже сложенный слоями
  // ответ (`адрес ?? профиль ?? посетитель`), поэтому здесь он и нужен: на
  // переведённой странице верхний слой всё равно победит через `routeLocale`, а
  // вне её ссылка наследует язык экрана.
  return withLangPath(routeLocale ?? lang, path);
}

/**
 * Адрес главной с меткой кампании этого визита — для ссылки на лого со страниц,
 * которые не лендинг. Был тремя одинаковыми константами (демо, публичка, юр).
 *
 * Абсолютный: `useBrandNav` отличает свой адрес от чужого по origin. Метку
 * кампании подставляет `withVisitCampaign` — она читает снимок входного адреса,
 * который за визит не меняется, поэтому пересчёт на каждый рендер бесплатен.
 *
 * @returns {string}
 */
export function useZoneHome() {
  const path = useZonePath('/');
  return withVisitCampaign(`${window.location.origin}${path}`);
}

/**
 * @param {string} location МЕСТО кнопки — единственное, чего не знает хук:
 *   `header` · `menu` · `menu_signin` · `hero` · `hero_demo` · `final` ·
 *   `final_demo`. `final` и `final_demo` уже живут в аналитике — не переименовывать.
 *   Оно же решает, регистрация это или вход (`guestEntryPath`), поэтому суффикс
 *   `_signin` у пункта «войти» несёт смысл, а не только метку в аналитике.
 * @param {string} [to] Адрес, если кнопка ведёт НЕ в продукт (ссылка на демо в
 *   финальном блоке лендинга). По умолчанию — регистрация, для пункта «войти» —
 *   форма входа, а для вошедшего «Мои поездки».
 * @returns {{href: string, onClick: (e: MouseEvent) => void}} раскрыть на `<a>`.
 */
export function useZoneCta(location, to) {
  const nav = useNavigate();
  const { pathname } = useLocation();
  const { isAuthenticated } = useAuth();
  // Метка кампании визита едет НА адрес: gtag читает её из строки запроса
  // (TRIP-407 PR5). Вошедшему она не нужна — он уже атрибуцирован.
  const href = to ?? (isAuthenticated ? APP_PATH : withVisitCampaign(guestEntryPath(location)));
  const onClick = (e) => {
    if (!isPlainLeftClick(e)) return;
    e.preventDefault();
    track('cta_clicked', { location, surface: zoneSurface(pathname) });
    // Через роутер, а не голым href: полная перезагрузка выбросила бы снимок
    // кампании визита вместе с документом (гард 2ad про то же).
    nav(href);
  };
  return { href, onClick };
}
