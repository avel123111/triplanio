import React from 'react';
import { Link } from 'react-router-dom';
import { useZoneHref } from './zoneCta';

/**
 * ★★ ССЫЛКА ЗОНЫ — ЕДИНСТВЕННАЯ ФОРМА, В КОТОРОЙ ЗОНА ПИШЕТ `<Link>`.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ СТРОКОЙ В `SiteChrome`. Смысл двери в том, что
 * `Link` из `react-router-dom` в зоне импортирует РОВНО ОДИН файл, и гард 2ah
 * проверяет это на уровне импорта — предикат полный, а не перечисление форм
 * записи адреса. Спрячь мы `ZoneLink` внутрь семисотстрочного `SiteChrome`, и
 * тому файлу пришлось бы разрешить импорт `Link` целиком: рядом с дверью
 * появилось бы место, где можно молча написать сырую ссылку, — то есть гард
 * охранял бы всех, кроме самого удобного места нарушить. Пятнадцать строк, в
 * которых нечему спрятаться, — цена полноты предиката.
 *
 * Адрес резолвит `useZoneHref`: он один решает, нужен ли языковой префикс
 * (`LOCALISED_PAGES`), и одинаково верен и для `/` (станет `/es`), и для
 * `/terms` (останется собой). Поэтому `to` пишется БЕЗ языка всегда — вызывателю
 * больше нечего помнить и не в чем ошибиться.
 *
 * Пропы прокидываются как есть: это `Link`, а не его пересказ.
 */
export default function ZoneLink({ to, ...rest }) {
  const href = useZoneHref();
  return <Link to={href(to)} {...rest} />;
}
