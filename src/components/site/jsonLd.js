// Структурированные данные (JSON-LD) неавторизованной зоны.
//
// ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ og-ТЕГОВ, которые у нас уже есть. `og:` объясняет
// МЕССЕНДЖЕРУ, как нарисовать карточку в чате. JSON-LD объясняет ПОИСКОВИКУ и
// движку ответов, ЧТО эта страница такое: организация, сайт, набор
// вопросов-ответов. Разные потребители, разные механизмы, одно другое не
// заменяет.
//
// ★ ГЛАВНОЕ ПРАВИЛО: разметка обязана совпадать с тем, что человек ВИДИТ на
// странице. Google штрафует за расхождение, и это не теоретический риск — это
// самый лёгкий способ им заработать. Поэтому здесь нет ни одной строки,
// набранной отдельно от разметки: `faqPageLd` принимает те же самые пары
// вопрос-ответ, которыми нарисован сам аккордеон.
//
// ★ ПОЧЕМУ НЕ В `index.html`. Он отдаётся на КАЖДЫЙ адрес — там могут жить
// только общесайтовые утверждения (организация, сайт), и они там и живут.
// `FAQPage` привязан к одной странице: положи его в `index.html` — и каждая
// страница сайта, включая экраны приложения, начнёт утверждать, что несёт этот
// FAQ. Та же ловушка, из-за которой туда сознательно не положен `canonical`.

import { useEffect } from 'react';

/**
 * Вставить блок JSON-LD на время жизни страницы.
 *
 * Идиома взята у `canonical` из `SiteZone`: узел создаётся эффектом и снимается
 * уборкой — иначе разметка одной страницы переживёт переход и станет враньём о
 * следующей. `data` сериализуется в теле эффекта, поэтому вызыватель может
 * строить объект прямо в рендере, не заботясь о ссылочной стабильности.
 *
 * @param {object|null|undefined} data объект schema.org; `null` — ничего не ставить
 */
export function useJsonLd(data) {
  const json = data ? JSON.stringify(data) : null;
  useEffect(() => {
    if (!json) return undefined;
    const el = document.createElement('script');
    el.type = 'application/ld+json';
    el.textContent = json;
    document.head.appendChild(el);
    return () => { el.remove(); };
  }, [json]);
}

/**
 * ЧТО МЫ ТАКОЕ — машине, одним объектом (TRIP-520).
 *
 * ЗАЧЕМ. До этого мы сообщали поисковику и движкам ответов ровно две вещи:
 * «существует организация Triplanio» и «у неё есть сайт». Не сказано было
 * главное — что это ПРИЛОЖЕНИЕ, что оно про планирование поездок, что работает
 * в браузере и что начать можно бесплатно. Замер конкурента 05.09.2026: у
 * Wanderlog в том же месте лежит `SoftwareApplication` с категорией, платформами
 * и ценой, и именно из него собирается ответ «что это за штука».
 *
 * ★ ЦЕНЫ PRO СЮДА НЕ ПИШУТСЯ. Прайс живёт в каталоге Stripe и приезжает в
 * рантайме (`Pro.jsx` читает `unit_amount`); литерала 6.99 в коде нет ни одного,
 * и заводить его здесь значит завести ТРЕТЬЮ копию цены, которая разойдётся с
 * каталогом на первом же изменении тарифа — молча, потому что сверять её не с
 * чем. Объявляем то, что верно безусловно и не протухает: вход бесплатный.
 * Так же поступает Wanderlog (`price: 0` при платном Pro).
 *
 * ★ РЕЙТИНГА ЗДЕСЬ НЕТ И НЕ ДОЛЖНО БЫТЬ, пока нет настоящих отзывов: за цифрой
 * у Wanderlog стоят 34 300 оценок в магазинах приложений, у нас — ноль. Google
 * снимает разметку целиком за расхождение с видимым, и это самый лёгкий способ
 * потерять её надолго.
 *
 * @param {{ name: string, description: string, url: string }} app
 * @returns {object}
 */
export function softwareAppLd({ name, description, url }) {
  return {
    '@context': 'https://schema.org',
    '@type': 'SoftwareApplication',
    name,
    description,
    url,
    applicationCategory: 'TravelApplication',
    // Веб-приложение: нативных сборок у нас нет, и обещать их разметкой нельзя.
    operatingSystem: 'Web',
    browserRequirements: 'Requires JavaScript',
    offers: {
      '@type': 'Offer',
      price: '0',
      priceCurrency: 'EUR',
      availability: 'https://schema.org/InStock',
    },
  };
}

/**
 * `FAQPage` из тех же пар, которыми нарисован аккордеон.
 *
 * Пустой или неполный список даёт `null`, а не пустую разметку: страница без
 * вопросов не является FAQ-страницей, и объявлять её таковой — то самое
 * расхождение с видимым, за которое штрафуют.
 *
 * @param {Array<{q: string, a: string}>} items
 * @returns {object|null}
 */
export function faqPageLd(items) {
  const clean = (items || []).filter((it) => it && it.q && it.a);
  if (!clean.length) return null;
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: clean.map((it) => ({
      '@type': 'Question',
      name: it.q,
      acceptedAnswer: { '@type': 'Answer', text: it.a },
    })),
  };
}
