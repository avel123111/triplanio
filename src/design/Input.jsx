import React from 'react';
import { Icon } from './icons';

/**
 * «Поле обязательное» - ОДИН источник (TRIP-333).
 *
 * Раньше это говорилось тремя способами, и ни одно поле не использовало больше
 * одного: звёздочка от `<Field required>`, звёздочка, ЗАШИТАЯ В СТРОКУ перевода
 * («Название *»), и нативный атрибут на экране входа. Видимая звёздочка и
 * признак для скринридера жили порознь, поэтому поле могло выглядеть
 * обязательным и не быть им для AT - и наоборот.
 *
 * Теперь у `<Field>` флаг ставится ОДИН раз (`<Field required>`) и доезжает до
 * поля контекстом, а не пропом через все промежуточные компоненты. Поля вне
 * `<Field>` на ЭТОТ шов ещё не переехали: `<Label>` в `EventEditDialog` уже
 * рисует ту же звёздочку (`data-required` от валидатора, строки `event.*_req`
 * выпилены), но своим контекстом, а поля под ним - локальные шимы `<input
 * className="input">`, не этот компонент, поэтому `required`/`aria-required`
 * там не ставится: видимое и озвученное в этой форме всё ещё врозь. Проп у
 * `Input` не заводится: он был бы вторым способом сказать то же самое, а такая
 * пара всегда расходится (TRIP-293). Явный атрибут в вызове по-прежнему возможен -
 * `{...rest}` разливается ПОСЛЕ и перекрывает контекст (поля вне `<Field>`);
 * признак для AT считается от ИТОГОВОГО значения, иначе `required={false}`
 * внутри `<Field required>` снял бы атрибут и оставил `aria-required` - ровно
 * то расхождение видимого и озвученного, которое эта правка и убирает.
 *
 * Нативный `required` безопасен: единственные `<form>` с сабмитом - на экране
 * входа, и они собраны на `.auth-input`, а не на этом компоненте. Если поле
 * когда-нибудь окажется внутри submit-формы, браузер начнёт валидировать его
 * сам, поверх `useHybridValidation`.
 */
const RequiredCtx = React.createContext(false);
export const FieldRequired = RequiredCtx.Provider;

// Атрибуты обязательности под spread - той же формы, что и `fieldState`.
const requiredAttrs = (on) => (on
  ? { required: true, 'aria-required': 'true' }
  : null);

/**
 * Поле ввода с декорациями - иконка слева, спиннер справа (TRIP-333).
 *
 * «Поле с иконкой» было собрано заново пять раз - `.dl-search`,
 * `.s22f-search`, `.ss-search` и инлайны в `Trips` и `Autocomplete` - с
 * отступом иконки 11/12/13/14/15px, а три сборки из пяти заново объявляли
 * рамку, фон и фокус поверх `.input`.
 *
 * Живёт отдельным модулем, а не в `design/index.jsx`: барраль реэкспортит
 * `components/ui/*` (SearchSelect и другие), и импорт поля оттуда замкнул бы
 * зависимость в кольцо. Зависимость `ui/* -> design` односторонняя, и это
 * единственное место, где её стоило бы нарушить - значит не нарушаем.
 *
 * Декорации стоят в DOM ПОСЛЕ поля и реагируют на его состояние
 * сиблинг-селектором, а не `:has()`: в цели сборки Firefox 78, где `:has()`
 * нет. Тот же приём и по той же причине, что у `.checkbox`.
 *
 * `className` уезжает на ОБЁРТКУ, а не на поле: у всех вызовов внешний класс
 * несёт раскладку (`flex`, `min-width`, порядок в медиазапросе), а не вид.
 *
 * ★В `className` можно класть ТОЛЬКО раскладку, которая не смещает коробку
 * (`flex`, `min/max-width`, `order`). Ни `padding`, ни `border`: декорации
 * позиционируются от обёртки, и любой её внутренний отступ уводит иконку -
 * `.ss-search` со своим `padding: 6px` ставил её на 6px вместо 12. Такой класс
 * остаётся ОТДЕЛЬНЫМ элементом снаружи.
 */
export const Input = ({ icon, iconActive, loading, num, className = '', boxRef, ...rest }) => {
  const required = React.useContext(RequiredCtx);
  // Слот справа резервируется, как только вызов ВООБЩЕ умеет показывать
  // спиннер (даже при `loading={false}`): включать отступ вместе со спиннером
  // значит менять ширину текстового поля прямо во время набора (TRIP-277).
  const hasEnd = loading !== undefined;
  const boxClass = ['input-affix', icon && 'input-affix--ic', hasEnd && 'input-affix--end', className]
    .filter(Boolean).join(' ');
  return (
    <div className={boxClass} ref={boxRef}>
      <input className={num ? 'input num' : 'input'} {...requiredAttrs(rest.required ?? required)} {...rest} />
      {icon && (
        <span
          className={`input-affix__ic${iconActive ? ' input-affix__ic--on' : ''}`}
          aria-hidden="true"
        >
          <Icon name={icon} size={16} />
        </span>
      )}
      {loading && (
        // Обёртка держит центрирующий transform, иконка - вращение: `aispin`
        // анимирует `transform`, и на одном элементе кадр затирает
        // translateY(-50%) - иконка съезжала на пол-высоты за оборот (TRIP-277).
        <span className="input-affix__end" aria-hidden="true">
          <Icon name="refresh" size={15} className="spin" />
        </span>
      )}
    </div>
  );
};

// Пара к <Input> для многострочного поля: тот же канон `.textarea`, декораций
// у него нет, поэтому и обёртки-позиционера нет - внешний класс идёт на само
// поле.
export const Textarea = ({ className = '', ...rest }) => {
  const required = React.useContext(RequiredCtx);
  return (
    <textarea
      className={className ? `textarea ${className}` : 'textarea'}
      {...requiredAttrs(rest.required ?? required)}
      {...rest}
    />
  );
};

/**
 * Несколько контролов, читающихся как ОДНО поле: сумма + валюта, цена «от/до».
 *
 * Рамку, радиус, фон и все состояния держит КОНТЕЙНЕР, дети внутри идут без
 * собственной рамки. Поэтому у поля нет и не нужен вариант «без рамки»: это
 * не свойство поля, а следствие того, что рамку взяла на себя группа.
 *
 * Фокус - `:focus-within` на контейнере, а не на детях: подсветиться должна
 * вся группа, иначе кольцо обводит половину видимого поля.
 *
 * Дети - обычные `<Input>` и любые add-on'ы (значок валюты, тире). Группа
 * ничего о них не знает, поэтому состав меняется без правки компонента.
 *
 * Состояние валидации приходит теми же атрибутами, что и полю
 * (`{...fieldState(...)}`), но красит КОНТЕЙНЕР: у детей рамки нет, красить у
 * них нечего. Своего пропа нет намеренно - он был бы вторым способом сказать
 * одно и то же, а вторая ручка на одно свойство всегда разъезжается с первой.
 */
export const InputGroup = ({ className = '', children, ...rest }) => (
  <div className={className ? `input-group ${className}` : 'input-group'} {...rest}>
    {children}
  </div>
);
