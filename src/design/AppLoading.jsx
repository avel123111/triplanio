/**
 * Ожидание на всю площадь — ОДИН элемент на все свои места.
 *
 * Разметка `.app-loading` + `.spin spin--ring spin--xl spin--ink` жила
 * КОПИЯМИ: две в `App.jsx` (гейт авторизации и `Suspense` маршрутов) и одна в
 * `I18nProvider`. Повторённая рядом с существующим классом разметка — признак
 * того, что у неё нет своего имени (правило #6 / TRIP-282), а не повод
 * скопировать ещё раз. Две копии в `App.jsx` схлопнулись сразу, третья ждала
 * общего дома: shared-компонент это «новое» и идёт через апрув (получен).
 *
 * ★ ИМПОРТ ИЗ `@/design/index` ЗДЕСЬ НЕ ГОДИТСЯ ДЛЯ ОДНОГО ПОТРЕБИТЕЛЯ.
 * `index.jsx` сам импортирует `useT` из `I18nContext`, поэтому обращение
 * `I18nContext → index.jsx` замкнуло бы цикл. Модули ES цикл переживают, но
 * привязка на момент вычисления модуля может оказаться `undefined` — то есть
 * это работало бы «пока работает». Поэтому `I18nContext` берёт ЭТОТ ФАЙЛ
 * напрямую, а все остальные — через `@/design/index`, как принято у остальных
 * примитивов ДС. Единственная зависимость файла — `@/lib/splash` (TRIP-478), и
 * она безопасна ровно потому, что у САМОГО `splash.js` импортов нет: цепочка
 * обрывается на нём и замкнуться не может. Добавишь этому файлу зависимость,
 * которая тянет ДС или контексты, — вернёшь тот самый цикл.
 *
 * Компонент намеренно без пропсов: у обоих вызывателей ожидание выглядит
 * одинаково, и это часть контракта («ожидание выглядит одинаково, откуда бы ни
 * пришло» — комментарий у `Suspense` в `App.jsx`). Появится второй облик —
 * появится ось, а не второй компонент.
 */
import { useEffect } from 'react';
import { holdSplash } from '@/lib/splash';

export default function AppLoading() {
  // Пока это ожидание на экране, экран запуска (TRIP-478) не уходит: для
  // человека заставка и полноэкранное ожидание — один и тот же кадр «ещё
  // грузится», и показывать их по очереди значит заставить ждать дважды. Право
  // «ещё рано» живёт ЗДЕСЬ, а не списком условий в App.jsx: условий четыре
  // (авторизация, словарь, два Suspense), и список разъехался бы с ветками при
  // первой же правке — а этот компонент рисуют все четыре.
  useEffect(() => holdSplash(), []);

  return (
    <div className="app-loading">
      <div className="spin spin--ring spin--xl spin--ink" />
    </div>
  );
}
