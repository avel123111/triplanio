import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/**
 * Лок-ап бренда в шапке: знак + вордмарк (TRIP-481).
 *
 * ★ ЧТО ЗДЕСЬ ДЕРЖИТСЯ И ПОЧЕМУ ЭТОМУ НУЖЕН ТЕСТ. Зазор между знаком и словом
 * до этой задачи НЕ БЫЛ ЗАДАН НИГДЕ — он складывался сам, из двух чужих
 * величин: воздуха внутри слота-якоря (--rail-w шире знака) и gap контейнера
 * `.app-header__left`. Получалось 27px, которых никто не назначал и которые
 * поэтому нельзя было ни найти грепом, ни поменять осознанно.
 *
 * Дефект такого рода не виден ни в одном диффе: чинишь его формулой, а
 * ломается он обратно ОДНИМ движением — кто-нибудь заменит `calc(…)` на
 * готовое «-15px», потому что так короче. Число совпадёт в тот день и
 * разъедется в тот, когда тронут --rail-w или размер знака. Скриншота у этого
 * нет, гарда тоже: 2p увидит одно объявление вместо другого и пропустит с
 * маркером. Единственный гейт — этот тест.
 *
 * Он проверяет не «зазор равен 12», а СПОСОБ, которым зазор получается:
 * величина обязана быть параметром, а компенсация чужих отступов — выводиться
 * из тех же токенов, что эти отступы и задают.
 */
const CSS = readFileSync(fileURLToPath(new URL('./app.css', import.meta.url)), 'utf8');

/** Значение объявления `prop` внутри правила с селектором `sel`. */
function decl(sel, prop) {
  const rule = CSS.match(new RegExp(`\\n${sel.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*\\{([^}]*)\\}`));
  assert.ok(rule, `правило ${sel} не найдено — селектор переименован, тест ослеп`);
  return rule[1].match(new RegExp(`(?:^|;|\\s)${prop}:\\s*([^;]+)`))?.[1]?.trim();
}

test('зазор знак↔слово выведен из токенов, а не вбит числом', () => {
  const m = decl('.app-header__brand-name', 'margin-left');
  assert.ok(m, 'у вордмарка нет margin-left — зазор снова стал суммой чужих отступов');

  // --brand-gap — САМА величина зазора; остальные три вычитают то, что иначе
  // прибавилось бы к нему само.
  for (const token of ['--brand-gap', '--rail-w', '--brand-mark', '--header-left-gap']) {
    assert.ok(m.includes(token),
      `margin-left не ссылается на ${token}: «${m}». Зазор обязан пересчитываться от геометрии, `
      + 'иначе он совпадёт сегодня и разъедется на первой правке слота или знака.');
  }
});

test('gap контейнера шапки — тот же токен, что вычитает формула', () => {
  const gap = decl('.app-header__left', 'gap');
  assert.equal(gap, 'var(--header-left-gap)',
    'gap задан числом, а формула зазора вычитает токен — два значения одного отступа разъедутся молча');
});

test('размер знака живёт одним токеном, а не копиями', () => {
  for (const [sel, prop] of [
    ['.app-header__logo', 'width'], ['.app-header__logo', 'height'],
    ['.app-header__logo img', 'width'], ['.app-header__logo img', 'height'],
  ]) {
    assert.equal(decl(sel, prop), 'var(--brand-mark)',
      `${sel} ${prop} — литерал вместо --brand-mark: формула зазора считает размер знака по токену, `
      + 'копия рядом с ней делает зазор неверным ровно на разницу');
  }
});
