// ЧИСЛИТЕЛЬНОЕ И СЛОВО ПРИ НЁМ — одно правило на всё приложение.
//
// ── ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ ───────────────────────────────────────────────────
// Правило было выписано ОДИННАДЦАТЬ раз тернарником по месту, и не одинаково:
// в `EventAiBlock` — по `% 10` / `% 100` (верно), в остальных десяти — `n < 5`
// или `n >= 2 && n <= 4` (неверно). Разница не теоретическая: `21 < 5` ложно,
// поэтому экран писал «21 городов», «22 ночей», «23 дней». Ошибка тихая — она
// не падает, не логируется и видна только на второй-третьей десятке, куда
// тестовый маршрут не доезжает.
//
// Отсюда и форма: не «хелпер, чтобы не повторяться», а ОДИН предикат с тестом.
// Тот же ход, что у `postLoginPath.js`, `plannerDraft.js` и `create/routeModel.js`.
//
// ── ПОЧЕМУ НЕ `Intl.PluralRules` ──────────────────────────────────────────────
// Он отдаёт КАТЕГОРИЮ ЯЗЫКА ('one'|'few'|'many'|'other'), а словарь у нас —
// три ключа `_one`/`_few`/`_many` на ВСЕ языки: у английского и испанского
// `_few` и `_many` заполнены той же формой множественного числа. То есть
// категории пришлось бы отображать в наши три имени таблицей соответствия для
// каждого языка — больше механики, чем самого правила. Русская тройка при этом
// на en/es даёт ровно верный ответ: 1 → `_one`, всё прочее → `_few`/`_many`, а
// это одно и то же слово.

/**
 * Какая из трёх форм словаря подходит числу.
 *
 * @param {number} n
 * @returns {'one'|'few'|'many'}
 */
export function pluralForm(n) {
  const abs = Math.abs(Math.trunc(Number(n) || 0));
  const mod10 = abs % 10;
  const mod100 = abs % 100;
  if (mod10 === 1 && mod100 !== 11) return 'one';
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 'few';
  return 'many';
}

/**
 * Слово при числе: `pluralWord(t, 21, 'trip.cities_count')` → «город».
 *
 * Берёт `t` параметром, а не зовёт хук: половина вызывателей — чистые функции
 * и хелперы вне компонента, и хук там завести нельзя.
 *
 * @param {(key: string) => string} t
 * @param {number} n
 * @param {string} base ключ БЕЗ суффикса формы (`view.nights`, `tse.day`)
 * @returns {string}
 */
export function pluralWord(t, n, base) {
  return t(`${base}_${pluralForm(n)}`);
}
