// @ts-check
// ЛЕСТНИЦА ДОСТУПА НА ФРОНТЕ — ЧТЕНИЕ ступени, а не её вывод.
//
// Ступень вызывающего («кто я на этом трипе») ВЫЧИСЛЯЕТ СЕРВЕР и отдаёт готовой:
// `getTripDetails` возвращает поле `myStep` — ту самую ступень, которой он сам
// проверил доступ (`_shared/tripAccess.ts` → `_shared/tripStep.ts`). Фронт её
// принимает через `TripAccessProvider` и здесь только СРАВНИВАЕТ с планкой.
//
// ★ Почему правило больше не зеркалится сюда. Зеркало (`EDITOR_ROLES` +
// `stepFromFacts` + `resolveMyStep`) выводило ступень из списка участников — а
// он приезжает ВТОРЫМ сетевым кругом, поэтому право «догружалось» отдельно от
// трипа и меню собиралось в два приёма. Заодно зеркало было четвёртой копией
// правила о ролях и могло разъехаться с сервером молча: обе двери отдают UI, но
// одна рисует кнопку, а другая на неё 403-ит. Копию сняли — расходиться нечему,
// а ступень приходит на первом же круге.
//
// Роль после этого живёт в ТРЁХ местах (все — серверные):
//   1. CHECK `trip_members_role_check` — какие роли вообще бывают
//   2. SQL  `_can_edit_trip`           — кого пускает RLS/secdef
//   3. TS   `EDITOR_ROLES` (сервер)    — кого пускает edge
// Пару (2)↔(3) сверяет LIVE-ассерт `checkEditorRoles` (гард 2e).
//
// КАЖДЫЙ affordance на фронте объявляет СВОЮ ступень через `clearsStep`, а не
// выводит право руками (`role !== 'viewer'` / `=== 'admin'` / `=== 'owner'`).
// Рукописный гейт мимо лестницы ловит гард 2z (`check-role-gate`).
//
// Модуль import-free намеренно — как и серверный: правило доступа не должно
// тянуть за собой ничего.

/** @typedef {'owner'|'editor'|'participant'|null} TripStep */

// Порядок ступеней. Дословно как серверный `LADDER` — паритет пинит
// `tripStep.test.js` (читает серверный файл текстом).
const LADDER = { participant: 1, editor: 2, owner: 3 };

/**
 * Перекрывает ли `step` планку `required`. null не перекрывает ничего
 * (fail-closed): «ступень ещё не приехала» и «ступени нет» одинаково не дают
 * прав. Дословно как серверный `clearsStep`.
 *
 * @param {TripStep} step
 * @param {'owner'|'editor'|'participant'} required
 */
export function clearsStep(step, required) {
  return step != null && LADDER[step] >= LADDER[required];
}
