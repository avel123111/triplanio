// Какой дверью гость входит в продукт — и с какого вида открывается экран входа.
//
// ПОЧЕМУ ОБЕ ПОЛОВИНЫ В ОДНОМ ФАЙЛЕ. Это одно решение, разложенное на двоих:
// отправитель (`zoneCta` — какой адрес поставить кнопке) и приёмник (`Login` —
// что этот адрес значит). Разъедься они на одну букву, кнопка «Начать
// бесплатно» снова молча открыла бы форму ВХОДА — и не покраснел бы ни один
// гард: обе стороны валидны сами по себе. Тот же довод, каким в этом эпике
// вынесен `postLoginPath.js` (ключ хранилища, выписанный дважды).
//
// ЗАЧЕМ ЭТО ВООБЩЕ. Замер по проду за 30.08–01.09 (трафик Google Ads): все CTA
// зоны обещают НАЧАТЬ («Start planning free» / «Empieza a planificar gratis» /
// «Начать бесплатно»), а вели на экран ВХОДА, чей заголовок обращён к
// вернувшемуся — «Continúa donde lo dejaste». Регистрацию новичок должен был
// найти текстовой ссылкой ПОД формой входа, то есть на телефоне ниже сгиба. За
// 53 часа её нашёл 1 человек из 49 дошедших до `/login`; 17 из 49 ушли обратно
// на лендинг кнопкой «назад», медиана — 4.5 секунды на экране.
//
// Регистрация — НЕ отдельный маршрут: экран тот же (`Login`), меняется только
// вид, с которого он открывается. Поэтому метка едет строкой запроса, а не
// вторым адресом — иначе у одной страницы стало бы два канонических адреса, а
// `canonical` в `SiteZone` строится из `pathname` и строку запроса отбрасывает.
//
// ★ Файл держим ЧИСТЫМ: ни React, ни `window`, ни импортов — цена того, чтобы
// у него был `node --test` (конвенция `zoneSurface.js` и `authFlowCode.js`).

/** Экран входа. Он же несёт регистрацию и восстановление — видами, не адресами. */
export const LOGIN_PATH = '/login';

/** Адрес восстановления пароля: свой маршрут, потому что ссылка приходит письмом. */
export const RECOVERY_PATH = '/reset-password';

/** Ключ и значение метки «открой сразу регистрацию». Пишется здесь ОДИН раз. */
const VIEW_PARAM = 'mode';
export const SIGNUP_VIEW = 'signup';

/** Адрес экрана входа, открытого на форме регистрации. */
export const SIGNUP_PATH = `${LOGIN_PATH}?${VIEW_PARAM}=${SIGNUP_VIEW}`;

/**
 * Куда ведёт CTA зоны у гостя.
 *
 * ★ РЕГИСТРАЦИЯ — ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ, а вход — исключение, и это не
 * перевёрнуто. Кнопок в зону продукта пять (`hero`, `header`, `menu`, `final` и
 * будущие), и ВСЕ они обещают начать; отдельным пунктом «войти» живёт один
 * (`menu_signin`). Разложи правило наоборот — списком «кто ведёт на
 * регистрацию» — и шестая кнопка, добавленная без строчки в этом списке, молча
 * унаследует поведение, от которого мы уходим. Умолчание должно быть тем,
 * которое чаще право.
 *
 * Предикат — СУФФИКС `_signin`, а не перечисление мест: в аналитике уже жили
 * `menu_signin` и `hero_signin`, то есть имя места и так несёт это различие.
 *
 * @param {string} ctaLocation место кнопки — то же значение, что едет в
 *   `cta_clicked.location` (`header` · `menu` · `menu_signin` · `hero` · `final`).
 * @returns {string} путь без метки кампании — её навешивает вызывающий.
 */
export function guestEntryPath(ctaLocation) {
  return String(ctaLocation || '').endsWith('_signin') ? LOGIN_PATH : SIGNUP_PATH;
}

/**
 * С какого вида открыть экран входа.
 *
 * @param {string} pathname `location.pathname`
 * @param {string} search `location.search`
 * @returns {'reset-password'|'signup'|'login'}
 */
export function initialAuthView(pathname, search) {
  if (pathname === RECOVERY_PATH) return 'reset-password';
  if (readViewParam(search) === SIGNUP_VIEW) return SIGNUP_VIEW;
  return 'login';
}

/**
 * Разбор адреса, отдельно от правила вида: метку кампании `withVisitCampaign`
 * дописывает ПОВЕРХ, поэтому `mode` приезжает не один и не обязательно первым.
 *
 * @param {string} search `location.search`
 * @returns {string|null}
 */
function readViewParam(search) {
  return new URLSearchParams(search || '').get(VIEW_PARAM);
}
