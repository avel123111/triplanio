// Куда возвращается человек после входа — и КАКОЙ адрес мы вообще имеем право
// туда пустить.
//
// ПОЧЕМУ ОТДЕЛЬНЫМ МОДУЛЕМ (TRIP-445). Две причины, и обе про то, что здесь
// сходятся ДВА файла:
//   · ключ хранилища был выписан дважды — константой `PENDING_KEY` в JoinTrip
//     (кто пишет) и строкой в Login (кто читает). Разъедься они на одну букву,
//     приглашение молча перестало бы доводить человека до поездки, и ни один
//     гард этого не увидел бы: обе стороны валидны сами по себе;
//   · предикат «этот адрес безопасен» жил внутри компонента, то есть не мог
//     иметь теста. Тот же ход, каким в этом эпике уже вынесены `authFlowCode.js`
//     и `authErrorText.js`: у решения, которое стоит денег или безопасности,
//     должен быть гейт на чистой функции, а не на чтении.

/** Ключ sessionStorage: сюда JoinTrip кладёт адрес, Login его читает. ОДИН. */
export const PENDING_KEY = 'postLoginRedirect';

/** Куда идти, если ничего не отложено. */
export const APP_HOME = '/trips';

/**
 * Можно ли отправить браузер по этому адресу.
 *
 * ★ `startsWith('/')` ОДНОГО СИМВОЛА МАЛО. `//evil.com` тоже начинается со
 * слэша, но это protocol-relative URL: браузер читает его как `https://evil.com`
 * и уводит с домена, а вызыватель делает `window.location.href = dest`
 * безоговорочно. Сегодня в хранилище пишет только JoinTrip (`/join/<токен>`), а
 * само хранилище своё по origin — значит для эксплуатации нужен уже полученный
 * XSS. Это защита в глубину, а не открытая дыра; но место — шов авторизации
 * (правило #13), цена — один предикат, поэтому пусть будет невозможным по
 * построению, а не «сегодня некому».
 *
 * `\` рядом со слэшем — тот же случай: часть браузеров исторически нормализуют
 * `/\evil.com` в protocol-relative. Дешевле запретить, чем помнить, кто как.
 *
 * @param {unknown} dest адрес из хранилища
 * @returns {boolean}
 */
export function isSafeInternalPath(dest) {
  if (typeof dest !== 'string' || dest.length < 2) return dest === '/';
  if (dest[0] !== '/') return false;
  return dest[1] !== '/' && dest[1] !== '\\';
}

/**
 * Запомнить адрес, на который человека вернуть после входа.
 *
 * Писателей стало двое (приглашение и адрес приложения, открытый без сессии —
 * TRIP-497), поэтому запись переехала сюда: у ключа и у проверки адреса один
 * дом, и второй писатель не может ни разойтись с первым в ключе, ни забыть
 * предикат. Небезопасный адрес молча не запоминается — вернуть человека
 * НЕКУДА хуже, чем вернуть его на домашнюю.
 *
 * @param {string} dest внутренний адрес (`/trips`, `/trip/<id>?lens=route`)
 */
export function rememberPostLogin(dest) {
  if (!isSafeInternalPath(dest)) return;
  try { sessionStorage.setItem(PENDING_KEY, dest); } catch { /* приватный режим — просто домой */ }
}

/** Забыть отложенный адрес: человек до него дошёл. */
export function forgetPostLogin() {
  try { sessionStorage.removeItem(PENDING_KEY); } catch { /* нечего забывать */ }
}

/**
 * Отложенный адрес, если он есть и безопасен, иначе домашняя приложения.
 * Чтение хранилища — единственная нечистая часть, поэтому предикат отдельно.
 */
export function postLoginPath() {
  try {
    const dest = sessionStorage.getItem(PENDING_KEY);
    if (isSafeInternalPath(dest)) return dest;
  } catch { /* приватный режим / отключённое хранилище — просто домой */ }
  return APP_HOME;
}
