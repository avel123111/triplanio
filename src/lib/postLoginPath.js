// Куда возвращается человек после входа — и КАКОЙ адрес мы вообще имеем право
// туда пустить.
//
// ПОЧЕМУ ОТДЕЛЬНЫМ МОДУЛЕМ (TRIP-445). Две причины, и обе про то, что здесь
// сходятся ДВА файла:
//   · ключ хранилища был выписан дважды — константой `PENDING_KEY` в JoinTrip
//     (кто пишет) и строкой в Login (кто читает). Разъедься они на одну букву,
//     приглашение молча перестало бы доводить человека до поездки, и ни один
//     гард этого не увидел бы: обе стороны валидны сами по себе;
//   · предикат «этот адрес безопасен» жил внутри компонента, то есть не мог
//     иметь теста. Тот же ход, каким в этом эпике уже вынесены `authFlowCode.js`
//     и `authErrorText.js`: у решения, которое стоит денег или безопасности,
//     должен быть гейт на чистой функции, а не на чтении.

/** Ключ sessionStorage: сюда JoinTrip кладёт адрес, Login его читает. ОДИН. */
export const PENDING_KEY = 'postLoginRedirect';

/** Куда идти, если ничего не отложено. */
export const APP_HOME = '/trips';

/**
 * Можно ли отправить браузер по этому адресу.
 *
 * ★ `startsWith('/')` ОДНОГО СИМВОЛА МАЛО. `//evil.com` тоже начинается со
 * слэша, но это protocol-relative URL: браузер читает его как `https://evil.com`
 * и уводит с домена, а вызыватель делает `window.location.href = dest`
 * безоговорочно. Сегодня в хранилище пишет только JoinTrip (`/join/<токен>`), а
 * само хранилище своё по origin — значит для эксплуатации нужен уже полученный
 * XSS. Это защита в глубину, а не открытая дыра; но место — шов авторизации
 * (правило #13), цена — один предикат, поэтому пусть будет невозможным по
 * построению, а не «сегодня некому».
 *
 * `\` рядом со слэшем — тот же случай: часть браузеров исторически нормализуют
 * `/\evil.com` в protocol-relative. Дешевле запретить, чем помнить, кто как.
 *
 * @param {unknown} dest адрес из хранилища
 * @returns {boolean}
 */
export function isSafeInternalPath(dest) {
  if (typeof dest !== 'string' || dest.length < 2) return dest === '/';
  if (dest[0] !== '/') return false;
  return dest[1] !== '/' && dest[1] !== '\\';
}

/**
 * Запомнить адрес, на который человека вернуть после входа.
 *
 * Писателей стало двое (приглашение и адрес приложения, открытый без сессии —
 * TRIP-497), поэтому запись переехала сюда: у ключа и у проверки адреса один
 * дом, и второй писатель не может ни разойтись с первым в ключе, ни забыть
 * предикат. Небезопасный адрес молча не запоминается — вернуть человека
 * НЕКУДА хуже, чем вернуть его на домашнюю.
 *
 * @param {string} dest внутренний адрес (`/trips`, `/trip/<id>?lens=route`)
 */
export function rememberPostLogin(dest) {
  if (!isSafeInternalPath(dest)) return;
  try { sessionStorage.setItem(PENDING_KEY, dest); } catch { /* приватный режим — просто домой */ }
}

/** Забыть отложенный адрес: человек до него дошёл. */
export function forgetPostLogin() {
  try { sessionStorage.removeItem(PENDING_KEY); } catch { /* нечего забывать */ }
}

/**
 * ЗАБЫТЬ, ЕСЛИ ЧЕЛОВЕК УЖЕ ПРИШЁЛ ПО ЭТОМУ АДРЕСУ.
 *
 * ★ ВТОРОЙ СПОСОБ ПРИБЫТИЯ, И ТРАТИТЬ ЕГО ПРИХОДИТСЯ ЗДЕСЬ. Обычно отложенный
 * адрес тратит тот, кто по нему уходит (`takePostLoginPath`). Но при возврате
 * от провайдера уходим не мы: `redirectTo` для Supabase собирается ИЗ ЭТОГО ЖЕ
 * адреса, и браузер приезжает сразу на него — тратить некому, и запись
 * переживала бы весь сеанс вкладки, уводя туда каждый следующий вход.
 *
 * ★★ ПРЕДИКАТ — «ПРИШЁЛ», А НЕ «ЕСТЬ СЕССИЯ». Первая редакция забывала запись
 * на ЛЮБОЙ загрузке документа с живой сессией, и это неверно дважды:
 *   · ссылка из письма восстановления открывается В ТОЙ ЖЕ ВКЛАДКЕ и приходит
 *     с сессией на `/reset-password` — человек НЕ пришёл, а запись стиралась, и
 *     после смены пароля его уводило на домашнюю вместо своей поездки;
 *   · `Login` читает ту же запись своим `getSession()`, а провайдер контекста —
 *     предок, его промис в очереди раньше: гонка решалась не в пользу читателя,
 *     то есть трата опережала использование.
 * Сверка с адресом закрывает оба случая по построению: на `/reset-password` и
 * на `/login` отложенный адрес не совпадает с текущим, значит не тратится.
 *
 * Сравнивается ПУТЬ: у отложенного адреса законно бывает строка запроса
 * (`/trip/<id>?lens=route`), а «пришёл» — про страницу, не про её параметры.
 *
 * @param {string} pathname текущий путь документа
 * @returns {boolean} потрачено ли
 */
export function forgetPostLoginOnArrival(pathname) {
  let stored = null;
  try { stored = sessionStorage.getItem(PENDING_KEY); } catch { return false; }
  if (!isSafeInternalPath(stored)) return false;
  if (String(stored).split(/[?#]/)[0] !== pathname) return false;
  forgetPostLogin();
  return true;
}

/**
 * Отложенный адрес, если он есть и безопасен, иначе домашняя приложения.
 * Чтение хранилища — единственная нечистая часть, поэтому предикат отдельно.
 */
export function postLoginPath() {
  try {
    const dest = sessionStorage.getItem(PENDING_KEY);
    if (isSafeInternalPath(dest)) return dest;
  } catch { /* приватный режим / отключённое хранилище — просто домой */ }
  return APP_HOME;
}

/**
 * Отложенный адрес — И СРАЗУ ЗАБЫТЬ ЕГО. Зовёт тот, кто ПО НЕМУ УХОДИТ.
 *
 * ★ ЗАЧЕМ РАЗДЕЛЬНО С `postLoginPath()`. Отложенный адрес — ОДНОРАЗОВОЕ
 * намерение («я шёл вот сюда, верни меня туда после входа»), а хранился он как
 * настройка: `postLoginPath()` читает и не тратит, а `forgetPostLogin()` зовёт
 * один `JoinTrip`. Значит запись переживала вход и уводила туда же КАЖДЫЙ
 * следующий раз в этой вкладке. Пока писателем был только аут-гейт
 * (`RedirectToLogin` — человек и правда шёл на защищённый адрес), залипание
 * почти не всплывало. С гостевым планировщиком (TRIP-505) писателей стало два,
 * и один клик «Создать аккаунт» на шаге «Обзор» уводил в планировщик любой
 * последующий вход — даже совсем не связанный с черновиком.
 *
 * ★ ТРАТИТ ТОТ, КТО УХОДИТ, А НЕ ТОТ, КТО СПРАШИВАЕТ. Читателей у адреса два, и
 * они разные по смыслу: `postLoginHref()` — навигация, которую делаем МЫ (уход
 * состоится), а `postLoginRedirectTo()` — адрес, который отдаётся Supabase для
 * письма или OAuth, и перехода может не случиться (человек закрыл окно
 * провайдера), а письмо ещё и переотправляют — там тратить нельзя, иначе вторая
 * отправка уедет на домашнюю. Поэтому трата — отдельная функция, а не режим
 * чтения. Та же идиома, что у `takeHandoff` в `lib/plannerDraft`.
 *
 * @returns {string}
 */
export function takePostLoginPath() {
  const dest = postLoginPath();
  forgetPostLogin();
  return dest;
}
