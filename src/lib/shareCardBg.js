// Подложка share-карточки в SVG-шаблоне (чистые строковые функции; IO — в
// components/trips/shareCard.js). TRIP-443: новый дизайн — прозрачный стикер,
// фон приходит ОТДЕЛЬНЫМ слоем-плейсхолдером, а не запечён в шаблон.
//
// ★ КОНТРАКТ С EDGE (render-share-card/template.ts, BG_TOKEN): шаблон рисует
// full-bleed `<image href="__SHARE_CARD_BG__">` в самом низу. Клиент:
//   · выбран фон  → подменяет токен на data-URI выбранной подложки;
//   · «Стандарт»  → удаляет элемент целиком → карточка прозрачная.
// И в превью (overlay), и в финале (card_svg) — один токен. Инварианты закреплены
// тестом (shareCardBg.test.js).
const BG_TOKEN = '__SHARE_CARD_BG__';
// Элемент фона целиком (для удаления, когда подложки нет). Токен — единственный
// маркер; `[^>]*` с обеих сторон снимает весь самозакрывающийся <image .../>.
const BG_IMG_RE = new RegExp(`<image[^>]*${BG_TOKEN}[^>]*/>`);

// Пустая картинка: валидный пустой SVG в data-URI. Нужна ПРЕВЬЮ, где фон
// меняется не пересборкой строки, а записью `href` в уже разобранный элемент
// (см. `blankCardBg`): элемент обязан существовать с самого начала, но до
// выбора подложки не должен ни рисовать, ни ходить в сеть. `data:,` для этого
// не годится — браузер считает его битой картинкой и пишет ошибку в консоль.
export const CARD_BG_BLANK = "data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg'/%3E";

/**
 * SVG карточки с ПУСТЫМ фоном-местом: токен подменяется на пустую картинку,
 * элемент остаётся. Это форма кадра для ПРЕВЬЮ, и разница с `applyCardBg`
 * принципиальная, а не косметическая.
 *
 * Превью вставляет кадр в документ разметкой (`dangerouslySetInnerHTML`), и
 * новая строка = ПОЛНЫЙ ПЕРЕ-РАЗБОР: все текстовые узлы уничтожаются и
 * создаются заново ради одной картинки. Замер на iOS 26 (Sentry, TRIPLANIO-2Y):
 * при первом разборе строка маршрута имеет верные ширины 237/171, после
 * пере-разбора — НОЛЬ, и названия городов пропадают. Поэтому кадр превью
 * разбирается ОДИН раз, а подложка потом ездит атрибутом `href`.
 *
 * Финальная карточка растеризуется целой строкой — там пересборка и уместна, и
 * `applyCardBg` остаётся её дверью.
 */
export function blankCardBg(svg) {
  if (!svg) return svg;
  return svg.replace(BG_TOKEN, () => CARD_BG_BLANK);
}

/** SVG карточки с подложкой: непустой bgDataUri встаёт фоном, пустой — фон
 *  удаляется (прозрачно). Реплейсер-ФУНКЦИЯ: подстановка дословная (спецпаттерны
 *  String.replace вроде `$&` не интерпретируются). */
export function applyCardBg(svg, bgDataUri) {
  if (!svg) return svg;
  if (!bgDataUri) return svg.replace(BG_IMG_RE, '');
  return svg.replace(BG_TOKEN, () => bgDataUri);
}
