/**
 * СВАЙП-ЗАКРЫТИЕ КАРТОЧКИ — ЧИСТОЕ ПРАВИЛО (без DOM).
 *
 * ★ ЗАЧЕМ ОТДЕЛЬНО — та же причина, что у `sheetDetents.js`: у этих правил нет
 * скриншота. «С какого смещения отпускание закрывает», «считается ли бросок»,
 * «куда улететь» — ошибка в любом выглядит как жест, который не сработал, или
 * как карточка, уехавшая не туда. Такое ловится пальцем на устройстве и поздно.
 * Чистые функции без импортов бегут в `node --test`; компоненту остаётся жест и
 * DOM.
 *
 * ★ ОСЬ ВЫБИРАЕТСЯ ОДИН РАЗ. Тот же осевой замок, что у шита (`gestureOwner`):
 * решение принимается по первым пикселям и дальше НЕ пересматривается. Иначе
 * диагональный свайп на середине хода перескакивает с оси на ось, и карточка
 * дёргается — ровно то, чего нет ни у одного системного тоста.
 *
 * ★ ВНИЗ ЗАКРЫТИЯ НЕТ, И ЭТО НЕ ЗАБЫВЧИВОСТЬ. На телефоне дека тостов прижата к
 * ВЕРХНЕМУ краю и растёт вниз (`app.css`, мобильный блок): «вниз» ведёт вглубь
 * экрана, к содержимому, а не за край. Уводить карточку туда значило бы тащить
 * её ПОВЕРХ контента, чтобы потом она исчезла в никуда. Поэтому разрешены три
 * направления — вверх, влево, вправо, — а тяга вниз гасится в ноль (упор).
 */

/** Порог намерения: до него жеста нет, это ещё тап. */
export const SWIPE_INTENT_PX = 6;

/**
 * Дистанция, после которой отпускание закрывает.
 *
 * Не «половина ширины»: у тоста ширина зависит от экрана, а ощущение свайпа —
 * нет. Абсолютное число даёт один и тот же жест на 320 и на 430 px.
 */
export const SWIPE_COMMIT_PX = 56;

/** Скорость на отпускании (px/мс), выше которой закрывает БРОСОК — на любой дистанции. */
export const SWIPE_FLICK_VELOCITY = 0.35;

/** Сколько летит карточка за край. Публикуется в CSS каналом `--sw-exit`. */
export const SWIPE_EXIT_MS = 200;

/** Запас за краем, чтобы карточка ушла целиком, а не легла кромкой на границу. */
const EXIT_GAP_PX = 32;

/**
 * Ось жеста или `null`, пока намерение не набрано.
 *
 * Сравнение строгое (`>`): на идеальной диагонали выигрывает ВЕРТИКАЛЬ. Выбор
 * не случайный — вертикаль здесь единственное направление с упором (вниз
 * нельзя), поэтому неверно угаданная вертикаль максимум ничего не сделает, а
 * неверно угаданная горизонталь увезёт карточку с экрана.
 *
 * @param {number} dx смещение пальца, + вправо
 * @param {number} dy смещение пальца, + вниз
 * @returns {'x' | 'y' | null}
 */
export function swipeAxis(dx, dy) {
  if (Math.abs(dx) < SWIPE_INTENT_PX && Math.abs(dy) < SWIPE_INTENT_PX) return null;
  return Math.abs(dx) > Math.abs(dy) ? 'x' : 'y';
}

/**
 * Куда сдвинуть карточку прямо сейчас: палец ведёт её 1:1 по выбранной оси.
 *
 * По второй оси смещения нет вовсе — это и есть замок. Тяга вниз обрезается в
 * ноль: карточка упирается, вместо того чтобы уезжать в контент.
 *
 * @param {'x'|'y'|null} axis
 * @param {number} dx
 * @param {number} dy
 * @returns {{ x: number, y: number }} px
 */
export function swipeOffset(axis, dx, dy) {
  if (axis === 'x') return { x: dx, y: 0 };
  if (axis === 'y') return { x: 0, y: Math.min(0, dy) };
  return { x: 0, y: 0 };
}

/**
 * Закрывать ли на отпускании и в какую сторону.
 *
 * Две независимые причины закрыть: дотянул (`SWIPE_COMMIT_PX`) ИЛИ бросил
 * (`SWIPE_FLICK_VELOCITY`). Только дистанции мало — быстрый короткий свайп,
 * которым и пользуются, «не срабатывал» бы; только скорости мало — медленная
 * осознанная тяга через полэкрана обязана закрыть.
 *
 * Направление броска берётся у СКОРОСТИ, а не у смещения: палец мог уехать
 * вправо и вернуться, и закрыть должно то, куда он летел в момент отпускания.
 *
 * @param {{ axis: 'x'|'y'|null, dx: number, dy: number, vx?: number, vy?: number }} p
 * @returns {'up' | 'left' | 'right' | null}
 */
export function swipeCommit({ axis, dx, dy, vx = 0, vy = 0 }) {
  if (axis === 'x') {
    if (Math.abs(dx) >= SWIPE_COMMIT_PX) return dx > 0 ? 'right' : 'left';
    if (Math.abs(vx) >= SWIPE_FLICK_VELOCITY) return vx > 0 ? 'right' : 'left';
    return null;
  }
  if (axis === 'y') {
    // Вверх — и только вверх: у направления вниз закрытия нет, значит нет и
    // броска вниз. Условие разбито на две строки не для красоты: знаки «больше»
    // и «меньше» на одной строке сканер i18n читает как JSX-текст (та же
    // ловушка описана у разбора броска в `PeekSheet`).
    if (dy <= -SWIPE_COMMIT_PX) return 'up';
    if (vy <= -SWIPE_FLICK_VELOCITY) return 'up';
    return null;
  }
  return null;
}

/**
 * Смещение, на котором карточка гарантированно за краем.
 *
 * По горизонтали хватает собственной ширины с запасом: дека вписана в экран с
 * отступами, поэтому уехать на свою ширину = уйти целиком. По вертикали так
 * НЕ работает: карточка стоит не у самого верха (перед ней могут лежать другие
 * карточки деки), поэтому расстояние считается от её НИЖНЕЙ кромки до верха
 * вьюпорта — иначе карточка из середины деки остановилась бы на виду.
 *
 * @param {'up'|'left'|'right'|null} dir
 * @param {{ width?: number, bottom?: number }} rect ширина карточки и её нижняя
 *   кромка в координатах вьюпорта (`getBoundingClientRect`)
 * @returns {{ x: number, y: number }} px
 */
export function swipeExit(dir, { width = 0, bottom = 0 } = {}) {
  if (dir === 'left') return { x: -(width + EXIT_GAP_PX), y: 0 };
  if (dir === 'right') return { x: width + EXIT_GAP_PX, y: 0 };
  if (dir === 'up') return { x: 0, y: -(bottom + EXIT_GAP_PX) };
  return { x: 0, y: 0 };
}
