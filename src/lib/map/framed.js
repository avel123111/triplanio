// @ts-check

/**
 * «КАРТУ УЖЕ КАДРИРОВАЛИ» — СОСТОЯНИЕ ИНСТАНСА, А НЕ КОМПОНЕНТА.
 *
 * ★ Зачем. Первая посадка камеры на экране идёт СКАЧКОМ (`duration: 0`), и для
 * холодной загрузки это правильно: анимировать въезд в кадр не из чего, карта
 * только что родилась. Но экраны с картой сменяют друг друга на ОДНОМ живом
 * инстансе (`MapProvider` переносит его DOM-узел между слотами, см. там), а
 * счётчик «кадрировал ли я уже» жил в `useRef` компонента — то есть при смене
 * экрана обнулялся. Живая, уже кадрированная карта получала повторный
 * `duration: 0` и резала кадр встык. Ровно это видно на переходе
 * «создал трип → открыть трип»: холст тот же, маршрут тот же, а камера дёргается.
 *
 * ★★ Почему WeakMap на инстансе, а не модульная переменная: карта — синглтон,
 * живущий дольше экранов, но НЕ дольше страницы; привязав факт к инстансу, мы
 * получаем правильный ответ и после пересоздания карты (перезагрузка, смена
 * стиля), и не держим её от сборки. Тот же приём и по той же причине, что у
 * отступов камеры — `lib/map/insets.js`.
 *
 * ★★★ Границы. Здесь ТОЛЬКО факт «камеру уже ставили по месту», без ответа на
 * вопрос «по какому именно». Хранить ещё и цель было бы враньём: камеру двигают
 * и фокус панели, и палец пользователя, и оверлей отелей — ни один из них сюда
 * не пишет, поэтому сохранённая цель протухала бы молча. Факт же
 * монотонен: единожды кадрированная карта кадрированной и остаётся.
 */

const framed = new WeakMap();

/** Кадрировали ли эту карту хоть раз за жизнь инстанса. @param {any} map */
export function hasFramed(map) {
  return !!map && framed.get(map) === true;
}

/** Отметить, что камеру поставили по месту. @param {any} map */
export function markFramed(map) {
  if (map) framed.set(map, true);
}
