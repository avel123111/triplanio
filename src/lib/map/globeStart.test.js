import test from 'node:test';
import assert from 'node:assert/strict';
import { GLOBE_DETAIL_ZOOM, startGlobeZoom } from './globeStart.js';

const air = { top: 32, right: 40, bottom: 32, left: 40 };
const panel = (px) => ({ top: 0, right: 0, bottom: 0, left: px });

// Холст = свободное окно, поэтому это реальные размеры холста на каждом детенте.
const CANVASES = [[430, 770], [430, 288], [490, 460], [390, 720], [1440, 900], [1280, 700]];

test('★★ зум НИКОГДА не падает ниже порога детализации', () => {
  // Ниже него Standard не рисует ни стран, ни береговой линии — шар становится
  // одноцветным диском. Это выглядит как «сломано», а не как «мелко», и именно
  // так дефект и приезжал со скринов.
  for (const [W, H] of CANVASES) {
    for (const p of [0, 550]) {
      const z = startGlobeZoom({ W, H, insets: panel(p) });
      assert.ok(z >= GLOBE_DETAIL_ZOOM, `${W}x${H}, панель ${p} → ${z.toFixed(2)}`);
    }
  }
});

test('★★★ ШАР ЗАКРЫВАЕТ ВИДИМОЕ ОКНО ЦЕЛИКОМ — края планеты в кадре не бывает', () => {
  // ГЛАВНЫЙ инвариант модуля. Планета, видимая целиком, — это диск с ободком
  // посреди заливки; на скриншотах он читается как «круги вокруг глобуса», и
  // претензия повторялась трижды. Накрываем ПО ДИАГОНАЛИ: шар, поставленный в
  // центр окна отступом камеры, обязан достать все четыре угла — диаметра в
  // высоту мало, углы остаются открытыми, и «круги» возвращаются именно там.
  const diam = (W, H, insets) => (512 * (2 ** startGlobeZoom({ W, H, insets }))) / Math.PI;
  for (const [W, H] of [[446, 600], [390, 720], [430, 770], [1440, 900], [1280, 700], [360, 640]]) {
    for (const bottom of [0, 110, 226, 505, 640]) {      // шит на телефоне
      for (const left of [0, 550, 620]) {                 // панель на десктопе
        const visW = W - left;
        const visH = H - bottom;
        // Условие разбито на строки не для красоты: знаки «больше» и «меньше»
        // на одной строке сканер i18n читает как JSX-текст.
        if (visW <= 0) continue;
        if (visH <= 0) continue;
        const insets = { top: 0, right: 0, bottom, left };
        assert.ok(diam(W, H, insets) >= Math.hypot(visW, visH),
          `${W}x${H}, шит ${bottom}, панель ${left} → шар ${Math.round(diam(W, H, insets))} при диагонали окна ${Math.round(Math.hypot(visW, visH))}`);
      }
    }
  }
});

test('★ меньше окно — меньше шар (накрывать нужно меньше)', () => {
  const z = (W, H, p = 0) => startGlobeZoom({ W, H, insets: panel(p) });
  assert.ok(z(390, 720) < z(1440, 900), 'десктоп крупнее телефона');
  assert.ok(z(1440, 900, 550) < z(1440, 900, 0), 'шире панель — меньше окно, меньше шар');
  assert.ok(z(1440, 900, 1100) < z(1440, 900, 550), 'очень широкая панель уже решает');
});

test('★ шар КРУПНЕЕ холста, и это не регресс, а само правило', () => {
  // Прежний тест требовал обратного («не крупнее холста, зум ниже 1.8») — он
  // принадлежал вписыванию, при котором планета видна целиком. Ровно это и
  // давало край шара в кадре. Накрытие требует шара БОЛЬШЕ окна, иначе углы
  // остаются открытыми; поэтому здесь проверяется противоположное.
  const z = startGlobeZoom({ W: 430, H: 770 });
  const diam = (512 * (2 ** z)) / Math.PI;
  assert.ok(diam > 770, `шар ${Math.round(diam)} при холсте 430x770`);
});

test('немеряный холст и абсурд — безопасное значение, не NaN и не пол', () => {
  for (const bad of [{ W: 0, H: 0 }, { W: 1440, H: 0 }, {}]) {
    const z = startGlobeZoom({ ...bad });
    assert.ok(Number.isFinite(z) && z >= GLOBE_DETAIL_ZOOM, JSON.stringify(bad));
  }
  assert.ok(startGlobeZoom({ W: 20000, H: 20000, air }) <= 5);
});
