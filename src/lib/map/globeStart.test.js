import test from 'node:test';
import assert from 'node:assert/strict';
import { GLOBE_DETAIL_ZOOM, startGlobeZoom } from './globeStart.js';

const air = { top: 32, right: 40, bottom: 32, left: 40 };
const panel = (px) => ({ top: 0, right: 0, bottom: 0, left: px });

// Холст = свободное окно, поэтому это реальные размеры холста на каждом детенте.
const CANVASES = [[430, 770], [430, 288], [490, 460], [390, 720], [1440, 900], [1280, 700]];

test('★★ зум НИКОГДА не падает ниже порога детализации', () => {
  // Ниже него Standard не рисует ни стран, ни береговой линии — шар становится
  // одноцветным диском. Это выглядит как «сломано», а не как «мелко», и именно
  // так дефект и приезжал со скринов.
  for (const [W, H] of CANVASES) {
    for (const p of [0, 550]) {
      const z = startGlobeZoom({ W, H, insets: panel(p), air });
      assert.ok(z >= GLOBE_DETAIL_ZOOM, `${W}x${H}, панель ${p} → ${z.toFixed(2)}`);
    }
  }
});

test('★★★ ШАР НИКОГДА НЕ БЫВАЕТ УЖЕ СВОЕГО ОКНА — иначе это «шарик в пустоте»', () => {
  // ГЛАВНЫЙ инвариант этого модуля, и он дороже монотонности ниже. Диаметр шара
  // зависит ТОЛЬКО от зума (512·2^z/π), а окно режет шит: вписывание в короткое
  // окно даёт диск заметно уже него, то есть космос по бокам. Ровно это на
  // скриншотах читается как «круги вокруг глобуса», и ровно это правило их
  // запрещает: стал уже — закрываем окно (cover).
  const d = (W, H, p = 0, b = 0) => {
    const insets = { ...panel(p), bottom: b };
    return (512 * (2 ** startGlobeZoom({ W, H, insets, air }))) / Math.PI;
  };
  const visW = (W, p) => W - p - air.left - air.right;
  // Телефон: холст во всю площадь, шит режет высоту отступом снизу.
  for (const [W, H, sheet] of [[430, 770, 505], [390, 720, 490], [430, 770, 640], [446, 600, 505]]) {
    assert.ok(d(W, H, 0, sheet) >= 0.9 * visW(W, 0),
      `${W}x${H}, шит ${sheet} → шар ${Math.round(d(W, H, 0, sheet))} при окне ${visW(W, 0)}`);
  }
  // Десктоп: панель режет ширину — окно остаётся высоким, работает вписывание.
  for (const [W, H, p] of [[1440, 900, 550], [1280, 700, 550], [1440, 900, 0]]) {
    assert.ok(d(W, H, p) >= 0.9 * visW(W, p),
      `${W}x${H}, панель ${p} → шар ${Math.round(d(W, H, p))} при окне ${visW(W, p)}`);
  }
});

test('★ ВНУТРИ вписывания шар не растёт от уменьшения места', () => {
  // Монотонность держится, пока шар вписывается; на переходе в cover она
  // НАМЕРЕННО нарушается — короткое окно требует БОЛЬШЕГО шара, а не меньшего.
  // Поэтому здесь только высокие окна, где режим один и тот же.
  const z = (W, H, p = 0) => startGlobeZoom({ W, H, insets: panel(p), air });
  assert.ok(z(390, 720) < z(1440, 900), 'десктоп крупнее телефона');
  assert.ok(z(1440, 900, 550) <= z(1440, 900, 0), 'шире панель — не крупнее шар');
  assert.ok(z(1440, 900, 1100) < z(1440, 900, 0), 'очень широкая панель уже решает');
});

test('★ шар не крупнее холста: на телефоне при zoom 2 он был ~700 px при экране 430', () => {
  // Регресс, на который ругались: «дефолтный глобус сильно приближен».
  // Ограничитель — 0.92 ширины холста, поэтому зум обязан быть заметно ниже 2.
  assert.ok(startGlobeZoom({ W: 430, H: 770, air }) < 1.8);
});

test('немеряный холст и абсурд — безопасное значение, не NaN и не пол', () => {
  for (const bad of [{ W: 0, H: 0 }, { W: 1440, H: 0 }, {}]) {
    const z = startGlobeZoom({ ...bad, air });
    assert.ok(Number.isFinite(z) && z >= GLOBE_DETAIL_ZOOM, JSON.stringify(bad));
  }
  assert.ok(startGlobeZoom({ W: 20000, H: 20000, air }) <= 5);
});
