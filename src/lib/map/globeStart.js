/**
 * СТАРТОВЫЙ ВИД ГЛОБУСА — размер шара, когда маршрута ещё нет (TRIP-422).
 *
 * ★ ОДНО ПРАВИЛО НА ВСЕ ЭКРАНЫ, БЕЗ ВЕТКИ «ТЕЛЕФОН». Размер шара mapbox считает
 * от высоты ХОЛСТА, а холст всегда во всю площадь шелла — поэтому вписывать
 * нужно в СВОБОДНОЕ ОКНО, то есть в холст МИНУС отступ камеры. Ровно это и
 * делают `insets`/`air` ниже, и ровно поэтому отдельной телефонной константы
 * здесь нет: закрытая площадь на телефоне приезжает тем же `insets.bottom`,
 * каким на десктопе приезжает `insets.left`.
 *
 * ⚠️ Шар ломали дважды, и оба раза корнем было то, что вычитать было НЕЧЕГО:
 * закрытую площадь на телефоне забирал сам холст, отступ приходил нулевым, и
 * «подгонка под свободное окно» вырождалась в подгонку под холст. Если шар снова
 * не попадает в окно — первым делом проверь, что `insets` доехали непустыми.
 *
 * ★★ ФОРМУЛА — РУЧКА, А НЕ ФИЗИКА, И ВРЁТ В МЕНЬШУЮ СТОРОНУ. Замер настоящей
 * камерой (headless, globe, холст 730×840, горизонт через `map.project`):
 * zoom 1.0 → 394 против 326 по формуле (+21 %), zoom 2.0 → 701 против 652 (+7 %).
 * Ошибка непостоянна, множителем не лечится. Инвертировать нельзя.
 *
 * ★★★ ПОЛ ЗУМА ПРИВЯЗАН К ДЕТАЛИЗАЦИИ, А НЕ К КРУГЛОМУ ЧИСЛУ. Ниже него стиль
 * Standard перестаёт рисовать страны и береговую линию, и шар превращается в
 * одноцветный диск — дефект, который выглядит как «сломано», а не как «мелко».
 */

/** @typedef {{ top: number, right: number, bottom: number, left: number }} Box */

const ZERO = { top: 0, right: 0, bottom: 0, left: 0 };

/** Ниже этого зума Standard перестаёт рисовать страны — одноцветный диск. */
export const GLOBE_DETAIL_ZOOM = 1;

/** Центр стартового вида: Атлантика, чуть выше экватора. */
export const GLOBE_START_CENTER = [0, 20];

/**
 * @param {{ W?: number, H?: number, insets?: Box, air?: Box }} [p]
 *   `W`/`H` — размеры ХОЛСТА; `insets` — закрытая площадь камеры (панель).
 * @returns {number} зум
 */
export function startGlobeZoom({ W = 0, H = 0, insets = ZERO, air = ZERO } = {}) {
  if (!(H > 0) || !(W > 0)) return 2.4;
  const visW = Math.max(200, W - insets.left - insets.right - air.left - air.right);
  const visH = Math.max(200, H - insets.top - insets.bottom - air.top - air.bottom);
  const targetD = Math.min(0.85 * visH, 0.92 * visW);
  return Math.max(GLOBE_DETAIL_ZOOM, Math.min(5, Math.log2((targetD * Math.PI) / 512)));
}
