/**
 * СТАРТОВЫЙ ВИД ГЛОБУСА — размер шара, когда маршрута ещё нет (TRIP-422).
 *
 * ★ ОДНО ПРАВИЛО НА ВСЕ ЭКРАНЫ, БЕЗ ВЕТКИ «ТЕЛЕФОН». Размер шара mapbox считает
 * от высоты ХОЛСТА, а холст всегда во всю площадь шелла — поэтому вписывать
 * нужно в СВОБОДНОЕ ОКНО, то есть в холст МИНУС отступ камеры. Ровно это и
 * делают `insets` ниже, и ровно поэтому отдельной телефонной константы
 * здесь нет: закрытая площадь на телефоне приезжает тем же `insets.bottom`,
 * каким на десктопе приезжает `insets.left`.
 *
 * ⚠️ Шар ломали дважды, и оба раза корнем было то, что вычитать было НЕЧЕГО:
 * закрытую площадь на телефоне забирал сам холст, отступ приходил нулевым, и
 * «подгонка под свободное окно» вырождалась в подгонку под холст. Если шар снова
 * не попадает в окно — первым делом проверь, что `insets` доехали непустыми.
 *
 * ★★ ФОРМУЛА — РУЧКА, А НЕ ФИЗИКА, И ВРЁТ В МЕНЬШУЮ СТОРОНУ. Замер настоящей
 * камерой (headless, globe, холст 730×840, горизонт через `map.project`):
 * zoom 1.0 → 394 против 326 по формуле (+21 %), zoom 2.0 → 701 против 652 (+7 %).
 * Ошибка непостоянна, множителем не лечится. Инвертировать нельзя.
 *
 * ★★★ ПОЛ ЗУМА ПРИВЯЗАН К ДЕТАЛИЗАЦИИ, А НЕ К КРУГЛОМУ ЧИСЛУ. Ниже него стиль
 * Standard перестаёт рисовать страны и береговую линию, и шар превращается в
 * одноцветный диск — дефект, который выглядит как «сломано», а не как «мелко».
 */

/** @typedef {{ top: number, right: number, bottom: number, left: number }} Box */

const ZERO = { top: 0, right: 0, bottom: 0, left: 0 };

/** Ниже этого зума Standard перестаёт рисовать страны — одноцветный диск. */
export const GLOBE_DETAIL_ZOOM = 1;

/**
 * ★★★ ШАР ЗАКРЫВАЕТ ВИДИМОЕ ОКНО ЦЕЛИКОМ. НЕ ВПИСЫВАЕТСЯ В НЕГО — ЗАКРЫВАЕТ.
 *
 * Пока планета помещалась в кадр целиком, вокруг неё был виден КРАЙ ШАРА и
 * пространство за ним. Это не наш фон: канвас mapbox там непрозрачен (замер
 * чтением пикселей с `preserveDrawingBuffer`: угол = rgb(4,22,42) на ночном
 * пресете), космос рисует сам движок, а от темы приложения он менялся потому,
 * что вместе с темой мы переключаем движку `day`/`night`. Но причина у дефекта
 * одна независимо от того, чья кисть: планета, видимая целиком, — это диск с
 * ободком посреди заливки, и на экране приложения он читается как артефакт.
 *
 * Поэтому кадрируем ПО ДИАГОНАЛИ свободного окна: шар, поставленный в его
 * центр отступом камеры, гарантированно накрывает все четыре угла, и края
 * планеты не видно ни на одном детенте, ни в одной теме. Всё, что за окном
 * (под шитом, под панелью), значения не имеет — его не видно.
 *
 * ⚠️ Диагональ, а не `max(ширина, высота)`: шар диаметром в высоту холста
 * оставляет непокрытыми УГЛЫ, и «круги» возвращаются именно там.
 */
const COVER_MARGIN = 1.02;

/** Центр стартового вида: Атлантика, чуть выше экватора. */
export const GLOBE_START_CENTER = [0, 20];

/**
 * @param {{ W?: number, H?: number, insets?: Box }} [p]
 *   `W`/`H` — размеры ХОЛСТА; `insets` — закрытая площадь камеры (панель на
 *   десктопе, шит на телефоне). Остаток — ВИДИМОЕ окно, его и накрываем.
 * @returns {number} зум
 */
export function startGlobeZoom({ W = 0, H = 0, insets = ZERO } = {}) {
  if (!(H > 0) || !(W > 0)) return 2.4;
  // Свободное окно считаем ЧЕСТНО, без пола в 200px: пол врал ровно там, где
  // окно короткое, и подменял ответ «шар сюда не помещается» ответом
  // «помещается, просто маленький».
  // ВОЗДУХ кадра здесь не вычитается намеренно: он поле ВОКРУГ содержимого, а
  // накрывать нужно всё окно до края — поле внутри шара смысла не имеет.
  const visW = Math.max(0, W - insets.left - insets.right);
  const visH = Math.max(0, H - insets.top - insets.bottom);
  if (!(visW > 0) || !(visH > 0)) return 2.4;
  // Запас 2%: ровно по диагонали шар касается углов, а его край — не линия, а
  // мягкий градиент атмосферы, и в точке касания он читается как засветка.
  const targetD = Math.hypot(visW, visH) * COVER_MARGIN;
  return Math.max(GLOBE_DETAIL_ZOOM, Math.min(5, Math.log2((targetD * Math.PI) / 512)));
}
