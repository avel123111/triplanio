// @ts-check
// Экран запуска: удержание и снятие (TRIP-478).
//
// Сам splash живёт в `index.html` — инлайновой разметкой и инлайновыми стилями,
// потому что до бандла ничего другого работать не может. Отсюда им только
// УПРАВЛЯЮТ: приложение — единственный, кто знает, готов ли он показать
// содержимое.
//
// ПОЧЕМУ УДЕРЖАНИЕ, А НЕ ПРОСТО «СНЯТЬ ПРИ МАУНТЕ». До TRIP-478 человек ждал
// дважды: пустое полотно, пока едет бандл, и полноэкранный `<AppLoading>` —
// пока грузится авторизация, а у залогиненного ещё и словарь. Уйди splash по
// маунту React, второе ожидание вернулось бы на экран, то есть задача не была
// бы сделана. Поэтому право «ещё рано» принадлежит не списку условий (их
// четыре, и они разъедутся с ветками при первой правке), а САМОМУ ОЖИДАНИЮ:
// `<AppLoading>` держит splash, пока смонтирован. Появится пятое ожидание —
// оно отрисуется тем же компонентом и попадёт под правило само.
const FADE_MS = 320;   // = transition .32s у `.splash` в index.html (числа связаны с обеих сторон)

// Нижняя граница показа. Знак собирается 0,95 с; уходить на 150-й миллисекунде
// (бандл и сессия из кэша) значит показать вспышку логотипа — хуже, чем не
// показывать вовсе. 700 мс = почти вся анимация; выше этого начинается уже
// заметная задержка интерактивности, поэтому досматривать до конца не ждём.
// `performance.now()` отсчитывается от начала навигации, то есть меряет ровно
// то, что видел человек, а не время от вызова.
const MIN_VISIBLE_MS = 700;

let holds = 0;         // сколько ожиданий сейчас на экране
let asked = false;     // приложение уже сказало «готово»
let done = false;      // снятие уже запущено

function run() {
  if (done) return;
  done = true;
  const el = document.getElementById('splash');
  if (!el) return;
  setTimeout(() => {
    el.setAttribute('data-out', '');
    setTimeout(() => el.remove(), FADE_MS);
  }, Math.max(0, MIN_VISIBLE_MS - performance.now()));
}

/**
 * Удерживает экран запуска, пока ожидание на экране. Зовётся из `<AppLoading>`
 * при монтировании; возвращает функцию снятия удержания (её и возвращает
 * `useEffect`). Снятие последнего удержания снимает splash, если приложение
 * уже отчиталось о готовности.
 * @returns {() => void}
 */
export function holdSplash() {
  holds += 1;
  return () => {
    holds -= 1;
    if (holds === 0 && asked) run();
  };
}

/**
 * Приложение готово показать содержимое. Пока держится хоть одно ожидание,
 * снятие откладывается до его конца. Идемпотентна.
 * @param {{ crashed?: boolean }} [opts] `crashed` — снять немедленно, не глядя
 *   на удержания: экран краха обязан быть виден, даже если ожидание осталось
 *   висеть в размонтированном поддереве.
 */
export function hideSplash(opts) {
  asked = true;
  if (opts?.crashed) holds = 0;
  if (holds === 0) run();
}
