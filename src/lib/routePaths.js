/**
 * ★★★ У КАКИХ СТРАНИЦ ЕСТЬ АДРЕС НА КАЖДЫЙ ЯЗЫК (TRIP-533).
 *
 * Это ВСЯ зона-как-страницы, а не подмножество. Локаль — свойство ДЕРЕВА
 * маршрутов, и внутри дерева она обязана быть единообразной: так устроены
 * Figma (`/`, `/es-la/`, и логин внутри того же дерева) и Notion (`/`, `/es`, а
 * на границе приложения локаль отбрасывается совсем). Дерева, где часть страниц
 * с локалью, а часть без, нет ни у кого — и не случайно.
 *
 * ★ ЧТО БЫЛО И ПОЧЕМУ ЭТО БЫЛ КОРЕНЬ. Здесь лежали только `/` и демо, а причина
 * записывалась так: «префикс — это имя готового файла, а у входа такого файла
 * нет и быть не может». Это неверно: префикс выпечки не требует — таблица
 * маршрутов зоны и так сопоставляется по пути БЕЗ префикса (`<Routes location>`
 * в `App.jsx`), то есть `/es/login` работал бы и без единого нового маршрута.
 * Склеены были две независимые вещи — «испечена ли страница» (вопрос сборки) и
 * «есть ли у неё адрес на язык» (вопрос адресной модели), — и ограничение
 * ОБЪЁМА РАБОТ записалось как закон домена.
 *
 * Ценой была не одна ссылка, а целый класс дефектов: пока `localeOf` мог
 * вернуть `null`, язык падал на слой устройства, любой адрес, который язык
 * УТВЕРЖДАЕТ (`/`), его перебивал, а для молчащих страниц приходилось держать
 * второй механизм (`?lang=`). Теперь адрес зоны говорит всегда, и лестница
 * языка схлопывается до одного слоя.
 *
 * ★ ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО — `/public/trip/:id` и `/join/:token`. Это не
 * страницы сайта, а ОДНОРАЗОВЫЕ CAPABILITY-АДРЕСА: ссылку шлёт человек
 * человеку, и язык у неё принадлежит ПОЛУЧАТЕЛЮ, а не отправителю. Языковой
 * адрес там навязывал бы язык того, кто поделился. Это правило домена, а не
 * недоделка, — тем оно и отличается от прежней склейки с выпечкой.
 */
export const LOCALISED_PAGES = ['/', DEMO_PATH, '/login', '/reset-password', '/terms', '/privacy'];

/**
 * ★ У КАКИХ СТРАНИЦ ЯЗЫКОВЫЕ ВЕРСИИ ОБЪЯВЛЯЮТСЯ ПОИСКУ.
 *
 * Подмножество `LOCALISED_PAGES`, и вопрос у него ДРУГОЙ: не «существует ли
 * адрес на язык» (существует у всех), а «обещаем ли мы краулеру три версии
 * одной страницы». Из него выводятся hreflang, карта сайта и состав выпечки.
 *
 * Почему остальные сюда не попадают:
 *   · `/login`, `/reset-password` — переведены, но искать их незачем;
 *     объяви мы три версии — получили бы три почти одинаковых адреса,
 *     конкурирующих между собой. Их языковые формы канонизируются на
 *     беспрефиксную (`SiteZone`).
 *   · `/terms`, `/privacy` — ТЕКСТ английский по решению (TRIP-465 §7):
 *     договор правится целиком как текст, а не по строкам через `t()`. Языковые
 *     адреса у них есть (обвязка-то переведена), но обещать поиску русскую
 *     версию, отдавая английскую прозу, нельзя — это и есть та ложь, ради
 *     которой их когда-то лишили языкового адреса целиком. Правильный ответ
 *     мельче: сам документ несёт `lang="en"` на своём элементе, страница —
 *     язык обвязки, hreflang нет, canonical на беспрефиксную форму.
 */
export const HREFLANG_PAGES = ['/', DEMO_PATH];

/**
 * ★ ЯЗЫК ЖИВЁТ В АДРЕСЕ, И АНГЛИЙСКИЙ ЖИВЁТ БЕЗ ПРЕФИКСА (TRIP-520).
 *
 * `/` — канонический английский адрес, `/es/…` и `/ru/…` — самостоятельные
 * страницы своих языков. Английский без префикса не «привилегия», а следствие:
 * это адрес, на который ведут ВСЕ уже существующие ссылки на нас — проверка
 * Google, карта сайта, `llms.txt`, теги соцсетей, чужие упоминания. Заведи мы
 * `/en/`, и та же страница получила бы два адреса: поисковик считает их
 * дублями и делит вес, а переключатель языка перестаёт знать, какой из них
 * настоящий. `/en/*` поэтому не существует как страница — платформа отвечает на
 * него постоянным переездом на бесперфиксный адрес (`vercel.json`).
 *
 * Список ЛИТЕРАЛОМ, а не выводом из `LANGUAGES`: обратный импорт замкнул бы
 * цикл (`translations` → `routePaths` → `translations`), а этот модуль обязан
 * открываться голым `node --test` и его же читает edge-middleware. Разъехаться
 * с настоящим списком языков не даёт `routePaths.test.js` — та же связка
 * «литерал + тест», которой живёт пре-пейнт скрипт в `index.html`.
 */
export const PREFIXED_LANGS = ['es', 'ru'];

/**
 * Разобрать адрес на язык и путь без языка.
 *
 * Голый префикс (`/es`) и префикс со слэшем (`/es/`) — ОДИН адрес, главная
 * своего языка: иначе `/es` провалилось бы в 404, а именно так эту ссылку и
 * набирают руками.
 *
 * @param {string} pathname
 * @returns {{ lang: 'es'|'ru'|null, path: string }} `lang` = null у английского
 */
export function splitLangPath(pathname) {
  const seg = pathname.split('/')[1];
  if (!PREFIXED_LANGS.includes(seg)) return { lang: null, path: pathname };
  const rest = pathname.slice(seg.length + 1);
  return { lang: seg, path: rest === '' ? '/' : rest };
}

/**
 * Собрать адрес страницы на нужном языке. Обратная к `splitLangPath`.
 *
 * @param {string} lang  код языка; английский (и любой беспрефиксный) отдаёт путь как есть
 * @param {string} path  путь БЕЗ языкового префикса
 * @returns {string}
 */
export function withLangPath(lang, path) {
  if (!PREFIXED_LANGS.includes(lang)) return path;
  return path === '/' ? `/${lang}` : `/${lang}${path}`;
}

/**
 * ★★★ АДРЕС СТРАНИЦЫ НА ЗАДАННОМ ЯЗЫКЕ — ЕДИНСТВЕННОЕ МЕСТО, ГДЕ РЕШАЕТСЯ,
 * НУЖЕН ЛИ ПРЕФИКС (TRIP-533).
 *
 * Отличие от `withLangPath` несущее: тот — СТРОИТЕЛЬ, он прибивает префикс
 * любому пути, потому что решение принимает не он. `withLangPath('ru','/login')`
 * вернёт `/ru/login` — адрес, которого не существует (`isZoneRoute` его не
 * знает). Пока «локализована ли страница» помнил вызыватель, ошибиться можно
 * было в ОБЕ стороны: забыть префикс (язык слетал на переходе) и приклеить
 * лишний (404). Здесь оба случая невозможны по построению — предикат один и он
 * же `LOCALISED_PAGES`.
 *
 * ИДЕМПОТЕНТЕН: сперва снимает уже стоящий префикс, потом ставит нужный. На
 * этом стоят переключатель языка (резолвит на ЧУЖОЙ язык) и клик по логотипу
 * (адрес приезжает абсолютным и уже с префиксом).
 *
 * Хвост (`?query`, `#hash`) сохраняется как есть: якорь `#together` и метка
 * кампании живут в адресе и на резолве теряться не должны.
 *
 * @param {string} path путь, возможно уже с префиксом и хвостом
 * @param {string} lang код языка
 * @returns {string}
 */
export function zoneHref(path, lang) {
  const cut = path.search(/[?#]/);
  const bare = cut === -1 ? path : path.slice(0, cut);
  const tail = cut === -1 ? '' : path.slice(cut);
  const { path: clean } = splitLangPath(bare);
  return (LOCALISED_PAGES.includes(clean) ? withLangPath(lang, clean) : clean) + tail;
}

/**
 * ★★ ЯЗЫК ПО УМОЛЧАНИЮ — ТОТ, ЧТО ЖИВЁТ БЕЗ ПРЕФИКСА.
 *
 * Литералом, а не импортом из `translations.js`: обратный импорт замкнул бы
 * цикл, а этот модуль обязан открываться голым `node --test` и его же читает
 * edge-middleware. Разъехаться с настоящим фолбэком языка не даёт
 * `routePaths.test.js` — та же связка «литерал + тест», что у `PREFIXED_LANGS`.
 */
export const DEFAULT_LANG = 'en';

/**
 * ★★ ЛОКАЛЬ, КОТОРУЮ АДРЕС ОБЯЗУЕТСЯ ПОКАЗАТЬ, — ИЛИ `null`, ЕСЛИ НЕ ОБЯЗУЕТСЯ.
 *
 * Это несущий предикат всей адресной модели, и вопрос у него РОВНО ОДИН:
 * «существует ли у этой страницы отдельный адрес на каждый язык». Не «испечена
 * ли она» — это другой вопрос и другой список (`PRERENDERED_PAGES`).
 *
 * Отвечает он так:
 *   · `/es/…`, `/ru/…`      — префикс назвал язык прямо;
 *   · любая страница зоны   — у неё ЕСТЬ языковые адреса, и беспрефиксный из
 *                             них английский (обычная роль `defaultLocale`);
 *   · всё остальное         — `null`: capability-адрес или экран приложения, у
 *                             них версия ОДНА, адрес про язык молчит, и решает
 *                             посетитель (в приложении — профиль).
 *
 * ПОЧЕМУ У ВОПРОСА СВОЙ СПИСОК, А НЕ ЗАИМСТВОВАННЫЙ. Первая редакция спрашивала
 * здесь `PRERENDERED_PAGES`, то есть выводила «есть ли у страницы адрес на
 * язык» из «испечена ли она». Стоило это живого дефекта: `/terms` и `/privacy`
 * пеклись, языкового адреса тогда не имели, а предикат по ним обещал
 * английский — человек переключал язык на `/terms`, нажимал вкладку «Privacy»,
 * и обвязка молча возвращалась в английскую, потому что смена пути
 * переспрашивала этот предикат.
 *
 * Сегодня языковой адрес у юр-документов ЕСТЬ (TRIP-533), и «английский на
 * беспрефиксной форме» — ответ верный. Но список остаётся своим ровно потому,
 * что вопрос отдельный: смена адресной модели уместилась в ОДНУ строку
 * `LOCALISED_PAGES` и не тронула ни выпечку, ни обещания поиску.
 *
 * @param {string} pathname
 * @returns {'en'|'es'|'ru'|null}
 */
export function localeOf(pathname) {
  const { lang, path } = splitLangPath(pathname);
  if (!LOCALISED_PAGES.includes(path)) return null;
  return lang ?? DEFAULT_LANG;
}

