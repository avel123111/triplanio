// @ts-check

/**
 * Состав ленты слайдов пикера обложки — ЧИСТАЯ функция (TRIP-421).
 *
 * ★ ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Здесь живёт правило, у которого нет скриншота:
 * «что видно в ленте и в каком порядке». Ошибка в нём выглядит как мигание
 * плейсхолдера или как задвоенная миниатюра — то есть замечается глазом и
 * поздно. Чистая функция без импортов бежит в `node --test` и закрывается
 * тестом; в адаптере остаётся только «откуда взялись данные».
 *
 * ★ ГЛАВНОЕ ПРАВИЛО: ТЕКУЩАЯ ОБЛОЖКА — ЧАСТЬ ОТВЕТА, А НЕ ПОСЛЕДСТВИЕ ЗАГРУЗКИ.
 * Её url известен синхронно (приезжает вместе с трипом), поэтому она попадает в
 * список СРАЗУ, ещё до ответа каталога пресетов. Прошлая редакция регистрировала
 * её эффектом и ждала каталог, чтобы не задвоить пресетную обложку, — и экран
 * открывался фоллбеком, потому что до ответа каталога список был пуст. Дубль
 * лечится дедупом ЗДЕСЬ, а не задержкой показа.
 *
 * Порядок: [«без обложки»] · текущая · прежние свои загрузки · каталог.
 * Всё, что уже есть в каталоге, из ведущей группы вычитается — свою позицию в
 * ряду задаёт каталог.
 *
 * `value` — текущая обложка ('' — её нет); `extras` — свои загрузки этой сессии
 * (новые первыми); `presets` — каталог (пуст, пока ответ не приехал); `blank` —
 * показывать ли слайд «без обложки» (пикер открыт без неё).
 *
 * ⚠️ Пояснения — ЗДЕСЬ, а не внутри `@param {{…}}`: текст после свойства
 * обрывает разбор типа, и tsc видит объект из одного поля (поймано typecheck).
 *
 * @param {{ value?: string, extras?: string[], presets?: string[], blank?: boolean }} [p]
 * @returns {string[]} url-ы по порядку ленты; '' = слайд «без обложки»
 */
export function composeCoverSlides({ value = '', extras = [], presets = [], blank = false } = {}) {
  /** @type {string[]} */
  const lead = [];
  const push = (url) => { if (url && !lead.includes(url)) lead.push(url); };

  // Пустая строка — не «значение», а отдельный слайд-состояние, поэтому её
  // добавляет только `blank`: иначе трип без обложки получал бы его дважды.
  if (blank) lead.push('');
  push(value);
  for (const url of extras) push(url);

  return [...lead.filter((url) => url === '' || !presets.includes(url)), ...presets];
}
