// Unit tests for the date-boundary coupling (TRIP-484 §4).
// Run: npm test  (node --test)
//
// Правило связки нельзя проверить скриншотом — у поведения его нет. Гейт здесь:
// чистая функция + этот файл. Каждый кейс — из ручного прохода Pavel по форме.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { endAfterStart, relinkChain, seedChain } from './dateRange.js';

// ── Пара «начало → конец» ────────────────────────────────────────────────────

test('конец позже нового начала — не трогаем', () => {
  assert.equal(endAfterStart('2026-09-01T12:00', '2026-09-02T12:00', '2026-09-05T15:00'), '2026-09-05T15:00');
});

test('начало обогнало конец — конец уезжает вперёд, длительность сохраняется', () => {
  // Двухчасовой перелёт остаётся двухчасовым.
  assert.equal(endAfterStart('2026-09-01T12:00', '2026-09-10T12:00', '2026-09-01T14:00'), '2026-09-10T14:00');
  // Отель на 4 ночи остаётся на 4 ночи (заезд 15:00 → выезд 11:00 пятого дня).
  assert.equal(endAfterStart('2026-09-01T15:00', '2026-09-08T15:00', '2026-09-05T11:00'), '2026-09-12T11:00');
});

test('длительность неизвестна — конец встаёт ровно на начало', () => {
  assert.equal(endAfterStart('', '2026-09-10T12:00', '2026-09-01T14:00'), '2026-09-10T12:00');
});

test('пара уже вывернута — длительность неизвестна, конец встаёт на начало', () => {
  // Конец РАНЬШЕ прежнего начала: «сохранять» тут нечего (это не длительность, а
  // ошибка ввода), поэтому связка не выдумывает срок, а просто чинит порядок.
  assert.equal(endAfterStart('2026-09-05T12:00', '2026-09-10T12:00', '2026-09-01T14:00'), '2026-09-10T12:00');
});

test('пустой конец не выдумывается', () => {
  assert.equal(endAfterStart('2026-09-01T12:00', '2026-09-10T12:00', ''), '');
});

test('дата без времени остаётся датой без времени (страховка)', () => {
  assert.equal(endAfterStart('2026-09-01', '2026-09-10', '2026-09-03'), '2026-09-12');
});

test('перенос через сутки считает настенные часы, а не «дни»', () => {
  // Ночной перелёт 23:30 → 06:40 следующего дня, перенос на неделю вперёд.
  assert.equal(endAfterStart('2026-09-01T23:30', '2026-09-08T23:30', '2026-09-02T06:40'), '2026-09-09T06:40');
});

// ── Цепочка сегментов ────────────────────────────────────────────────────────

const chain = () => ([
  { start: '2026-09-01T10:00', end: '' },   // вылет предзаполнен, прилёт в пересадку — нет
  { start: '', end: '2026-09-01T20:00' },   // прилёт предзаполнен, вылет из пересадки — нет
]);

test('конец сегмента заполняет пустое начало следующего', () => {
  const next = relinkChain(chain(), 0, { end: '2026-09-01T13:00' });
  assert.equal(next[0].end, '2026-09-01T13:00');
  assert.equal(next[1].start, '2026-09-01T13:00');
  assert.equal(next[1].end, '2026-09-01T20:00'); // конец переезда на месте
});

test('конец сегмента толкает уже заполненное, но более раннее начало следующего', () => {
  const links = [
    { start: '2026-09-01T10:00', end: '2026-09-01T13:00' },
    { start: '2026-09-01T15:00', end: '2026-09-01T20:00' },
  ];
  const next = relinkChain(links, 0, { end: '2026-09-01T18:00' });
  assert.equal(next[1].start, '2026-09-01T18:00');
  assert.equal(next[1].end, '2026-09-01T23:00'); // звено уехало ЦЕЛИКОМ: 5 часов перелёта сохранены
});

test('монотонная цепочка останавливает разлив (ничего лишнего не двигаем)', () => {
  const links = [
    { start: '2026-09-01T10:00', end: '2026-09-01T13:00' },
    { start: '2026-09-01T15:00', end: '2026-09-01T20:00' },
    { start: '2026-09-02T09:00', end: '2026-09-02T12:00' },
  ];
  const next = relinkChain(links, 0, { end: '2026-09-01T14:00' });
  assert.equal(next[1].start, '2026-09-01T15:00'); // и так позже — не тронуто
  assert.deepEqual(next[2], links[2]);
});

test('разлив идёт по всей цепочке, пока звенья мешают друг другу', () => {
  const links = [
    { start: '2026-09-01T10:00', end: '2026-09-01T13:00' },
    { start: '2026-09-01T14:00', end: '2026-09-01T16:00' },
    { start: '2026-09-01T17:00', end: '2026-09-01T19:00' },
  ];
  const next = relinkChain(links, 0, { start: '2026-09-01T20:00' });
  assert.equal(next[0].end, '2026-09-01T23:00'); // пара: +3 часа
  assert.equal(next[1].start, '2026-09-01T23:00');
  assert.equal(next[1].end, '2026-09-02T01:00'); // +2 часа
  assert.equal(next[2].start, '2026-09-02T01:00');
  assert.equal(next[2].end, '2026-09-02T03:00');
});

test('вход не мутируется', () => {
  const links = chain();
  const snapshot = JSON.parse(JSON.stringify(links));
  relinkChain(links, 0, { end: '2026-09-01T13:00' });
  assert.deepEqual(links, snapshot);
});

test('правка назад ничего не тянет назад — это дело валидатора, не связки', () => {
  const links = [
    { start: '2026-09-01T10:00', end: '2026-09-01T13:00' },
    { start: '2026-09-01T15:00', end: '2026-09-01T20:00' },
  ];
  const next = relinkChain(links, 1, { start: '2026-09-01T11:00' });
  assert.equal(next[0].end, '2026-09-01T13:00'); // предыдущее звено не тронуто
  assert.equal(next[1].start, '2026-09-01T11:00');
});

// ── Засев цепочки в окне переезда ────────────────────────────────────────────

test('две пересадки: окно делится поровну, стоянка получает свою долю', () => {
  // Дефолты прямого переезда: вылет 12:00, прилёт 15:00. Цепочка из двух звеньев
  // делит их на три равные доли — перелёт, стоянка, перелёт.
  const out = seedChain(
    [{ start: '2026-09-01T12:00', end: '' }, { start: '', end: '2026-09-01T15:00' }],
    { start: '2026-09-01T12:00', end: '2026-09-01T15:00' },
  );
  assert.deepEqual(out, [
    { start: '2026-09-01T12:00', end: '2026-09-01T13:00' },
    { start: '2026-09-01T14:00', end: '2026-09-01T15:00' },
  ]);
});

test('пустая цепочка засевается целиком из концов окна', () => {
  const out = seedChain([{ start: '', end: '' }, { start: '', end: '' }], { start: '2026-09-01T10:00', end: '2026-09-01T14:00' });
  assert.equal(out[0].start, '2026-09-01T10:00');
  assert.equal(out[1].end, '2026-09-01T14:00');
  assert.equal(out[0].end, '2026-09-01T11:20');
  assert.equal(out[1].start, '2026-09-01T12:40');
});

test('введённое пользователем не перезаписывается, доля считается между СОСЕДЯМИ', () => {
  // Добавили третий сегмент в цепочку, где первые даты уже введены руками.
  const out = seedChain([
    { start: '2026-09-01T08:00', end: '2026-09-01T09:00' },  // введено
    { start: '2026-09-01T10:00', end: '' },                  // конец освободился
    { start: '', end: '2026-09-01T16:00' },                  // новый финальный
  ], { start: '2026-09-01T08:00', end: '2026-09-01T16:00' });
  assert.equal(out[0].end, '2026-09-01T09:00');   // не тронуто
  assert.equal(out[1].start, '2026-09-01T10:00'); // не тронуто
  assert.equal(out[1].end, '2026-09-01T12:00');   // делится ОКНО МЕЖДУ 10:00 и 16:00
  assert.equal(out[2].start, '2026-09-01T14:00');
});

test('окна нет — цепочка остаётся пустой (дефолт не выдумывается)', () => {
  const links = [{ start: '', end: '' }, { start: '', end: '' }];
  assert.deepEqual(seedChain(links, {}), links);
});

test('засев не мутирует вход', () => {
  const links = [{ start: '2026-09-01T12:00', end: '' }, { start: '', end: '2026-09-01T15:00' }];
  const snapshot = JSON.parse(JSON.stringify(links));
  seedChain(links, { start: '2026-09-01T12:00', end: '2026-09-01T15:00' });
  assert.deepEqual(links, snapshot);
});
