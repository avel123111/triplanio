// @ts-check

/**
 * ЗАКРЫТАЯ ПЛОЩАДЬ ШЕЛЛА — ЧИСТАЯ ФУНКЦИЯ (TRIP-422 → TRIP-484).
 *
 * ★ ОДИН МЕХАНИЗМ НА ОБЕ ОСИ И НА ОБЕ ПЛАТФОРМЫ: закрытая площадь — это ОТСТУП
 * КАМЕРЫ, а холст всегда во всю площадь шелла.
 *   панель режет ШИРИНУ → `camera.left`;
 *   шит режет ВЫСОТУ    → `camera.bottom`.
 * Карта лежит ПОД шитом целиком, как под панелью на десктопе, и в вырезах его
 * скруглений видна она, а не фон страницы.
 *
 * ⚠️ ПРЕДЫДУЩАЯ РЕДАКЦИЯ ОТДАВАЛА ВЫСОТУ САМОМУ СЛОТУ (холст = свободное окно),
 * и это стоило трёх дефектов, невидимых по отдельности:
 *   1. холст менять размер плавно НЕЛЬЗЯ (каждый кадр = переаллокация GL), а шит
 *      едет за пальцем — между ними открывалась полоса фона до 414 px на всё
 *      время жеста (`onHeightChange` отдаёт только ЗАФИКСИРОВАННУЮ высоту);
 *   2. `map.resize()` держит центр в центре холста: убрал снизу Δ — содержимое
 *      мгновенно уехало вверх на Δ/2. На десктопе та же дельта приезжала 320-мс
 *      плавным паном камеры, на телефоне — телепортом;
 *   3. на верхнем детенте холст сжимался до ~20 px, и любой фит, посчитанный в
 *      этот момент, уходил в предельный зум и там оставался.
 * Отступ камеры всех трёх не имеет по построению: холст не меняется вовсе.
 *
 * ★★ ПРО ГЛОБУС. Диаметр шара mapbox считает от высоты ХОЛСТА — поэтому зум
 * стартового вида считается от СВОБОДНОГО ОКНА (`lib/map/globeStart.js` вычитает
 * этот самый отступ), а не от холста. Прежняя формулировка «холст обязан быть
 * равен свободному окну» была следствием того, что отступ на телефоне всегда был
 * нулевым и вычитать было нечего.
 *
 * @param {{ phone?: boolean, sheetPx?: number, panelPx?: number, overlayOpen?: boolean, collapsed?: boolean }} [p]
 *
 * `contentBottom` — ГДЕ КОНЧАЕТСЯ СВОБОДНОЕ ОКНО СНИЗУ (высота шита). Холсту он
 * больше не нужен, а вот всему, что экран кладёт ПОВЕРХ карты, нужен по-прежнему:
 * низ такого элемента — низ ЭКРАНА, и без этой величины он ложится под шит. Так
 * пилюля «6 городов · 12 ночей» планировщика и логотип mapbox отступают от шита,
 * а не от края.
 *
 * @returns {{ contentBottom: number, camera: { top: number, right: number, bottom: number, left: number } }}
 */
export function mapShellInsets({ phone = false, sheetPx = 0, panelPx = 0, overlayOpen = false, collapsed = false } = {}) {
  // Из DOM приходят 0, NaN и отрицательные (первый кадр, размонтирование) —
  // такое обязано выродиться в «карта во всю площадь», а не в отрицательный отступ.
  const px = (v) => (Number.isFinite(v) && v > 0 ? Math.round(/** @type {number} */ (v)) : 0);
  const none = { top: 0, right: 0, bottom: 0, left: 0 };
  // Режимы не смешиваются: шит живёт в портале и на переходе десктоп↔телефон
  // успевает подержать прошлое значение — прочитать его значит отрезать полосу
  // по призраку.
  if (phone) {
    const bottom = px(sheetPx);
    return { contentBottom: bottom, camera: { ...none, bottom } };
  }
  // Колонка слева закрыта, если раскрыта панель ИЛИ открыт слой — ширина у обоих
  // одна (panelPx). Оба сигнала булевы → сдвиг мгновенный, без замера.
  const leftClosed = overlayOpen || !collapsed;
  return { contentBottom: 0, camera: { ...none, left: leftClosed ? px(panelPx) : 0 } };
}

export default mapShellInsets;
