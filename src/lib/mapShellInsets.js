/**
 * ЗАКРЫТАЯ ПЛОЩАДЬ ШЕЛЛА — ЧИСТАЯ ФУНКЦИЯ (TRIP-422).
 *
 * ★ ЧТО ЗАКРЫТО — РЕШАЕТ ОСЬ, потому что размер глобуса mapbox считает от высоты
 * ХОЛСТА:
 *   панель режет ШИРИНУ → холст целый, кадр уводит отступ камеры;
 *   шит режет ВЫСОТУ    → её забирает СЛОТ (холст = свободное окно).
 *
 * ⚠️ Развязывать холст и свободное окно нельзя — так ломали глобус дважды:
 * высоты расходятся втрое, шар считается от одной и показывается в другой.
 *
 * @param {{ phone?: boolean, sheetPx?: number, panelPx?: number, overlayOpen?: boolean, collapsed?: boolean, cornerPx?: number }} [p]
 *   `cornerPx` — радиус скруглений шита (`--r-xl`): на столько слот заходит под
 *   него, иначе в вырезах углов виден фон страницы. Значение ЧИТАЕТСЯ ИЗ CSS
 *   вызывателем — второй записи этого числа в JS быть не должно.
 *
 *   `overlayOpen` — открыт ли слой города/события. Он занимает ТУ ЖЕ левую
 *   колонку той же ширины (`panelPx`), но его наличие НЕ зависит от свёрнутости
 *   маршрута. Флаг, не замер: колонка закрыта, если раскрыта панель ИЛИ открыт
 *   слой. Чтобы сдвиг под слой не прерывал focus-камеру, отступ применяется
 *   мгновенно на стороне `useMapInsets` (см. там про `focusing`).
 *
 * `slotUnder` — НА СКОЛЬКО НИЗ СЛОТА ЗАШЁЛ ПОД ШИТ (тот самый радиус). Это не
 * дубль `slotBottom`, а его вторая половина, и без неё всё, что экран кладёт
 * ПОВЕРХ карты, врёт на эту величину: у него «низ карты» — низ слота, а он уже
 * под шитом. Ровно так пилюля «6 городов · 12 ночей» планировщика оказывалась
 * лежащей на шите, хотя честно отступала 14px от своего низа.
 *
 * @returns {{ slotBottom: number, slotUnder: number, camera: { top: number, right: number, bottom: number, left: number } }}
 */
export function mapShellInsets({ phone = false, sheetPx = 0, panelPx = 0, overlayOpen = false, collapsed = false, cornerPx = 0 } = {}) {
  // Из DOM приходят 0, NaN и отрицательные (первый кадр, размонтирование) —
  // такое обязано выродиться в «карта во всю площадь», а не в отрицательный слот.
  const px = (v) => (Number.isFinite(v) && v > 0 ? Math.round(/** @type {number} */ (v)) : 0);
  const none = { top: 0, right: 0, bottom: 0, left: 0 };
  // Режимы не смешиваются: шит живёт в портале и на переходе десктоп↔телефон
  // успевает подержать прошлое значение — прочитать его значит отрезать полосу
  // по призраку.
  if (phone) {
    const slotBottom = Math.max(0, px(sheetPx) - px(cornerPx));
    // Заход считается ВЫЧИТАНИЕМ, а не повтором `cornerPx`: шит ниже своего
    // радиуса не бывает, но если бы стал (нулевая высота на первом кадре),
    // повтор объявил бы заход больше самого шита.
    return { slotBottom, slotUnder: px(sheetPx) - slotBottom, camera: none };
  }
  // Колонка слева закрыта, если раскрыта панель ИЛИ открыт слой — ширина у обоих
  // одна (panelPx). Оба сигнала булевы → сдвиг мгновенный, без замера.
  const leftClosed = overlayOpen || !collapsed;
  return { slotBottom: 0, slotUnder: 0, camera: { ...none, left: leftClosed ? px(panelPx) : 0 } };
}

/**
 * ВЫСОТА, КОТОРУЮ ШИТ ОТРЕЗАЕТ У СЛОТА КАРТЫ. Не равна высоте шита (TRIP-484).
 *
 * ★ ПОКА ИДЁТ ЖЕСТ — САМЫЙ БОЛЬШОЙ РАЗМЕР КАРТЫ (нижний детент). Высота холста
 * приходит только на ОСАДКЕ детента, а шит едет за пальцем покадрово. Тянешь
 * его вниз — холст ещё старый, и между его низом и верхом шита открывается
 * полоса фона: замер на живом экране (стенд `harness/`, экран 743, тяга с
 * середины вниз) даёт РОВНЫЙ РОСТ до 350 px. Отдать холсту сразу крайний размер
 * дешевле любого слежения: ресайз один на жест (каждый кадр = переаллокация
 * GL-буфера), а шит просто съезжает по уже нарисованной карте. Прыжка от этого
 * роста нет — его гасит компенсация в `useMapInsets`.
 *
 * ★★ НА ОСАДКЕ — НЕ ВЫШЕ СРЕДНЕГО ДЕТЕНТА. Движение шита с середины вверх
 * означает, что он закроет экран целиком: карту под ним двигать незачем.
 * Заодно исчезает «холст в 20 px» на верхнем детенте — состояние, в которое
 * уходил и в котором застревал автофокус.
 *
 * @param {{ sheetPx?: number, stops?: number[], dragging?: boolean }} [p]
 * @returns {number}
 */
export function mapSlotPx({ sheetPx = 0, stops = [], dragging = false } = {}) {
  const px = (v) => (Number.isFinite(v) && v > 0 ? Math.round(/** @type {number} */ (v)) : 0);
  const list = (Array.isArray(stops) ? stops : []).filter((v) => Number.isFinite(v) && v >= 0);
  if (!list.length) return px(sheetPx);
  if (dragging) return px(list[0]);
  // Потолок — ВТОРОЙ СВЕРХУ детент: верхний закрывает экран целиком.
  return Math.min(px(sheetPx), px(list[Math.max(0, list.length - 2)]));
}

/**
 * КОГДА применять новый размер слота — задержка в мс.
 *
 * ★ Размер холста анимировать нельзя (каждый кадр = переаллокация GL-буфера),
 * значит он меняется скачком и единственная ручка — МОМЕНТ. Правило
 * несимметрично: карта РАСТЁТ сразу (шит съезжает по ней), СЖИМАЕТСЯ после
 * приезда шита (её низ всё это время закрыт им самим). Иначе между ними
 * открывается полоса фона — замерено до 351 px на 160 мс.
 *
 * @param {{ prev?: number, next?: number, settleMs?: number }} [p] отступ слота снизу
 * @returns {number}
 */
export function slotChangeDelay({ prev = 0, next = 0, settleMs = 0 } = {}) {
  if (!(next > prev)) return 0;
  return Math.max(0, Math.round(settleMs));
}

export default mapShellInsets;
