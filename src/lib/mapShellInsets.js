// @ts-check

/**
 * ЗАКРЫТАЯ ПЛОЩАДЬ ШЕЛЛА — ЧИСТАЯ ФУНКЦИЯ (TRIP-422).
 *
 * ★ ЧТО ЗАКРЫТО — РЕШАЕТ ОСЬ, потому что размер глобуса mapbox считает от высоты
 * ХОЛСТА, а холст всегда во всю площадь шелла:
 *   панель режет ШИРИНУ → кадр уводит отступ КАМЕРЫ (`transform.padding`);
 *   шит режет ВЫСОТУ    → кадр уводит СДВИГ холста, а отступ камеры остаётся
 *                         нулевым (`padding` на проекции globe рисует диск).
 *
 * ⚠️ РАЗМЕР ХОЛСТА НЕ ТРОГАЕМ НИ ПРИ КАКИХ УСЛОВИЯХ. Так глобус ломали дважды:
 * ресайз двигает мир на половину дельты и роняет шар (вид пришпилен к центру
 * холста), а каждый кадр ресайза — переаллокация GL-буфера. Тянет «подогнать
 * холст под свободное окно» — значит правило ниже прочитано не до конца.
 *
 * @param {{ phone?: boolean, sheetPx?: number, capPx?: number, panelPx?: number, overlayOpen?: boolean, collapsed?: boolean }} [p]
 *   `capPx` — высота ВТОРОГО СВЕРХУ детента (её знает шит). Выше неё сдвигать
 *   холст незачем: верхний детент закрывает экран целиком, и всё, что мы там
 *   двигаем, никто не видит — а движение при этом видно на подходе к нему.
 *   `overlayOpen` — открыт ли слой города/события. Он занимает ТУ ЖЕ левую
 *   колонку той же ширины (`panelPx`), но его наличие НЕ зависит от свёрнутости
 *   маршрута. Флаг, не замер: колонка закрыта, если раскрыта панель ИЛИ открыт
 *   слой. Чтобы сдвиг под слой не прерывал focus-камеру, отступ применяется
 *   мгновенно на стороне `useMapInsets` (см. там про `focusing`).
 *
 * `slotBottom` — ГДЕ КОНЧАЕТСЯ СВОБОДНОЕ ОКНО СНИЗУ, то есть высота шита. Её
 * читает то, что экран кладёт ПОВЕРХ карты (пилюля планировщика): холст теперь
 * во всю высоту шелла и уходит ПОД шит целиком, поэтому отступ от собственного
 * низа у такого элемента приходится на площадь под шитом — прибавь эту
 * величину, и отступ снова считается от края шита.
 *
 * ★★ ДВЕ КОРОБКИ, И ПУТАТЬ ИХ НЕЛЬЗЯ:
 *   `camera` — ЧЕМ СДВИГАЕМ КАМЕРУ (`transform.padding`). На телефоне НОЛЬ:
 *     вид туда, куда надо, уводит сам холст (он уезжает вверх на половину
 *     шита), а `padding` на проекции `globe` рисует планету диском с
 *     прозрачным остатком — замерено, это и были «круги».
 *   `fit` — ВО ЧТО ВПИСЫВАЕМ маршрут. Видимая часть холста — его ЦЕНТРАЛЬНАЯ
 *     полоса высотой «холст минус шит», поэтому коробка симметрична: по
 *     половине шита сверху и снизу. Без неё фит вписывает маршрут во весь
 *     холст, и половина городов уезжает под шит (замер: города на y=440 и
 *     y=−183 при окне 0..238).
 *
 * `shift` — НА СКОЛЬКО ХОЛСТ УЕЗЖАЕТ ВВЕРХ (половина закрытого, с потолком по
 * `capPx`). На десктопе всегда 0: там холст не двигают вовсе.
 *
 * @returns {{ slotBottom: number, camera: any, fit: any, shift: number }}
 */
export function mapShellInsets({ phone = false, sheetPx = 0, capPx = 0, panelPx = 0, overlayOpen = false, collapsed = false } = {}) {
  // Из DOM приходят 0, NaN и отрицательные (первый кадр, размонтирование) —
  // такое обязано выродиться в «карта во всю площадь», а не в отрицательный слот.
  const px = (v) => (Number.isFinite(v) && v > 0 ? Math.round(/** @type {number} */ (v)) : 0);
  const none = { top: 0, right: 0, bottom: 0, left: 0 };
  // Режимы не смешиваются: шит живёт в портале и на переходе десктоп↔телефон
  // успевает подержать прошлое значение — прочитать его значит отрезать полосу
  // по призраку.
  if (phone) {
    // ★ СДВИГ СЧИТАЕТСЯ ЗДЕСЬ, А НЕ У ЧИТАТЕЛЯ, и это не педантизм: посчитанный
    // на стороне шелла «просто по высоте шита» он оставался ненулевым при
    // переходе в десктоп (шит размонтирован, последнее значение осталось) — и
    // холст держался сдвинутым до перезагрузки страницы. Правило одно, ветка
    // «телефон» одна, десктоп получает ноль по построению.
    const capped = px(capPx) > 0 ? Math.min(px(sheetPx), px(capPx)) : px(sheetPx);
    const half = Math.round(capped / 2);
    return {
      slotBottom: px(sheetPx),
      camera: none,
      fit: { ...none, top: half, bottom: half },
      shift: half,
    };
  }
  // Колонка слева закрыта, если раскрыта панель ИЛИ открыт слой — ширина у обоих
  // одна (panelPx). Оба сигнала булевы → сдвиг мгновенный, без замера.
  const leftClosed = overlayOpen || !collapsed;
  // Десктоп: панель лежит ПОВЕРХ целого холста — там сдвиг камеры и расчёт
  // кадра это одно и то же.
  const box = { ...none, left: leftClosed ? px(panelPx) : 0 };
  return { slotBottom: 0, camera: box, fit: box, shift: 0 };
}

export default mapShellInsets;
