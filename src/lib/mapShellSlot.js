/**
 * Свободное окно карты — ЧИСТАЯ функция (TRIP-422).
 *
 * ★ ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Здесь живёт инвариант, поломка которого стоила
 * дороже всего в этой задаче и НЕ ВИДНА ни одному гарду: «слот карты равен
 * свободному окну». Когда он нарушен, экран не падает и тесты не краснеют —
 * просто шар оказывается меньше окна, и вокруг него видно дымку и космос.
 * Скриншота у правила нет, поэтому его дом — чистая функция и `node --test`.
 *
 * ★ ПОЧЕМУ ИМЕННО ЭТИ ДВЕ ВЕЛИЧИНЫ. Панель и шит не лежат ПОВЕРХ карты, они её
 * ГРАНИЦА: на десктопе карта кончается там, где кончается панель, на телефоне —
 * там, где начинается шит. Больше закрывать её нечему, поэтому третьей стороны
 * тут нет и заводить её нельзя: она сразу станет вторым мнением о том, что
 * закрыто.
 *
 * ★ РЕЖИМЫ НЕ СМЕШИВАЮТСЯ. На телефоне ширина панели не читается вовсе, на
 * десктопе — высота шита: шит живёт в портале на `<body>` и на переходе между
 * режимами успевает подержать прошлое значение. Прочитать его «на всякий
 * случай» значит отрезать у десктопной карты низ по призраку.
 *
 * ★ ЗАХОД ПОД СКРУГЛЕНИЕ. Слот заканчивается НЕ ровно по кромке панели или
 * шита, а на радиус их углов дальше. Иначе в вырезах скруглений видно фон
 * страницы: скругление читается не как скругление, а как цветное пятно по краям
 * (этот дефект приезжал со скрина), а плавающий виджет на светлой карте
 * перестаёт читаться как отдельный объект. Кадру это ничего не портит: слот
 * становится на 20px БОЛЬШЕ свободного окна, то есть содержимое выходит за него
 * чуть сильнее, а не слабее — направление безопасное.
 *
 * @param {{ phone?: boolean, sheetPx?: number, panelPx?: number, collapsed?: boolean }} [p]
 * @returns {{ bottom: number, left: number }} px, всегда конечные и ≥ 0
 */
/** Радиус скруглений виджета и шита (`--r-xl`): на столько слот карты заходит
 *  под них. Скругление обязано лежать НА КАРТЕ — иначе в вырезах углов виден
 *  фон страницы, и оно читается не как скругление, а как цветное пятно; заодно
 *  виджет перестаёт читаться как плавающий над картой объект. */
const PANEL_CORNER = 20;

export function mapSlotInsets({ phone = false, sheetPx = 0, panelPx = 0, collapsed = false } = {}) {
  // Измерения приходят из DOM (getBoundingClientRect / ResizeObserver): на
  // размонтировании и первом кадре там бывает 0, NaN и отрицательное. Слот от
  // такого обязан выродиться в «карта во всю площадь», а не в отрицательный
  // отступ, который CSS молча проигнорирует по-своему.
  const px = (v) => (Number.isFinite(v) && v > 0 ? Math.round(v) : 0);
  if (phone) return { bottom: Math.max(0, px(sheetPx) - PANEL_CORNER), left: 0 };
  return { bottom: 0, left: collapsed ? 0 : Math.max(0, px(panelPx) - PANEL_CORNER) };
}
