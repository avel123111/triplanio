/**
 * Свободное окно карты — ЧИСТАЯ функция (TRIP-422).
 *
 * ★ ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Здесь живёт инвариант, поломка которого стоила
 * дороже всего в этой задаче и НЕ ВИДНА ни одному гарду: «карта кадрируется по
 * СВОБОДНОМУ окну». Когда он нарушен, экран не падает и тесты не краснеют —
 * просто половина шара оказывается под панелью. Скриншота у правила нет,
 * поэтому его дом — чистая функция и `node --test`.
 *
 * ★★ ЗАКРЫТУЮ ПЛОЩАДЬ МОЖНО ВЫРАЗИТЬ ДВУМЯ СПОСОБАМИ, И ОНИ НЕ РАВНОЗНАЧНЫ.
 *
 *   ОТСТУП КАМЕРЫ (`padding` вьюпорта) — канвас во всю площадь, карта видна и
 *   ПОД панелью, кадр уходит в свободное окно. Так и должно быть по умолчанию:
 *   виджет плавает НАД картой, а не вместо неё.
 *
 *   СЖАТИЕ СЛОТА — канвас физически равен свободному окну.
 *
 * Разница замерена на живом экране, телефон 430×900, шит 612 (точек рамки
 * свободного окна вне планеты, из 44):
 *
 *   отступ камеры, zoom 2 … 3.2   34 · 30 · 23 · 12   центр точен, но шар МЕЛКИЙ
 *   слот = свободное окно, zoom 2  0                  шар кроет окно целиком
 *
 * Причина не в отступе как таковом: диаметр шара Mapbox следует ВЫСОТЕ канваса,
 * и отступ СНИЗУ заставляет камеру отъехать — шар становится меньше свободного
 * окна, вокруг него видно дымку. Отступ СЛЕВА высоту не трогает, и там та же
 * камера даёт точный центр без потери размера (замер на десктопе 1280×900:
 * сдвиг центра 0.004 против 0.225 без отступа).
 *
 * Отсюда ОДНО правило с названной причиной: закрытая площадь уходит в отступ
 * камеры — кроме той её части, что режет ВЫСОТУ; эту часть забирает слот.
 *
 * @param {{ phone?: boolean, sheetPx?: number, panelPx?: number, collapsed?: boolean }} [p]
 * @returns {{ slot: { bottom: number, left: number }, camera: { top: number, right: number, bottom: number, left: number } }}
 */
export function mapSlotInsets({ phone = false, sheetPx = 0, panelPx = 0, collapsed = false } = {}) {
  // Измерения приходят из DOM (getBoundingClientRect / ResizeObserver): на
  // размонтировании и первом кадре там бывает 0, NaN и отрицательное. Слот от
  // такого обязан выродиться в «карта во всю площадь», а не в отрицательный
  // отступ, который CSS молча проигнорирует по-своему.
  const px = (v) => (Number.isFinite(v) && v > 0 ? Math.round(v) : 0);
  const none = { top: 0, right: 0, bottom: 0, left: 0 };
  // ★ РЕЖИМЫ НЕ СМЕШИВАЮТСЯ. На телефоне ширина панели не читается вовсе, на
  // десктопе — высота шита: шит живёт в портале на `<body>` и на переходе между
  // режимами успевает подержать прошлое значение. Прочитать его «на всякий
  // случай» значит отрезать у десктопной карты низ по призраку.
  if (phone) {
    // Шит режет ВЫСОТУ — эту часть забирает слот. Заход под скругление: иначе в
    // вырезах углов виден фон страницы, и скругление читается как цветное пятно.
    return { slot: { bottom: Math.max(0, px(sheetPx) - PANEL_CORNER), left: 0 }, camera: none };
  }
  // Панель режет ШИРИНУ — карта остаётся во всю площадь и видна под виджетом,
  // а кадр уходит вправо отступом камеры.
  const left = collapsed ? 0 : px(panelPx);
  return { slot: { bottom: 0, left: 0 }, camera: { ...none, left } };
}

/** Радиус скруглений виджета и шита (`--r-xl`): на столько слот карты заходит
 *  под них там, где слот вообще сжимается. */
const PANEL_CORNER = 20;
