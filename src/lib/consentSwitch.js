// Переход через границу согласия — ЕДИНСТВЕННОЕ место, где клиент PostHog
// меняет режим хранения, и единственное, что знает, как через этот переход
// пронести личность и супер-свойства (TRIP-502).
//
// ПРАВИЛО, РАДИ КОТОРОГО ЭТО СУЩЕСТВУЕТ: сначала приклей визит к аккаунту,
// только потом включай хранение. Выход из безкукового режима SDK делает
// `reset(true)` — намеренно, чтобы состояние безкуковых и обычных событий не
// перетекало друг в друга (`posthog-core.ts`). Значит момент включения хранения
// решает, чем закончится визит: включили по кнопке баннера — приход остаётся на
// брошенной персоне и воронка теряет всех, кто согласился; включили после
// `identify` — терять уже нечего, приход к тому моменту принадлежит аккаунту.
//
// ПОЧЕМУ ОТДЕЛЬНЫМ МОДУЛЕМ, А НЕ СТРОЧКАМИ В АДАПТЕРЕ. Это правило ломалось
// трижды подряд, и ни один тест этого не поймал: `destinations/posthog.js`
// читает `window` и `import.meta.env`, поэтому под `node --test` не
// импортируется, и всё, что его тесты умеют, — сверять собственный исходник
// регулярками. Здесь импортов нет вовсе, SDK приходит аргументом, и порядок
// вызовов проверяется по-настоящему — фейковым клиентом, который умеет
// сбрасываться так же, как настоящий (`consentSwitch.test.js`).

/**
 * Выполнить переключение режима, не потеряв супер-свойства.
 *
 * `reset()` внутри SDK зовёт `persistence.clear()` и сносит ВСЕ супер-свойства
 * разом — метку окружения, метки кампании, `ref_trip_id`. Часть из них
 * восстановима (`setCampaign()` перечитает адрес), а часть нет: `ref_trip_id`
 * ставят экраны приглашения и публичного трипа, то есть ДО входа, и в момент
 * переключения взять его неоткуда. Родного «перенеси свойства через сброс» у
 * SDK нет и не будет — он их роняет намеренно, поэтому переносим сами, ровно
 * здесь и по явному списку.
 *
 * @param {any} ph                 клиент PostHog
 * @param {string[]} ownedKeys     супер-свойства, которыми владеет приложение
 * @param {() => void} switchMode  само переключение (opt_in / opt_out)
 */
export function preservingOwnProps(ph, ownedKeys, switchMode) {
  const kept = {};
  for (const key of ownedKeys) {
    const value = ph.get_property?.(key);
    if (value != null && value !== '') kept[key] = value;
  }

  switchMode();

  // Возврат ДО следующего события: `identify` ниже — тоже событие, и без этого
  // порядка оно уехало бы без метки окружения и без кампании.
  if (Object.keys(kept).length) ph.register?.(kept);
}

/**
 * Сказать PostHog, кто это, и — если человек разрешил — включить хранение.
 *
 * Три шага, и порядок между ними и есть весь смысл модуля:
 *
 *  1. `identify(uid)` — визит склеивается с аккаунтом. В безкуковом режиме это
 *     ничего не пишет на устройство: клиент шлёт `$identify` с сентинелом, а
 *     дневную хеш-персону подставляет и сшивает сервер.
 *  2. Включение хранения. Клиент сбрасывается и заводит новый идентификатор —
 *     но приход, клик и старт регистрации уже принадлежат аккаунту.
 *  3. `identify(uid)` ещё раз — свежий идентификатор склеивается с тем же
 *     аккаунтом. Если сброса не было (согласия нет, либо хранение включили
 *     раньше), SDK этот вызов молча пропускает: он шлёт `$identify` только
 *     когда персона анонимна И id отличается от текущего.
 *
 * Сброс случается один раз на устройство: после первого включения SDK помнит
 * согласие сам и больше не сбрасывается. Повторяется только после выхода из
 * аккаунта — `reset()` стирает и хранилище, и копию согласия SDK.
 *
 * @param {any} ph                       клиент PostHog
 * @param {string} uid                   id аккаунта (никакого PII)
 * @param {object} opts
 * @param {boolean} opts.granted         человек разрешил хранение на устройстве
 * @param {string[]} opts.ownedKeys      супер-свойства приложения
 */
export function identifyUnderConsent(ph, uid, { granted, ownedKeys }) {
  if (!uid) return;

  ph.identify?.(uid);
  if (!granted) return;

  preservingOwnProps(ph, ownedKeys, () => {
    // Без события `$opt_in`: согласие — это состояние клиента, а не поступок,
    // который надо отдельно считать в воронке.
    ph.opt_in_capturing?.({ captureEventName: false });
  });

  // Запись экрана живёт по ту сторону границы: в безкуковом режиме у SDK нет
  // клиентской сессии, а значит и записывать нечего. Голый вызов, без аргументов
  // — он говорит «разрешено», а какие сессии писать, решают настройки проекта.
  ph.startSessionRecording?.();

  ph.identify?.(uid);
}
