import { GUEST_PLANNER_PATH, canonicalPath, isZoneRoute } from './routePaths.js';

/**
 * Тема ДОКУМЕНТА — один модуль на оба факта, из которых она складывается:
 * «это страница неавторизованной зоны» и «тёмная ли тема».
 *
 * ЗОНА СВЕТЛАЯ ПО ПОСТРОЕНИЮ, У НЕЁ НЕТ ТЕМЫ. Тема приложения по умолчанию
 * `system`, поэтому у человека с тёмной ОС `[data-theme=dark]` оказывался на
 * `<html>` и на лендинге, куда он ещё даже не логинился. Своя палитра зоны от
 * этого защищена (её токены на `html.site`), а всё остальное — нет: компонент
 * ПРИЛОЖЕНИЯ на странице зоны читал тёмные токены, а до загрузки `site.css`
 * тёмной была вся страница целиком.
 *
 * Импорты РЕЛЯТИВНЫЕ, без алиаса `@/`: модуль под тестом, а `node --test`
 * алиасы из `jsconfig.json` не резолвит.
 */

/** @param {{stored: string, systemDark: boolean, lightZone: boolean}} x */
export function resolveDark({ stored, systemDark, lightZone }) {
  if (lightZone) return false;                       // зона светлая по построению
  return stored === 'dark' || (stored === 'system' && systemDark);
}

/**
 * Адреса зоны — ЗАТРАВКА, а не авторитет.
 *
 * Владелец факта «это страница зоны» — ОБОЛОЧКА `SiteZone`. Но и она приезжает
 * позже темы: чанк приложения разбирается к ~220 мс, а тема ложится к ~115 мс,
 * и между этими моментами документ успевал стать тёмным целиком. Закрыть окно
 * можно только решением ПО АДРЕСУ, принятым до того, как что-либо
 * смонтировалось. Поэтому список задаёт НАЧАЛЬНОЕ значение, а дальше владельцем
 * становится смонтированная оболочка: ошибка затравки стоит одного кадра, а не
 * неверной темы.
 *
 * Владельцем была СТРАНИЦА, и это давало второе окно, которого затравка не
 * видит: страницы зоны ленивые, поэтому при переходе внутри зоны старая уже
 * снялась, а новая ещё едет — и тема на это время возвращалась к системной
 * (TRIP-475). Оболочка внутри зоны не размонтируется, у неё такого окна нет.
 */
// ★ СВЕТЛОЕ = «ВЕДЁТ В ЗОНУ» + ДВЕ ПОВЕРХНОСТИ, КОТОРЫЕ СТРАНИЦАМИ ЗОНЫ НЕ
// ЯВЛЯЮТСЯ. Первое слагаемое ВЫВОДИТСЯ — зовём `isZoneRoute`, а не переписываем
// его таблицу: копия молча отставала бы (новая страница зоны приезжала бы тёмной
// на первом кадре у человека с тёмной ОС, и не покраснело бы ничего). Отставала
// на самом деле: рукописный список знал точные адреса, но не знал префикса
// `/d/`, и чужой демо-слаг рисовался в зоне тёмным первым кадром.
//
// Слагаемые, которых в `isZoneRoute` нет и быть не должно:
//   · гостевой планировщик — страницей зоны он не является (нет canonical,
//     закрыт от индексации), но поверхность у него светлая (разбор ниже);
//   · приглашение и публичная поездка — экраны ПРИЛОЖЕНИЯ, которые рисуются
//     сайтовой ДС и потому тоже светлые.
const PREFIX = ['/join/', '/public/trip/'];

/**
 * ★ ИМЯ ГОВОРИТ «ЗАТРАВКА», И ЭТО НЕ ПРИДИРКА. Рядом живёт `routePaths.isZoneRoute`
 * — тот же вид, та же сигнатура, и на гостевом планировщике они отвечают
 * ПРОТИВОПОЛОЖНО: `/plan` рисуется своей веткой, а не таблицей зоны (там
 * `false`), но поверхность у него светлая (здесь `true`). Под общим именем
 * импорт не из того модуля дал бы молча неверный ответ ровно на том адресе,
 * ради которого различие и заведено.
 *
 * @param {string} pathname
 */
export function seedsLightZone(pathname) {
  // ⚠️ НОРМАЛИЗАЦИЯ ОДНА И ОБЩАЯ С КРАЁМ (`canonicalPath`), И МЕРЯЕТСЯ ПО НЕЙ
  // ЖЕ — обе половины. Здесь стояла своя (`/\/+$/`, снимала НЕСКОЛЬКО слэшей),
  // да ещё префиксы сверялись по СЫРОМУ адресу, а точные — по нормализованному:
  // два правила «тот же ли это адрес» в одном выражении. Разойдись они — и
  // первый кадр красился бы не так, как страницу решил рисовать роутер, молча
  // и только на адресе с хвостом.
  const p = canonicalPath(pathname || '/');
  return isZoneRoute(p) || p === GUEST_PLANNER_PATH || PREFIX.some((x) => p.startsWith(x));
}
