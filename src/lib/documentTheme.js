import { DEMO_PATH } from '../pages/Demo/demoPath.js';

/**
 * Тема ДОКУМЕНТА — один модуль на оба факта, из которых она складывается:
 * «это страница неавторизованной зоны» и «тёмная ли тема».
 *
 * ЗОНА СВЕТЛАЯ ПО ПОСТРОЕНИЮ, У НЕЁ НЕТ ТЕМЫ. Тема приложения по умолчанию
 * `system`, поэтому у человека с тёмной ОС `[data-theme=dark]` оказывался на
 * `<html>` и на лендинге, куда он ещё даже не логинился. Своя палитра зоны от
 * этого защищена (её токены на `html.site`), а всё остальное — нет: компонент
 * ПРИЛОЖЕНИЯ на странице зоны читал тёмные токены, а до загрузки `site.css`
 * тёмной была вся страница целиком.
 *
 * Импорты РЕЛЯТИВНЫЕ, без алиаса `@/`: модуль под тестом, а `node --test`
 * алиасы из `jsconfig.json` не резолвит.
 */

/** @param {{stored: string, systemDark: boolean, lightZone: boolean}} x */
export function resolveDark({ stored, systemDark, lightZone }) {
  if (lightZone) return false;                       // зона светлая по построению
  return stored === 'dark' || (stored === 'system' && systemDark);
}

/**
 * Адреса зоны — ЗАТРАВКА, а не авторитет.
 *
 * Владелец факта «это страница зоны» — `useSiteCss()`, его зовут все семь
 * страниц. Но страницы ЛЕНИВЫЕ: чанк приезжает к ~220 мс, а тема ложится к
 * ~115 мс, и между этими моментами документ успевал стать тёмным целиком.
 * Закрыть окно можно только решением ПО АДРЕСУ, принятым до того, как
 * что-либо смонтировалось. Поэтому список задаёт НАЧАЛЬНОЕ значение, а дальше
 * владельцем становится смонтированная страница: ошибка затравки стоит одного
 * кадра, а не неверной темы.
 */
const EXACT = new Set(['/', '/login', '/reset-password', '/terms', '/privacy', DEMO_PATH]);
const PREFIX = ['/join/', '/public/trip/'];

/** @param {string} pathname */
export function isZoneRoute(pathname) {
  const p = (pathname || '/').replace(/\/+$/, '') || '/';
  return EXACT.has(p) || PREFIX.some((x) => (pathname || '').startsWith(x));
}
