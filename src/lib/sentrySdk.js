// ★ ЕДИНСТВЕННАЯ ДВЕРЬ К ВЕНДОРСКОМУ SDK — И ОНА СУЩЕСТВУЕТ РАДИ ОДНОГО
// СВОЙСТВА СБОРЩИКА (TRIP-475).
//
// `sentry.js` тянул SDK так: `const S = await import('@sentry/react')`. Весь
// namespace попадает в переменную, а дальше по нему ходят точкой — `S.init`,
// `S.replayIntegration`. Сборщик не может знать, какие свойства будут взяты в
// рантайме, поэтому ОБЯЗАН сохранить живыми ВСЕ экспорты пакета. В чанк
// приезжали куски SDK, которых наш код не вызывает ни разу:
//
//     @sentry-internal/feedback        49 595 байт  — виджет обратной связи,
//                                                     `feedbackIntegration()`
//                                                     мы не зовём нигде;
//     @sentry-internal/replay-canvas   14 838 байт  — запись canvas, не включена;
//     и ещё вдвое ужавшийся после этого @sentry/core.
//
// Замер: чанк Sentry 486 673 → 275 786 сырых, 149 829 → 85 497 brotli
// (−64 332 байта с загрузки каждого посетителя).
//
// ⚠️ ДЕСТРУКТУРИЗАЦИЯ НА МЕСТЕ НЕ ПОМОГАЕТ, ПРОВЕРЕНО ЗАМЕРОМ. Вариант
// `const { init, … } = await import('@sentry/react')` даёт РОВНО те же 149 829
// байт: сквозь `await import()` сборщик не видит, что именно берут. Работает
// только СТАТИЧЕСКИЙ именованный импорт, то есть отдельный модуль, который
// потом целиком уезжает динамическим `import()`. Отсюда этот файл.
//
// ⚠️ ДОБАВЛЯЯ СЮДА ИМЯ, ПОМНИ, ЧТО ЭТО ПЛАТА В БАЙТАХ: каждый новый экспорт
// тянет свою ветку SDK. И никогда не пиши здесь `export * from '@sentry/react'`
// или `import * as` — это возвращает ровно ту болезнь, ради которой файл заведён.
// Правило пинит `sentry.test.js`.
import {
  init,
  browserTracingIntegration,
  replayIntegration,
  captureException,
} from '@sentry/react';

export { init, browserTracingIntegration, replayIntegration, captureException };
