/**
 * tapGesture — «был ли это ТАП» по паре pointerdown/pointerup.
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ ДВЕ СТРОКИ НА МЕСТЕ. Выбор строки в списке
 * пикера (`common/Autocomplete`) больше не висит на синтетическом `click`, и
 * решение «тап или скролл» стало ПОВЕДЕНИЕМ, у которого нет скриншота. В
 * JSX-файл `node --test` не заглядывает (модуль с разметкой он не загрузит), а
 * грепом такое правило не пинится. Поэтому решение живёт чистой функцией — её
 * гейт `tapGesture.test.js`.
 *
 * ★ ПОЧЕМУ `click` ПРИШЛОСЬ СНЯТЬ (iOS, замер на iPhone/WebKit). Синтетический
 * `click` рождается на ОБЩЕМ ПРЕДКЕ целей `mousedown` и `mouseup` и на тач-
 * платформе теряется по двум независимым причинам сразу:
 *   • WebKit держит слово, набранное подсказкой клавиатуры (T9/предиктивный
 *     ввод), как MARKED TEXT — незакоммиченную композицию. Первое касание вне
 *     поля тратится на её коммит, и остаток совместимой мышиной цепочки
 *     движок не досылает. Симптом ровно такой: список виден, `mouseenter`
 *     отработал (строка подсветилась), а выбор не случился — пока не нажмёшь
 *     Enter, который коммитит композицию явно.
 *   • список успевает переехать между down и up (отступ скроллера под
 *     клавиатуру `--kb-h`, ответ нового поиска), и общим предком двух целей
 *     оказывается контейнер, а не строка.
 * Pointer-события ни тем, ни другим не задеты: на тач-платформе они рождаются
 * из тач-последовательности, а не из мышиной совместимости, и у тач-указателя
 * есть НЕЯВНЫЙ ЗАХВАТ — `pointerup` придёт на тот же элемент, что и
 * `pointerdown`, даже если содержимое под пальцем уехало.
 *
 * ★★ ПОРОГ — ТОТ ЖЕ, ЧТО У ПЕРЕТАСКИВАНИЯ СТРОК (`lib/useRouteDnD`, 9 px):
 * различение «палец нажал» / «палец повёз» в приложении одно, и второй порог с
 * другим числом означал бы, что один и тот же жест на двух экранах считается
 * по-разному. Скролл списка гасится ДВАЖДЫ — порогом и `pointercancel`
 * (браузер шлёт его, когда забирает жест себе под скролл); порог нужен там,
 * где отмену не прислали, отмена — там, где палец уехал ровно по строке.
 */

/** Смещение, после которого жест перестаёт быть тапом (px). @see lib/useRouteDnD */
export const TAP_SLOP = 9;

/**
 * @typedef {{ id: number, x: number, y: number, row: any }} TapDown
 * @typedef {{ id: number, x: number, y: number }} TapUp
 */

/**
 * Что выбрано этим жестом, или `null`, если жест тапом не был.
 *
 * Возвращается СТРОКА ИЗ `down`, а не та, что оказалась под пальцем на `up`:
 * человек выбирает то, по чему нажал. Если список между down и up перерисовался
 * (пришёл ответ нового поиска) или уехал, «то, что под пальцем» — уже другой
 * город, и отдать его значило бы молча подменить выбор.
 *
 * @param {TapDown|null|undefined} down
 * @param {TapUp|null|undefined} up
 * @param {number} [slop]
 * @returns {any|null}
 */
export function tapPick(down, up, slop = TAP_SLOP) {
  if (!down || !up) return null;
  // Мультитач: второй палец не должен завершать чужой жест.
  if (down.id !== up.id) return null;
  if (Math.hypot(up.x - down.x, up.y - down.y) > slop) return null;
  return down.row ?? null;
}

export default tapPick;
