/**
 * ДВИЖЕНИЕ ПОВЕРХНОСТЕЙ — ОДИН ТЕМП И ОДНА КРИВАЯ (TRIP-422).
 *
 * Когда шит встаёт на детент, вместе с ним обязаны доехать камера карты (JS) и
 * плавающие контролы над ней (CSS). Разными механизмами, но одним временем и
 * одной кривой — иначе «плавно» не выйдет ни при каких значениях.
 *
 * Числа здесь ОДНИ: примитивы публикуют их инлайн-переменными на своём корне
 * (`--surface-settle` / `--surface-ease`), а CSS читает — тем же приёмом, каким
 * нижний нав публикует свою высоту. В `:root` им не место: это свойство
 * движения конкретной поверхности, а не глобальный токен темы.
 */

/** Сколько едет поверхность, вставая на место (мс). */
export const SURFACE_SETTLE_MS = 320;

/** Контрольные точки кривой (те же, что у `cubic-bezier` в CSS). */
export const SURFACE_EASE = [0.22, 1, 0.36, 1];

/** Та же кривая записью для CSS. */
export const SURFACE_EASE_CSS = `cubic-bezier(${SURFACE_EASE.join(', ')})`;

/**
 * Значение кубической кривой Безье в точке `t`.
 *
 * ★ ПОЧЕМУ РЕШАЕМ УРАВНЕНИЕ, А НЕ БЕРЁМ `y(t)` НАПРЯМУЮ. `cubic-bezier` — это
 * ПАРАМЕТРИЧЕСКАЯ кривая: и x, и y заданы через собственный параметр `u`.
 * Браузер по времени `t` сначала находит `u`, для которого `x(u) === t`, и
 * только потом берёт `y(u)`. Подставить `t` вместо `u` — распространённая
 * ошибка: получится похожая, но ДРУГАЯ кривая, и камера разъедется с шитом
 * ровно посередине хода (сильнее всего там, где кривая круче — здесь это старт).
 *
 * Корень ищем делением пополам: x(u) монотонна при контрольных точках в [0,1],
 * 24 шага дают точность ~6e-8 — вчетверо мельче кадра при 60 Гц.
 *
 * @param {number} t 0..1, доля пройденного времени
 * @param {number[]} [pts] контрольные точки [x1, y1, x2, y2]
 * @returns {number} 0..1, доля пройденного пути
 */
export function surfaceEasing(t, pts = SURFACE_EASE) {
  if (!(t > 0)) return 0;
  if (t >= 1) return 1;
  const [x1, y1, x2, y2] = pts;
  // B(u) для контрольных точек 0, a, b, 1.
  const at = (u, a, b) => {
    const v = 1 - u;
    return 3 * v * v * u * a + 3 * v * u * u * b + u * u * u;
  };
  let lo = 0;
  let hi = 1;
  for (let i = 0; i < 24; i += 1) {
    const mid = (lo + hi) / 2;
    if (at(mid, x1, x2) < t) lo = mid; else hi = mid;
  }
  return at((lo + hi) / 2, y1, y2);
}
