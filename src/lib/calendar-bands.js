/**
 * Полосы городов календаря: из «какие города в каждом дне» — в «где начинается
 * и где кончается полоса города» (в долях дня).
 *
 * ★ ЗАЧЕМ ЭТО ОТДЕЛЬНОЙ ФУНКЦИЕЙ, А НЕ ПРОГОНОМ ПО ДНЯМ. Прежняя редакция
 * собирала полосы из ДНЕЙ С ОДНИМ ГОРОДОМ и объявляла имя только над ними.
 * Город с одной ночью между двумя другими не имеет НИ ОДНОГО такого дня: день
 * заезда он делит с предыдущим городом, день выезда — со следующим. Имя такого
 * города не печаталось нигде и ни в одном виде — на экране оставались две
 * безымянные половинки. Полоса обязана считаться ПО ВИЗИТУ, тогда у неё всегда
 * есть тело, в которое можно написать название.
 *
 * ★ ДЕНЬ ПЕРЕСАДКИ ДЕЛИТСЯ. Дата выезда и дата заезда — один и тот же день, и
 * оба города в нём законно присутствуют (окно визита включает обе границы).
 * День делится на равные доли по числу городов в нём, в порядке их появления:
 * уходящий занимает первую долю, приходящий — следующую. Поэтому границы полос
 * ДРОБНЫЕ: полоса «Барселона» начинается в середине дня заезда и кончается в
 * середине дня выезда.
 *
 * Единица — индекс дня в ряду: `0` = левый край первого дня, `1` = его правый
 * край и одновременно левый край второго. Ряд может быть недельным (7 дней
 * месяца) или недельным видом (те же 7 колонок) — функция об этом не знает.
 */

/**
 * @typedef {{ name: string, colorIdx: number, v: { idx: number } }} DayCity
 * @typedef {{ cities: DayCity[] }} DayCell
 * @typedef {{ start: number, end: number, city: DayCity, split: boolean }} CityBand
 */

/**
 * @param {DayCell[]} row дни ряда слева направо
 * @returns {CityBand[]} полосы городов, в порядке появления слева
 */
export function cityBands(row) {
  /** @type {Map<number, CityBand>} */
  const byVisit = new Map();

  row.forEach((cell, dayIdx) => {
    const cities = cell?.cities || [];
    const k = cities.length;
    if (!k) return;
    cities.forEach((c, posInDay) => {
      // Доля дня, которую занимает этот город: при одном городе — весь день,
      // при пересадке — своя k-я часть в порядке появления.
      const from = dayIdx + posInDay / k;
      const to = dayIdx + (posInDay + 1) / k;
      const key = c?.v?.idx;
      if (key == null) return;
      const band = byVisit.get(key);
      if (!band) {
        byVisit.set(key, { start: from, end: to, city: c, split: k > 1 });
        return;
      }
      // Полоса растёт вправо по мере встречи города в следующих днях. Признак
      // `split` липкий: если ХОТЬ ОДИН день города поделён, полоса не занимает
      // свои крайние дни целиком — это меняет её геометрию, а не только вид.
      band.end = to;
      if (k > 1) band.split = true;
    });
  });

  return [...byVisit.values()].sort((a, b) => a.start - b.start);
}

/**
 * Полоса в процентах ширины ряда — готовые `left`/`width` для абсолютного слоя.
 * Вынесено сюда, а не в разметку, чтобы деление на 7 жило рядом с моделью и
 * было под тем же тестом.
 * @param {CityBand} band
 * @param {number} [cols] колонок в ряду (7 у обоих видов)
 */
export function bandStyle(band, cols = 7) {
  const left = (band.start / cols) * 100;
  const width = ((band.end - band.start) / cols) * 100;
  return { left: `${left}%`, width: `${width}%` };
}
