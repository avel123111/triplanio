test('★ ДАТЧИК: гашение комментариев в index.jsx несущее, а не декоративное', () => {
  // Мутация «снять гашение» краснеет только пока в комментариях `index.jsx`
  // упомянут класс, которого нет в CSS (сегодня — мёртвый скин `.field--error`).
  // Уберут этот комментарий или вернут правило — и пин станет ИНЕРТНЫМ, а
  // проверка молча перестанет что-либо значить. Датчик ловит именно это: он
  // сравнивает набор, собранный БЕЗ гашения, с рабочим и требует, чтобы разница
  // существовала. Имя класса не зашито намеренно — зашитое имя умирает вместе с
  // комментарием и уносит пин с собой.
  const rawParts = read('../design/index.jsx').split(/export const ([A-Z][A-Za-z0-9]*) *=/).slice(1);
  const raw = new Set();
  for (let i = 0; i < rawParts.length; i += 2) {
    const [name, body] = [rawParts[i], rawParts[i + 1] ?? ''];
    if (!new RegExp(`<${name}[ >/\\n]`).test(KIT)) continue;
    for (const m of body.matchAll(/\b([a-z][\w-]*--[\w-]+)\b/g)) {
      if (CANON.has(familyOf(m[1]))) raw.add(m[1]);
    }
  }
  assert.ok(
    raw.size > EMITTED.size,
    `набор без гашения (${raw.size}) не шире рабочего (${EMITTED.size}) — в комментариях ` +
      `index.jsx больше нет имён классов, и мутация «снять гашение» перестала краснеть. ` +
      `Пин инертен: либо верни случай, либо сними этот датчик осознанно.`,
  );
});

