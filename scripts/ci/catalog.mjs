/**
 * КАТАЛОГ ДИЗАЙН-СЛОЯ — общий разбор для тех, кто его СЧИТАЕТ.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. С TRIP-364 PR-I число записей `apart` стало седьмым
 * храповиком пола 2o, и его считают ДВОЕ: `audit-design.mjs` (для 2o) и
 * `check-design-axes.mjs` (2q печатает его же строкой «обличий вне осей»).
 * Две литеральные реализации одного числа — ровно та форма, которую этот эпик
 * уже лечил один раз: предикат периметра жил внутри одного гарда, второй имел
 * свой, и вердикты молча разошлись (см. шапку `perimeter.mjs`).
 *
 * ⚠️ И здесь они УЖЕ РАЗОШЛИСЬ, это замер, а не опасение: на каталоге с
 * `apart: { sev: null }` аудит молча возвращал 0, а 2q падал необработанным
 * `TypeError`. Тихий ноль — небезопасная сторона: семья с `null` выключала бы
 * свои записи из храповика, и число ПАДАЛО бы, читаясь как прогресс.
 *
 * Правило то же: число, которое храповит один гард и печатает другой, обязано
 * считаться ОДНОЙ функцией.
 */

/** Записи `apart` во всём каталоге: `{ семья: { хвост: причина } }` → сколько
 *  хвостов всего. Семья с непригодным значением (`null`, строка, массив) даёт
 *  0 СВОИХ записей и не роняет счёт — форму каталога проверяет тот, кто его
 *  читает (аудит поднимает `catalogError`, 2q — структурную ошибку), а дело
 *  этой функции одно: посчитать одинаково у обоих. */
/** Семьи, объявившие оси. Считается тут по той же причине, что и `apart`: число
 *  печатает 2q («семей с осями») и храповит 2o, то есть у него ДВА читателя. */
export function countAxesFamilies(axes) {
  if (!axes || typeof axes !== 'object' || Array.isArray(axes)) return 0;
  return Object.keys(axes).length;
}

export function countApart(apart) {
  if (!apart || typeof apart !== 'object' || Array.isArray(apart)) return 0;
  let n = 0;
  for (const perFamily of Object.values(apart)) {
    if (!perFamily || typeof perFamily !== 'object' || Array.isArray(perFamily)) continue;
    n += Object.keys(perFamily).length;
  }
  return n;
}
