/**
 * Общий разбор «маркеров-исключений со значением» — форма `<marker>: <ключ> +N — причина`.
 *
 * ЗАЧЕМ ОН ОДИН. Эту форму несут ДВА гарда: 2o (`floor-exempt`, `check-design-floor.mjs`)
 * и 2r (`door-exempt`, `check-data-door.mjs`). Раньше у каждого был свой парсер,
 * переписанный руками, и они УЖЕ РАЗОШЛИСЬ: 2r ловил «строка с маркером, но не
 * разобралась» (пояс из TRIP-376), а 2o — «знак не тот / не назван» (TRIP-337);
 * ни один не имел обеих проверок. Это ровно та болезнь, против которой семейство
 * дизайн-ратчета и написано — N копий одной формы, разъехавшихся тихо (TRIP-321).
 * Один парсер = обе проверки у обоих гардов, и разъехаться больше нечему.
 *
 * PATHSPEC НЕСУЩИЙ, поэтому его держит ВЫЗЫВАЮЩИЙ, а не этот модуль: маркеры
 * читаются только из ДОБАВЛЕННЫХ строк диффа под тем деревом, которое меряется
 * (у 2o это `src/`, у 2r — ещё и `supabase/functions/`). Без ограничения любая
 * строка репо, упомянувшая маркер, выдала бы бюджет — 2o так и падал с кодом 2 на
 * вводящем его PR, споткнувшись о собственные строки-фикстуры. Поэтому сюда
 * приходит УЖЕ суженный диффом текст, а модуль только разбирает его.
 *
 * ТРИ ОПЕЧАТКИ — ОДИН ИСХОД (`die`), НИКОГДА ТИШИНА:
 *   • неизвестное ИМЯ метрики                                   → die
 *   • не тот или НЕ НАЗВАННЫЙ знак (`+N` = величина нарушения,
 *     а не дельта числа; направление роли не играет)            → die
 *   • строка называет маркер, но не разобралась в валидную форму
 *     (нет числа, дефис вместо двоеточия, кривой порядок)       → die
 * Последнее — то, ради чего модуль и вынесен: опечатка в ФОРМЕ маркера обязана
 * ловиться так же громко, как опечатка в ИМЕНИ, иначе автор видит красноту, не
 * понимает, что его исключение не прочитано, и правит не то.
 *
 * `die(msg, extra[])` инжектится вызывающим: в проде он печатает `::error::` со
 * своим префиксом и делает `process.exit(2)`; в тесте — бросает, чтобы разбор
 * можно было проверить без выхода из процесса. Модуль после `die` ничего не
 * ждёт (в проде туда не возвращаются, в тесте бросок останавливает цикл).
 *
 * @param {string} diff            вывод `git diff --unified=0 BASE...HEAD -- <pathspec>`
 * @param {object} o
 * @param {string} o.marker        имя маркера без двоеточия, напр. `floor-exempt`
 * @param {Array<{key:string, up?:boolean}>} o.metrics  таблица метрик гарда
 * @param {(msg:string, extra?:string[])=>never} o.die   отказ гарда (exit 2 / throw)
 * @returns {Record<string, number>}  ключ метрики → суммарный разрешённый бюджет
 */
export function parseValueExemptions(diff, { marker, metrics, die }) {
  const byKey = new Map(metrics.map((m) => [m.key, m]));
  const out = Object.create(null);
  // Знак ловится НЕОБЯЗАТЕЛЬНЫМ, чтобы `<ключ> 25` и `<ключ> -25` НАШЛИСЬ и
  // упали на сверке ниже. Требуй регулярка `\+`, такой маркер не совпал бы вовсе
  // — тихий ноль бюджета, то есть тот же отказ, ради которого падает опечатка в
  // имени, только на шаг раньше.
  const re = new RegExp(`${marker}:\\s*([a-zA-Z][\\w-]*)\\s*([+-]?)(\\d+)`, 'g');
  for (const line of diff.split('\n')) {
    if (!line.startsWith('+') || line.startsWith('+++')) continue;
    const found = [...line.matchAll(re)];
    // Строка назвала маркер, но ничего валидного не дала — опечатка в форме.
    // Тот же закон, что «нечего проверять» ≠ «проверено, чисто»: маркер-опечатка
    // ≠ «исключений не просили».
    if (!found.length && line.includes(`${marker}:`)) {
      die(`маркер ${marker} не разобрался — ожидается «${marker}: <метрика> +N — причина».`, [
        `маркер был: ${line.slice(1).trim()}`,
        `известные метрики: ${[...byKey.keys()].join(', ')}`,
      ]);
    }
    for (const match of found) {
      // Группы регулярки по порядку: 1 — метрика, 2 — знак (необязательный),
      // 3 — величина. Разложены в имена, чтобы позиционные `m[1..3]` не мелькали
      // по всему разбору нечитаемо.
      const [, key, sign, digits] = match;
      const metric = byKey.get(key);
      if (!metric) {
        die(`исключение называет неизвестную метрику \`${key}\` — опечатка не должна читаться как «исключений не просили».`, [
          `известные метрики: ${[...byKey.keys()].join(', ')}`,
          `маркер был: ${line.slice(1).trim()}`,
        ]);
      }
      if (sign !== '+') {
        const what = sign ? `не тот ЗНАК: ${sign}${digits}` : `НЕ НАЗВАН ЗНАК: ${digits}`;
        const dir = metric.up
          ? 'метрика может только РАСТИ, и `+N` тут означает согласованное ПАДЕНИЕ на N'
          : 'метрика может только УБЫВАТЬ, и `+N` означает согласованный РОСТ на N';
        die(`у исключения для \`${key}\` ${what}: ${dir}.`, [
          `нужно: ${marker}: ${key} +${digits} — причина + апрув`,
          `маркер был: ${line.slice(1).trim()}`,
          'Форма одна на все метрики: +N = величина разрешённого НАРУШЕНИЯ, а не дельта числа.',
          'Знак с ошибкой - это опечатка, а опечатка не должна читаться как «исключения не просили».',
        ]);
      }
      out[key] = (out[key] ?? 0) + Number(digits);
    }
  }
  return out;
}
