/**
 * ПЕРИМЕТР НЕАВТОРИЗОВАННОЙ ЗОНЫ — один список на всех, кто её судит (TRIP-445).
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ. Периметр зоны был выписан ТРИЖДЫ, и все три раза
 * по-разному:
 *   · 2ad `check-site-nav`          — семь путей, полный;
 *   · 2ab `check-ds-boundary`       — пять: без `Login.jsx` и `JoinTrip.jsx`;
 *   · 2ae `check-site-primitive-dup`— ДВА: только лендинг и обвязка, с
 *     комментарием «публичка/логин/join придут своими PR Ф6».
 * Страницы пришли ещё в августе, а списки за ними не пошли: каждый новый PR Ф6
 * дописывал себя в тот гард, который в тот день покраснел. Расхождение молча
 * становится вердиктом — гард отвечает «чисто» про дерево, половину которого не
 * открывал. Замерено: прогон 2ae с полным периметром сразу дал две настоящие
 * утечки (`.muted`, `.cflag` в `PublicTrip.jsx`), не видные никому три недели.
 *
 * Это тот же урок и то же лечение, что у `perimeter.mjs` (TRIP-321 §10): «два
 * гарда, отвечающие на соседние вопросы по одному дереву, обязаны иметь ОДИН
 * периметр». Здесь он для другого дерева — зоны, а не дизайн-слоя приложения.
 *
 * ★ ПУСТОЙ ИЛИ ИСЧЕЗНУВШИЙ ПУТЬ = КРАСНЫЙ, А НЕ ПРОПУСК. Гард, смотрящий в
 * пустую комнату, обязан падать громко: иначе «зону тихо сузили» выглядит как
 * «нарушений нет» (TRIP-282). Проверку несёт `assertZonePerimeter`, зовут её
 * все три гарда.
 */
import { existsSync } from 'node:fs';

/**
 * Все восемь маршрутов зоны живут в этих семи путях. Каталог — рекурсивно.
 * Добавляешь страницу в зону — дописываешь СЮДА, и её начинают судить все три
 * гарда сразу, а не тот один, что покраснел первым.
 */
const ZONE = [
  'src/components/site',
  'src/pages/Landing',
  'src/pages/Demo',
  'src/pages/Legal.jsx',
  'src/pages/PublicTrip.jsx',
  'src/pages/Login.jsx',
  'src/pages/JoinTrip.jsx',
];

/**
 * ★ ПЕРЕОПРЕДЕЛЕНИЕ — ДЛЯ ТЕСТОВ ГАРДОВ, И ТОЛЬКО.
 *
 * Тест гарда строит ВРЕМЕННЫЙ репозиторий из двух-трёх файлов и гоняет гард
 * подпроцессом с `cwd` в нём (шаблон `check-inline-styles.test.mjs`). Полного
 * дерева зоны там нет по построению, и строгая проверка периметра роняла бы
 * КАЖДЫЙ такой тест раньше, чем гард дойдёт до своего правила — то есть тест
 * перестал бы проверять то, ради чего написан.
 *
 * Приём не новый: ровно так 2ae читал свой `ZONE_MARKUP_DIRS` до того, как
 * периметр стал общим. Обхода в проде это не даёт — переменную надо ЗАДАТЬ, а
 * в CI её никто не задаёт; и пустое значение игнорируется, чтобы `ZONE_PERIMETER=`
 * не превращалось в «периметр пуст, всё чисто».
 */
export const SITE_ZONE = (process.env.ZONE_PERIMETER || '')
  .split(',').map((s) => s.trim()).filter(Boolean);
if (!SITE_ZONE.length) SITE_ZONE.push(...ZONE);

/**
 * Периметр обязан существовать целиком. Исчезнувший путь означает, что зону
 * переставили, а гард остался смотреть в пустоту — это провал проверки, а не её
 * успех.
 * @param {string} guard имя гарда для сообщения
 * @param {string[]} [paths] переопределение (только для тестов)
 */
export function assertZonePerimeter(guard, paths = SITE_ZONE) {
  const missing = paths.filter((p) => !existsSync(p));
  if (!missing.length) return;
  console.error(`::error::${guard}: путь периметра зоны не существует: ${missing.join(', ')}`);
  console.error('  Гард смотрел бы в пустую комнату и отвечал «чисто». Если зона переехала —');
  console.error('  правь SITE_ZONE в scripts/ci/zone-perimeter.mjs: он ОДИН на все гарды зоны.');
  process.exit(2);
}
