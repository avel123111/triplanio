#!/usr/bin/env node
/**
 * CI guard 2u — check-css-comments (TRIP-344).
 *
 * ЗАЧЕМ. Блок-комментарий CSS, у которого потерян терминатор (или, наоборот, появился
 * ЛИШНИЙ терминатор литералом внутри текста комментария), молча меняет то, что сборщик
 * считает ПРАВИЛОМ, а что — комментарием. В TRIP-344 построчное снятие маркеров
 * `visual-diff-*` (шаг воркфлоу 2p) съело терминатор на последней строке блока, а
 * следом закрывающая пара была ещё и упомянута литералом в тексте — и правило
 * `.icon-btn .dot { position: absolute }` было ВПИТАНО в комментарий, не доехало до
 * бандла: метка непрочитанных потеряла абсолютное позиционирование, стала вторым
 * ребёнком grid-кнопки и вытолкнула иконку колокола на 10px вверх.
 *
 * НИ ОДИН существующий гард этого не ловил: 2p сравнивает РАЗОБРАННЫЙ CSS — а правила
 * нет с ОБЕИХ сторон; 2n видит класс живым литералом на других экранах; сборка не
 * падала, а минифицировала текст комментария и роняла правило. Поймалось только
 * рендером живого экрана (замер: в бандле `.icon-btn .dot` — ноль вхождений; после
 * фикса — есть). Этот гард делает класс дефекта машинно видимым.
 *
 * ПРЕДИКАТ (только HEAD, АБСОЛЮТНЫЙ инвариант, а не храповик). Для каждого CSS-файла
 * крошечный сканер строк/комментариев (ТОЛЬКО стандартная библиотека — поэтому гард
 * живёт в джобе `guards`, у которой намеренно НЕТ `npm ci`) флагует ровно два случая,
 * каждый из которых в валидном CSS не встречается НИКОГДА:
 *   1. закрывающая пара комментария ВНЕ комментария — осиротевший / лишний терминатор
 *      (это и есть вторая ошибка инцидента TRIP-344, ею он и ловится);
 *   2. конец файла ВНУТРИ комментария — незакрытый комментарий.
 * Строки (`content: "…"`) пропускаются, поэтому `content` с парой-терминатором внутри
 * литерала терминатором НЕ считается.
 *
 * ЧЕГО ЭТОТ ГАРД НЕ ЛОВИТ — названо честно (иначе «OK» печатался бы над непроверенным).
 * Съеденный терминатор, «сцеленный» закрытием СЛЕДУЮЩЕГО комментария (правило впитано,
 * а сам файл остаётся синтаксически сбалансированным), тут НЕ ловится: единственный
 * дешёвый признак — «в теле комментария есть блок `{…}`» — даёт ложные срабатывания на
 * ЖУРНАЛЬНЫХ комментариях 2p, которые легитимно цитируют селекторы и `{@media …}`
 * (замер по репо: такой предикат краснеет на `app.css` — честная документация). А
 * ложное срабатывание тут дороже пропуска: оно заблокировало бы КАЖДЫЙ 2p-PR. Надёжно
 * эта форма ловится только сверкой набора правил база↔HEAD (узор 2n) — это отдельная,
 * НЕ мелкая работа; пока её нет, форма закрывается тем же, чем поймалась сегодня, —
 * рендером живого экрана (это и стоит в планке приёмки объектных PR).
 *
 * Почему не `postcss` (как 2p). postcss «лечит» несцеленный комментарий так же, как
 * сборщик, и тянул бы гард в джобу с `npm ci`. Сканер строк/комментариев — ровно та
 * работа, которую стандартная библиотека делает надёжно, а инвариант джобы `guards`
 * («без зависимостей, старт мгновенный») остаётся цел (тот же довод в шапке 2r).
 *
 * A CI guard is code: у него есть тест (`check-css-comments.test.mjs`), и каждый его
 * зелёный проверен красным — мутацией по обоим правилам предиката (TRIP-282).
 */
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';

const git = (args) =>
  execFileSync('git', args, {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
    stdio: ['ignore', 'pipe', 'pipe'],
  });

/**
 * Сканирует CSS: строки пропускает (чтобы пара-терминатор внутри `content:"…"` не
 * читалась как закрытие комментария), комментарии выделяет и проверяет закрытость.
 * Возвращает список находок с номером строки.
 * @param {string} css
 * @returns {{line:number, kind:string}[]}
 */
export function scanCss(css) {
  const findings = [];
  const n = css.length;
  let i = 0;
  let line = 1;

  while (i < n) {
    const c = css[i];
    const d = css[i + 1];

    // Строковый литерал — пропускаем целиком (внутри терминатор не считается).
    if (c === '"' || c === "'") {
      const quote = c;
      i += 1;
      while (i < n) {
        if (css[i] === '\\') { i += 2; continue; }
        if (css[i] === '\n') line += 1;
        if (css[i] === quote) { i += 1; break; }
        i += 1;
      }
      continue;
    }

    // Начало комментария — ищем его закрытие.
    if (c === '/' && d === '*') {
      const startLine = line;
      i += 2;
      let closed = false;
      while (i < n) {
        if (css[i] === '*' && css[i + 1] === '/') { i += 2; closed = true; break; }
        if (css[i] === '\n') line += 1;
        i += 1;
      }
      if (!closed) findings.push({ line: startLine, kind: 'незакрытый комментарий /*' });
      continue;
    }

    // Закрывающая пара вне комментария и вне строки — осиротевший / лишний терминатор.
    if (c === '*' && d === '/') {
      findings.push({ line, kind: 'осиротевший терминатор комментария */' });
      i += 2;
      continue;
    }

    if (c === '\n') line += 1;
    i += 1;
  }

  return findings;
}

function listCssFiles() {
  // ВСЕ .css, затем фильтр по префиксу: `src/**/*.css` в pathspec НЕ матчит файл
  // прямо в `src/` (напр. `src/index.css` — второй канон типографики) и в
  // `public/` (`public/landing.css`). Тот пропуск поймал e2e-тест, а не ревью.
  const out = git(['ls-files', '*.css']);
  return out
    .split('\n')
    .map((s) => s.trim())
    .filter((p) => p && (p.startsWith('src/') || p.startsWith('public/')));
}

function main() {
  const files = listCssFiles();
  let bad = 0;
  for (const file of files) {
    const findings = scanCss(readFileSync(file, 'utf8'));
    for (const f of findings) {
      bad += 1;
      console.error(`✗ ${file}:${f.line} — ${f.kind}`);
    }
  }

  if (bad) {
    console.error(
      `\n2u check-css-comments: ${bad} порч(и) комментария. ` +
        'Сломанная пара комментария молча роняет правило из бандла — см. шапку гарда (TRIP-344).',
    );
    process.exit(1);
  }
  console.log(`2u check-css-comments: ${files.length} CSS-файлов, комментарии целы.`);
}

// Запуск только как CLI; при импорте из теста main() не вызывается.
if (import.meta.url === `file://${process.argv[1]}`) main();
