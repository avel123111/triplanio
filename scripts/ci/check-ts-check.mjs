#!/usr/bin/env node
/**
 * CI guard 2s (TRIP-377, Ф0.1 эпика TRIP-374) — храповик ВВЕРХ: файл, у которого
 * прагма `// @ts-check` ДЕЙСТВОВАЛА на базовой ветке, не может её потерять.
 *
 * ЗАЧЕМ. Эпик «единая дверь в данные» переносит запись и чтение на контракт
 * (endpoint + типы ответа). Единственный слой, который поймает расхождение
 * «сервер отдаёт не то, что читает экран», — типы; но `checkJs` в проекте
 * ВЫКЛЮЧЕН, поэтому единственный вход в проверку — поштучная прагма в файле.
 * Прагма при этом ничем не удерживается: она снимается одной строкой, а прогон
 * `npm run typecheck` от этого ЗЕЛЕНЕЕТ (ошибок стало меньше — их стало
 * ноль), то есть регресс покрытия выглядит как успех. Это и есть предмет 2s.
 *
 * ЦЕНА `checkJs: true` — ЗАМЕР, а не оценка (пинованный `node_modules/.bin/tsc`
 * 5.9.3, `-p ./jsconfig.json --checkJs --noEmit`, замер 2026-08-09):
 *   · на периметре `jsconfig.json` (214 файлов программы) — 420 ошибок в 155 файлах;
 *   · на всём `src/` (include `src/**`, exclude только `node_modules`/`dist`) — 401 в 147.
 * Числа НАЗВАНЫ ОБА намеренно: «сколько стоит включить checkJs» не определено без
 * периметра, и подставить одно вместо другого легко. В постановке задачи стояло
 * 1366 — это ЗАМЕР ДРУГОГО ДЕРЕВА (до TRIP-388, где 21 компонент ДС получил
 * аннотации и снял сотни TS2739/TS2741). Отсюда же режим работы: `checkJs`
 * включается не флагом, а файлами — каждый обязан быть зелёным ПОСЛЕ настоящей
 * типизации, поэтому прагмы не ставятся пачкой «раз уж мы здесь».
 *
 * ★ ПРЕДИКАТ РАНЬШЕ ЧИСЛА. «Файл с `@ts-check`» тремя способами даёт ТРИ разных
 * числа на одном дереве, и никто при этом не ошибается:
 *   · греп по тексту                              — 22
 *   · греп + ведущий комментарий любого вида      — 10
 *   · СЕМАНТИКА TS (то, что реально проверяется)  —  9
 * Разница не хвостовая: 12 файлов лишь УПОМИНАЮТ `// @ts-check` в прозе
 * комментария (`AppHeader.jsx`, `icons.jsx`, `resolveAuthor.js`, …), а
 * `css-custom-props.d.ts` держит упоминание в БЛОЧНОМ комментарии, который TS
 * прагмой не считает вовсе. Считать текстом значило бы захраповить число, у
 * которого 13 единиц ничего не проверяют, и одновременно ПРОПУСТИТЬ настоящий
 * регресс: сдвинуть живую прагму под первый импорт — проверка выключена,
 * текстовое число не шелохнулось. Это ровно тот класс дефекта, что «понижение
 * метрики инлайнов без снятия инлайна» (TRIP-388 PR 4): предикат, чувствительный
 * к ФОРМЕ ЗАПИСИ, — дыра по построению.
 *
 * ПОЭТОМУ ПРЕДИКАТ ПОВТОРЯЕТ TS, а не грепает. Правило TS (`processCommentPragmas`
 * → `getLeadingCommentRanges(text, 0)`, `PragmaKindFlags.SingleLine`, «последняя
 * директива побеждает») проверено ПРОБОЙ на живом tsc 5.9.3 — файл с заведомой
 * ошибкой типов и прагмой в разных написаниях:
 *   `// @ts-check` первой строкой                      → ПРОВЕРЯЕТСЯ
 *   `//@ts-check` / `/// @ts-check` / `//   @ts-check`  → ПРОВЕРЯЕТСЯ
 *   `// @ts-check` после блочного комментария и пустой строки → ПРОВЕРЯЕТСЯ
 *   `// @ts-check` с текстом после                     → ПРОВЕРЯЕТСЯ
 *   `// @TS-Check` (регистр TS не различает)           → ПРОВЕРЯЕТСЯ
 *   BOM U+FEFF / NBSP U+00A0 / NEL U+0085 перед прагмой → ПРОВЕРЯЕТСЯ
 *   шебанг `#!/usr/bin/env node` строкой выше          → ПРОВЕРЯЕТСЯ
 *   `@ts-check` внутри БЛОЧНОГО комментария            → НЕ проверяется
 *   `// @ts-check` НИЖЕ первой строки кода             → НЕ проверяется
 *   `// TODO @ts-check` (не в начале комментария)      → НЕ проверяется
 *   `// @ts-check-foo`                                 → НЕ проверяется
 *   `// @ts-check` + ниже `// @ts-nocheck`             → НЕ проверяется (последняя побеждает)
 *
 * ★ Пять строк таблицы (регистр, BOM/NBSP/NEL, шебанг) ПОЯВИЛИСЬ ПОСЛЕ
 * РАСХОЖДЕНИЯ: предикат считал BOM, NBSP, NEL, шебанг и другой регистр
 * «первым токеном» и отвечал «прагмы нет», тогда как tsc файл ПРОВЕРЯЛ. Цена
 * такого недоучёта не тихая: BOM, дописанный редактором в шапку файла с живой
 * прагмой, выкидывал бы файл из набора и гард краснел бы «верни прагму» — про
 * прагму, которая на месте и работает (класс «маркер, вынуждающий лгать»).
 * Нашёл `code-simplifier` прогоном по настоящему tsc, а не чтением, — поэтому
 * все пятнадцать написаний теперь стоят в тесте и судятся самим tsc.
 *
 * ЧТО СВЕРЯЕТСЯ — ДВА ПРАВИЛА, и оба БЛОКИРУЮТ, потому что каждое закрывает то,
 * что пропускает другое:
 *
 *   A (пофайловое, «на месте»). Путь из базового набора, который на HEAD
 *     существует, обязан остаться в наборе; а если путь исчез, но git показал
 *     преемника и тот на месте — правило спрашивается ПО ПРЕЕМНИКУ. Ловит
 *     подмену, которую счёт не видит: прагму сняли с одного файла и поставили
 *     на другой — число плоское, регресс настоящий. Называет файл поимённо.
 *     ★ Половина «по преемнику» появилась ПОСЛЕ ЗАМЕРА: без неё `git mv` в том
 *     же PR выводил файл из-под A ЦЕЛИКОМ (путь на HEAD не существует), дальше
 *     работало только счётное B, а оно закрывается ЛЮБОЙ новой работой —
 *     `git mv` + снятие прагмы + прагма на новом файле давало `2 → 2 (+0)` и
 *     exit 0, тогда как редакция ДО разделения правил ловила это поимённо.
 *     То есть обход правила A стоил одной строки `git mv`.
 *   B (счётное, «исчезло с базового пути»). Всё, что с базового пути пропало,
 *     судится одним вопросом: восполнено ли ЧИСЛО. Переезд с живой прагмой даёт
 *     −1 на старом пути и +1 на новом, то есть ноль. Переезд со снятой прагмой
 *     и удаление дают −1 и краснеют.
 *
 * ★ ПОЧЕМУ B НЕ СПРАШИВАЕТ У GIT, ЧТО ЭТО БЫЛО. Первая редакция прощала потерю
 * по флагу `D` из `git diff --name-status`, а git выдаёт `D`+`A` вместо `R`, как
 * только сходство падает ниже порога (по умолчанию 50%). Замерено: переезд с
 * переписыванием и снятой прагмой печатал `-1` и выходил 0 — то есть число
 * ПАДАЛО НА ГЛАЗАХ при зелёном вердикте (нашёл ревьюер Codex, PR #743). Вывод
 * общий: **вердикт не должен зависеть от того, как git НАЗВАЛ правку** — любой
 * порог сходства обходится переписыванием. Связка `--find-renames=10% -l0`
 * осталась, и мест, где она всё же влияет на приговор, РОВНО ДВА — оба названы,
 * потому что «связка на приговор не влияет» было бы неправдой:
 *   · правило A по преемнику — только УЖЕСТОЧАЕТ (добавляет красное, никогда не
 *     снимает), поэтому дыры не открывает: не распознанный переезд по-прежнему
 *     судится числом;
 *   · вычет переезда в TypeScript — ЕДИНСТВЕННОЕ место, где связка ПРОЩАЕТ, и
 *     это остаток той же дыры, названный вслух. ЗАМЕРЕНО: при пороге 10% git
 *     пару «снесённый `src/a.js` с прагмой» + «независимый новый `src/brandnew.ts`»
 *     называет переименованием `R012`, и гард печатает `2 → 1 (-1)`, объясняет
 *     это несуществующим переездом в TypeScript и выходит 0 — тот же симптом,
 *     ради которого правило B перестали спрашивать у git. При `--find-renames=20%`
 *     и выше эта пара уже не сходится, а калиброванный тест переезда `.js → .ts`
 *     с переработкой держится до 25% включительно (`R028`). Порог не поднят
 *     здесь намеренно: это правка ПОВЕДЕНИЯ вердикта и тюнинг числа, а не
 *     уборка, — идти она должна отдельным решением; принципиальный выход,
 *     снимающий зависимость от git насовсем, — судить переезд в TypeScript по
 *     СОВПАДЕНИЮ ПУТИ С ТОЧНОСТЬЮ ДО РАСШИРЕНИЯ (`src/x.js` → `src/x.ts`),
 *     а конверсию с переездом отправлять в разговор, как удаление.
 *
 * УДАЛЕНИЕ ФАЙЛА ИЗ НАБОРА — КРАСНОЕ, и это решение, а не недосмотр. Прощать его
 * нечем: «удалено» и «переехало с переписыванием» с точки зрения дерева
 * неразличимы, а прощение первого — готовый обход для второго. Цена названа:
 * снос экрана с прагмой требует разговора (сообщение так и говорит). Маркера
 * под это НЕ ЗАВЕДЕНО намеренно — как у 2q, второй канал вернул бы закрытую
 * дверь; если такие сносы окажутся частыми, правильный ход — объявляемый
 * маркер с проверкой, а не молчаливое вычитание.
 *
 * ГРАНИЦЫ, названные вслух:
 *   · Прагма на файле, который tsc НЕ ЗАГРУЖАЕТ, инертна (программа = `include`
 *     из `jsconfig.json` + граф импортов). Гард этого не проверяет — для этого
 *     нужен прогон tsc, а джоба `guards` намеренно живёт без `npm ci`. Замер на
 *     вводящем PR: все 9 файлов набора программой загружены (`tsc --listFiles`).
 *   · Считаются только JS-семейные расширения. У `.ts`/`.d.ts` прагма не нужна
 *     (проверяются всегда), и их учёт раздувал бы храповик даром; переезд
 *     `.js → .ts` поэтому не потеря, а РОСТ покрытия — вычитается и печатается.
 *   · Сторона HEAD читается из РАБОЧЕГО ДЕРЕВА (отслеживаемые файлы), сторона
 *     базы — из `BASE_REF`. Локально это судит то, что у тебя на диске.
 *
 * Env: BASE_REF (по умолчанию origin/dev). Недостижимая база — КРАСНЫЙ (код 2), а
 * не пропуск: храповик, который ничего не измерил, не должен печатать «OK»
 * (урок пола 2o). Ноль файлов на HEAD — тоже код 2 по той же причине.
 * Exit: 0 ok, 1 нарушение, 2 внутренняя ошибка.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';

const BASE_REF = process.env.BASE_REF || 'origin/dev';
const SCANNED = /\.(jsx?|mjs|cjs)$/;
const ROOT = 'src/';

const unknown = process.argv.slice(2).filter((a) => a !== '--');
if (unknown.length) {
  console.error(`::error::check-ts-check: unknown flag ${unknown.join(' ')}.`);
  console.error('  Флагов у гарда нет: потолок живёт на базовой ветке, а не в файле, который правит PR.');
  process.exit(2);
}

// `core.quotePath=false` — НЕСУЩЕЕ, а не косметика: по умолчанию git печатает
// не-ASCII пути C-квотированными (`"src/\303\274ber.js"`), фильтр расширений
// спотыкается о завершающую кавычку, и файл выпадает из наблюдения ЦЕЛИКОМ.
// Замерено: `src/über.js` со снятой прагмой давал `1 → 1 (+0)` и exit 0 —
// ТИХИЙ ЗЕЛЁНЫЙ ровно на том, против чего гард заведён.
const git = (args) =>
  execFileSync('git', ['-c', 'core.quotePath=false', ...args], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
    stdio: ['ignore', 'pipe', 'pipe'],
  });

/* ------------------------------ the predicate ----------------------------- */

/**
 * Действует ли в файле `// @ts-check` — ровно по правилам TypeScript.
 *
 * TS смотрит ТОЛЬКО ведущие комментарии (до первого токена) и ТОЛЬКО
 * однострочные; из встреченных директив побеждает ПОСЛЕДНЯЯ. Каждое из этих
 * трёх условий проверено пробой на живом tsc (список написаний — в шапке).
 */
/** Конец однострочного комментария — ЛЮБОЙ терминатор строки JS, а не только
 *  `\n`. Их четыре: LF, CR, LSEP U+2028, PSEP U+2029, и различие не
 *  теоретическое: `// @ts-check⟨U+2028⟩// @ts-nocheck` — это ДВА комментария,
 *  tsc читает второй и проверку ВЫКЛЮЧАЕТ (замерено), а поиск по одному `\n`
 *  склеивает их в один и объявляет файл покрытым. Отказ в опасную сторону:
 *  гард печатает «покрыт», покрытия нет. Нашёл ревьюер (Codex) на PR #743. */
const LINE_END = /[\n\r\u2028\u2029]/g;
function endOfLine(src, from) {
  LINE_END.lastIndex = from;
  return LINE_END.exec(src)?.index ?? src.length;
}

function tsCheckEnabled(src) {
  let enabled = false;
  let i = 0;
  let onlyTriviaSoFar = true;
  while (i < src.length) {
    const c = src[i];
    // Пробел по версии JS (`\s` включает BOM U+FEFF, NBSP U+00A0 и LSEP U+2028)
    // плюс NEL U+0085, которого в `\s` НЕТ. Символы названы ИМЕНАМИ и записаны
    // ЭКРАНИРОВАННО, и это не аккуратность: литеральный U+2028 в комментарии
    // ЗАВЕРШАЕТ СТРОКУ в JS и рвёт файл (проверено — `node --check` упал ровно
    // на нём), а BOM делает файл двоичным для грепа. Тот же класс, что
    // литеральный NUL в памяти про 2p: управляющий символ пишется ИМЕНЕМ.
    //
    // Узкий список ' \t\r\n' был НЕДОУЧЁТОМ, и цена его НЕ ТИХАЯ: BOM,
    // дописанный редактором в шапку файла с ЖИВОЙ прагмой, выкидывал бы файл
    // из набора, и гард краснел бы текстом «верни прагму» — про прагму,
    // которая стоит на месте и работает. Нашёл `code-simplifier` прогоном.
    if (/[\s\u0085]/.test(c)) {
      i++;
    } else if (onlyTriviaSoFar && c === '#' && src[i + 1] === '!') {
      i = endOfLine(src, i) + 1; // шебанг — тривия, tsc его пропускает
      onlyTriviaSoFar = false;
    } else if (c === '/' && src[i + 1] === '/') {
      const end = endOfLine(src, i);
      // `@(\S+)` — как в singleLinePragmaRegEx у TS: имя директивы кончается на
      // первом пробеле, поэтому `@ts-check-foo` директивой НЕ является, а
      // `// @ts-check и почему` — является. Регистр TS не различает (`i` в его
      // регулярке + `toLowerCase()`), поэтому `// @TS-Check` — рабочая прагма.
      const m = /^\/\/\/?\s*@(\S+)/.exec(src.slice(i, end));
      const name = m?.[1].toLowerCase();
      if (name === 'ts-check' || name === 'ts-nocheck') enabled = name === 'ts-check';
      i = end + 1;
      onlyTriviaSoFar = false;
    } else if (c === '/' && src[i + 1] === '*') {
      const end = src.indexOf('*/', i + 2);
      i = end === -1 ? src.length : end + 2;
      onlyTriviaSoFar = false;
    } else {
      break; // первый токен — дальше TS директивы не ищет, и мы тоже
    }
  }
  return enabled;
}

/** Упоминание есть, а директива не действует — самый интересный вид регресса. */
const mentionsButInert = (src) => !tsCheckEnabled(src) && src.includes('@ts-check');

/* --------------------------------- sides ---------------------------------- */

try {
  git(['rev-parse', '--verify', `${BASE_REF}^{commit}`]);
} catch {
  console.error(`::error::check-ts-check: BASE_REF ${BASE_REF} не разрешается — измерить храповик нечем.`);
  console.error('  Это КРАСНЫЙ, а не пропуск: гард, который ничего не измерил, не должен печатать OK.');
  process.exit(2);
}

// Всё ниже — от корня репо (pathspec `src/`, чтение файлов). Запуск из
// подкаталога без этого нашёл бы ноль файлов и напечатал бы «OK».
process.chdir(git(['rev-parse', '--show-toplevel']).trim());

/** Файлы, где ВООБЩЕ встречается текст прагмы, — дешёвый отбор кандидатов. */
function candidates(rev) {
  try {
    // `-i` обязателен: TS сравнивает имя директивы БЕЗ учёта регистра, значит
    // `// @TS-Check` — рабочая прагма. Без флага предикат её узнаёт, а кандидат
    // не находится — починка регистра была бы инертной (мутация, которая не
    // запускается, ловится только так: два места, одно правило).
    const args = ['grep', '-l', '-I', '-i', '--fixed-strings', '@ts-check'];
    if (rev) args.push(rev);
    return git([...args, '--', ROOT])
      .split('\n')
      .filter(Boolean)
      .map((line) => (rev ? line.slice(rev.length + 1) : line))
      .filter((p) => SCANNED.test(p));
  } catch (e) {
    // git grep выходит 1, когда совпадений нет; всё остальное — авария.
    if (e.status === 1) return [];
    throw e;
  }
}

let baseSet;
let headSet;
let headInert;
let headText;
try {
  baseSet = new Set(
    candidates(BASE_REF).filter((p) => tsCheckEnabled(git(['show', `${BASE_REF}:${p}`]))),
  );
  // Каждый кандидат читается РОВНО ОДИН раз: набор, список инертных и разбор
  // потерь спрашивают один и тот же текст.
  const head = new Map(
    candidates(null)
      .filter((p) => existsSync(p))
      .map((p) => [p, readFileSync(p, 'utf8')]),
  );
  headText = head;
  headSet = new Set([...head].filter(([, src]) => tsCheckEnabled(src)).map(([p]) => p));
  headInert = [...head].filter(([, src]) => mentionsButInert(src)).map(([p]) => p);
} catch (e) {
  console.error(`::error::check-ts-check: не смог прочитать дерево: ${e.stderr || e.message}`);
  process.exit(2);
}

/**
 * Связка «старый путь → новый» — чтобы ОБЪЯСНИТЬ расхождение в сообщении,
 * спросить правило A по преемнику и вычесть переезд в TypeScript. СЧЁТНОЕ
 * правило B её не спрашивает НИ РАЗУ, и это не стиль: первая редакция прощала
 * потерю по флагу `D`, а git выдаёт `D`+`A` вместо `R`, как только сходство
 * падает ниже порога (по умолчанию 50%). Замерено — переезд с переписыванием и
 * снятой прагмой печатал `-1` и выходил 0 (ревьюер Codex, PR #743). Порог
 * поэтому опущен до 10% и снят лимит `-l0` (git МОЛЧА бросает поиск
 * переименований на больших диффах), но опираться на него в ПРОЩЕНИИ всё равно
 * нельзя — любой порог обходится переписыванием, а низкий вдобавок сводит
 * посторонние файлы (замер и оба следствия — в шапке, «мест ровно два»).
 */
let renamed = new Map();
try {
  for (const line of git([
    'diff', '--name-status', '--find-renames=10%', '-l0', `${BASE_REF}...HEAD`, '--', ROOT,
  ])
    .split('\n')
    .filter(Boolean)) {
    const [status, a, b] = line.split('\t');
    if (status.startsWith('R')) renamed.set(a, b);
  }
} catch (e) {
  console.error(`::error::check-ts-check: не смог сравнить с ${BASE_REF}: ${e.stderr || e.message}`);
  process.exit(2);
}

/* -------------------------------- verdict --------------------------------- */

if (!headSet.size) {
  console.error('::error::check-ts-check: на HEAD не найдено НИ ОДНОГО файла с действующей прагмой `// @ts-check`.');
  console.error('  «Нечего проверять» и «проверено, чисто» не должны печатать один вердикт (TRIP-282).');
  process.exit(2);
}

// Переезд в TypeScript — это РОСТ покрытия, а не потеря: у `.ts` прагма не
// нужна, файл проверяется всегда (шапка говорит это же про `.d.ts`). Без
// вычета `git mv src/a.js src/a.ts` при живой прагме давал `-1` и код 1 —
// красный ровно на ходе, ради которого эпик и заведён. Конверсия ПЛЮС переезд в
// другой каталог под вычет НЕ попадает намеренно: тогда её пришлось бы брать у
// git, а это и есть закрытая дверь. Такой ход — разговор, как и удаление.
const TS_EXTS = ['.ts', '.tsx', '.mts', '.cts'];

// ПРАВИЛО A (пофайловое, на МЕСТЕ). Путь из базового набора, который на HEAD
// существует, обязан остаться в наборе. Классификация диффа тут не спрашивается
// вовсе — только «файл на месте и прагмы нет».
const lost = [];
// ПРАВИЛО B (счётное). Всё, что с базового пути ИСЧЕЗЛО — переезд, переезд с
// переписыванием, удаление, — судится ОДНИМ вопросом: восполнено ли число.
// Переезд с живой прагмой даёт −1 на старом пути и +1 на новом, то есть ноль;
// переезд со снятой прагмой и удаление дают −1 и краснеют. Так СЧЁТНЫЙ вердикт
// перестаёт зависеть от того, как git назвал правку (у кого связка всё же
// спрошена — названо в шапке, «мест ровно два»).
const vanished = [];
const converted = [];
const inertAt = (p) => mentionsButInert(headText.get(p) ?? readFileSync(p, 'utf8'));
for (const path of baseSet) {
  if (existsSync(path)) {
    if (!headSet.has(path)) lost.push({ path, now: path, inert: inertAt(path) });
    continue;
  }
  const to = renamed.get(path) ?? null;
  // Переезд в TypeScript — РОСТ покрытия: у `.ts` прагма не нужна, файл
  // проверяется всегда. Признаётся ПО ПУТИ (`src/x.js` → `src/x.ts`), а НЕ по
  // связке git: при пороге 10% git спаривает снос с посторонним новым `.ts`
  // (замерено — `R043`), и гард печатал `-1`, объявлял это «переводом в
  // TypeScript» и выходил 0, то есть ровно тот обход, который чинил ревьюер,
  // возвращался с другой стороны. После правки **связка может только УЖЕСТОЧАТЬ**
  // (сообщение + правило A по преемнику) и не прощает нигде.
  const twin = TS_EXTS.map((ext) => path.replace(/\.[^./]+$/, ext)).find((p) => existsSync(p));
  if (twin) {
    converted.push(`${path} → ${twin}`);
    continue;
  }
  vanished.push({ path, to });
  // ПРАВИЛО A ПО НОВОМУ ПУТИ: преемник на месте и прагмы у него нет — это ровно
  // та подмена, ради которой A заведено, только с `git mv` в том же PR. Без
  // строки переезд выводил файл из-под A целиком, и обход стоил одной команды
  // (замер и разбор — в шапке). Связка тут только УЖЕСТОЧАЕТ: не распознанный
  // переезд по-прежнему судится числом.
  // …но только для JS-семейного преемника: советовать «верни прагму» файлу
  // `.ts` — ложная инструкция, прагма там не нужна и ничего не включает.
  if (to && SCANNED.test(to) && existsSync(to) && !headSet.has(to)) {
    lost.push({ path, now: to, inert: inertAt(to) });
  }
}

// Компенсацией исчезнувшему служит ЛЮБОЙ новый путь под прагмой — в первую
// очередь тот, куда файл переехал. Считать нехватку разностью с общим числом
// нельзя: счёт падает и от правила A («файл на месте, прагму сняли»), и тогда B
// перехватывало бы вердикт, печатая пустой список вместо имени файла.
const newWithPragma = [...headSet].filter((p) => !baseSet.has(p));
const uncompensated = vanished.length - newWithPragma.length;
// Набор НОВЫХ путей: `headSet` состоит из них, а `renamed` ключуется СТАРЫМИ —
// сверка с ключами всегда ложна, и переехавший файл печатался бы «+ новым».
// Число при этом верное, врёт только строка, а ложное сообщение хуже пропуска.
const renamedTo = new Set(renamed.values());
const added = [...headSet].filter((p) => !baseSet.has(p) && !renamedTo.has(p));

console.log(
  `check-ts-check: файлов с действующей прагмой // @ts-check — ${baseSet.size} на ${BASE_REF} → ${headSet.size} на HEAD` +
    ` (${headSet.size - baseSet.size >= 0 ? '+' : ''}${headSet.size - baseSet.size})`,
);
if (added.length) console.log(`  + ${added.join(' · ')}`);
if (converted.length) console.log(`  → переведено в TypeScript (прагма больше не нужна): ${converted.join(' · ')}`);
if (headInert.length) {
  console.log(
    `  i упоминают «@ts-check» в прозе, но директивы не несут (${headInert.length}): ${headInert.join(' · ')}`,
  );
}

// Оба правила ПЕЧАТАЮТСЯ, и выход один: «сработало A» и «сработало B» — разные
// диагнозы, и глушить второй ранним `exit` значило бы послать автора чинить
// половину.
let violated = false;

if (uncompensated > 0) {
  violated = true;
  console.error(
    `::error::check-ts-check: покрытие типами упало на ${uncompensated} — с базового пути исчезли файлы, и число не восполнено`,
  );
  for (const v of vanished) {
    const hint = v.to
      ? headSet.has(v.to)
        ? `переехал в ${v.to}, прагма на месте`
        : SCANNED.test(v.to)
          ? `похоже, переехал в ${v.to} — верни туда \`// @ts-check\` первой строкой`
          : `похоже, переехал в ${v.to} и переведён в TypeScript. Вычет конверсии берётся` +
            ' ПО ПУТИ (`x.js` → `x.ts`), а конверсия ВМЕСТЕ с переездом — нет: иначе её' +
            ' пришлось бы брать у git, а это закрытая дверь. Если это она, скажи в PR'
      : 'преемник не найден: если файл удалён намеренно, скажи об этом в PR — храповик' +
        ' считает файлы, и такое падение обязано быть решением, а не побочным эффектом';
    console.error(`  ✗ ${v.path}: ${hint}`);
  }
}

if (lost.length) {
  violated = true;
  console.error('::error::check-ts-check: покрытие типами упало — файл потерял действующую прагму `// @ts-check`');
  for (const l of lost) {
    console.error(
      `  ✗ ${l.now}${l.now === l.path ? '' : ` (был ${l.path})`}: на ${BASE_REF} прагма действовала, на HEAD — нет.` +
        (l.inert
          ? '\n    → текст `@ts-check` в файле ЕСТЬ, но директивой не является: TS читает только ОДНОСТРОЧНЫЕ' +
            '\n      комментарии ДО первого токена, и побеждает ПОСЛЕДНЯЯ из @ts-check/@ts-nocheck.' +
            '\n      Верни `// @ts-check` первой строкой файла.'
          : '\n    → верни `// @ts-check` и почини типы, а не наоборот: прагма — единственный вход в' +
            '\n      проверку, пока `checkJs` выключен (цена включения записана в шапке гарда).'),
    );
  }
}

process.exit(violated ? 1 : 0);
