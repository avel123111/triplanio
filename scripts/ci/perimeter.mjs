/**
 * ПЕРИМЕТР ЭПИКА (TRIP-321/337 §10) — один предикат на всех, кто судит разметку
 * и стили дизайн-слоя.
 *
 * ЧТО ЭТО. Лендинг, экран входа и публичные правовые страницы унификацией НЕ
 * трогаются до фазы 10. Это не «забыли», а решение: они портированы отдельной
 * статикой, живут своей типографикой и своим `.card`/`.btn`, и втягивать их в
 * канон раньше времени значит менять маркетинговую страницу ради числа в гарде.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ. Предикат родился в `audit-design.mjs` и там же
 * применялся, поэтому гард 2q, написанный позже, судил разметку, которую эпик
 * из периметра ИСКЛЮЧИЛ: `btn--lg`/`btn--white` (LandingPage, PublicTrip) и
 * `card--wide` печатались как «класс не существует, элемент МОЛЧА получит
 * дефолт» - заведомо ложно, правило у них есть в `public/landing.css`, который
 * инжектится рантаймом на маркетинговых роутах (`SiteChrome.useLandingCss`).
 * Два гарда, отвечающие на соседние вопросы по одному дереву, обязаны иметь
 * ОДИН периметр, иначе расхождение молча становится вердиктом.
 *
 * ⚠️ ЦЕНА, И ОНА ОСОЗНАННАЯ. Исключение симметрично: 2q перестаёт проверять на
 * лендинге не только ложные случаи, но и ЗАКОННЫЕ (`btn--primary`, `btn--ghost`
 * там тоже есть). Лендинг не судится НИ В ОДНУ СТОРОНУ до фазы 10, и снимается
 * это одной строкой в одном месте - в чём и смысл общего предиката.
 *
 * ⚠️ ГРАНИЦА ПРИМЕНЕНИЯ. 2q применяет предикат к скану РАЗМЕТКИ. К скану CSS -
 * нет, и сегодня это разницы не даёт: из CSS-файлов `src/**` под предикат
 * попадают ровно два - `pages/login.css` и `pages/PublicTrip.css` (всего под
 * него подходит 6 файлов, остальные 4 - разметка), а канон-обличий
 * (`<семья>--<хвост>`) в этих двух ЗАМЕРЕНО НОЛЬ. Появится первое - предикат надо будет применить и там;
 * пока применять его к CSS значило бы объявить решение, которого никто не
 * принимал. `public/landing.css` вне периметра и так - он вне `AUDIT_ROOT`.
 */

/** Файлы, которых унификация TRIP-321 не касается (лендинг / вход / публичные).
 *  В `audit-design.mjs` они всё ещё СКАНИРУЮТСЯ на определения алиасов - остров
 *  токенов там ровно то, что делает глобальное переименование небезопасным, - но
 *  исключены из счёта семей и классов. */
export const OUT_OF_SCOPE = /(^|\/)(login\.css|PublicTrip|JoinTrip|SiteChrome|Landing|Privacy|Terms)/;

export const inScope = (f) => !OUT_OF_SCOPE.test(f);
