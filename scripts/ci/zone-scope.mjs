/**
 * СКОУП САЙТОВОЙ ДС — один дом факта, которым живут гарды зоны (TRIP-505).
 *
 * ── ЧТО ЗА ФАКТ ─────────────────────────────────────────────────────────────
 * `public/site.css` расщеплён на два слоя, и оба висят на ОДНОМ имени `.site`:
 *   · документный — `html.site`: `html`, `body`, появление `main`. Включается
 *     только там, где страницу целиком рисует сайтовая ДС;
 *   · компонентный — `:where(.site) …`: все классы и элементные правила. Он
 *     находит своего предка и на `<html>` (страница зоны), и на ОБЁРТКЕ шапки
 *     посреди экрана приложения (гостевой планировщик).
 * Скоуп написан через `:where()` НАМЕРЕННО: он не добавляет специфичности, то
 * есть каскад после расщепления в точности прежний. Это не деталь оформления —
 * первая редакция расщепления писала `.site …` и подняла специфичность всему
 * файлу: сайтовая ДС начала выигрывать у КОМПОНЕНТОВ ПРИЛОЖЕНИЯ, живущих на
 * страницах зоны (баннер согласия), и виджет потерял свою заливку. Поймано
 * попиксельным сравнением, не рассуждением.
 *
 * ── ЗАЧЕМ ЭТОТ МОДУЛЬ ───────────────────────────────────────────────────────
 * Гарды зоны читают site.css СЕЛЕКТОРАМИ: 2p (`check-css-semantics`) строит по
 * ним единицы наблюдения и каскад, 2ae (`check-site-primitive-dup`) ищет
 * «правило-одиночку» `.btn{…}`. Для обоих скоуп — шум: объявления не
 * изменились, специфичность не изменилась, изменилась ФОРМА. Не сними её — и
 * оба гарда покраснеют на 800+ «изменений», которых нет, а дальше их придётся
 * гасить сотней маркеров-обходов, то есть погасить сам гейт.
 *
 * Поэтому гарды смотрят на site.css ЧЕРЕЗ `unscope()`: файл возвращается к той
 * форме, в которой его модель и была написана. Обратное преобразование живёт в
 * ОДНОМ месте — иначе второй гард отстанет от первого молча.
 *
 * Симметрия проверяется тестом `zone-scope.test.mjs`: `unscope()` от текущего
 * `public/site.css` обязан не содержать ни одного следа скоупа.
 */

/** Префикс компонентного слоя. Тот же литерал, что в `public/site.css`. */
export const ZONE_SCOPE = ':where(.site)';

/**
 * ВЕСОМАЯ форма того же скоупа — для правил, которым специфичность НУЖНА.
 *
 * `:where()` весит ноль, и это ровно то, что требуется 1207 правилам из 1208.
 * Исключение одно: заголовки. `app.css` держит глобальное
 * `h1,h2,h3,h4{color:var(--ink);text-wrap:balance}`, и зона обязана его
 * перебить — до расщепления это делал селектор `html.site h1` (0,1,2).
 * `:is()` берёт вес самого тяжёлого аргумента, поэтому
 * `:is(html.site,.site) h1` весит столько же, сколько весил, и при этом
 * находит предка на обоих хостах. Разница с `ZONE_SCOPE` — только в весе, и
 * заводить её ради чего-то ещё нельзя: тяжёлый скоуп начнёт выигрывать у
 * компонентов приложения, живущих на страницах зоны.
 */
export const ZONE_SCOPE_WEIGHTED = ':is(html.site,.site)';

/**
 * Формы документного слоя: слева — как написано в файле, справа — как эта же
 * единица называлась ДО расщепления. Порядок важен: `:where(html.site) body`
 * обязан сняться раньше, чем общий префикс.
 */
const DOC_FORMS = [
  [':where(html.site) body', 'body'],
  [':is(html.site,.site)', 'html.site'],
  ['html:where(.site)', 'html'],
];

/**
 * Убрать скоуп зоны из текста стилей.
 *
 * Текстом, а не разбором CSS: литерал `:where(.site) ` встречается только в
 * позиции селектора — в значениях объявлений такой строки быть не может, и это
 * пинует тест. Разбор здесь стоил бы второго парсера CSS в репозитории.
 *
 * @param {string} css
 * @returns {string}
 */
export function unscope(css) {
  let out = css;
  for (const [from, to] of DOC_FORMS) out = out.split(from).join(to);
  return out.split(`${ZONE_SCOPE} `).join('');
}

/**
 * Осталось ли в тексте хоть что-то от скоупа. Нужен тесту: «сняли всё», а не
 * «сняли то, что вспомнили».
 *
 * Комментарии отброшены: разбор расщепления называет свои литералы прямо в
 * тексте (иначе объяснить его нечем), и это не след скоупа, а его описание.
 *
 * @param {string} css
 * @returns {string[]} найденные следы (пусто — чисто)
 */
export function scopeTraces(css) {
  const code = css.replace(/\/\*[\s\S]*?\*\//g, '');
  return [ZONE_SCOPE, ...DOC_FORMS.map(([from]) => from)].filter((x) => code.includes(x));
}
