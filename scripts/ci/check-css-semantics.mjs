#!/usr/bin/env node
/**
 * CI-гард 2p · ЯРУС 2 визуального гейта (TRIP-340 PR3, решение Р13).
 *
 * ЧТО ЭТО. Для каждого класса — а с TRIP-360 и для каждого правила БЕЗ класса
 * (`:root`, голый тег, шаг кейфрейма), где единицей служит сам селектор, —
 * считается НАБОР ИТОГОВЫХ ОБЪЯВЛЕНИЙ, то есть что реально достаётся элементу
 * после разрешения каскада, на BASE_REF и на HEAD. Разница печатается строкой
 * `.btn--primary padding 10px → 8px` и блокирует PR.
 *
 * ЗАЧЕМ ИМЕННО ОН. Единственный ранее существовавший способ доказать «визуально
 * ничего не поменялось» — `cmp` собранного CSS (ярус 1, приём PR #691). Он
 * доказывает МНОГО (байты те же), но умеет только «да/нет»: как только PR
 * НАМЕРЕННО что-то меняет, ярус 1 краснеет и молчит о том, ЧТО изменилось.
 * Фазы 04–09 эпика TRIP-337 состоят из намеренных правок, поэтому им нужен
 * инструмент, который не запрещает изменение, а НАЗЫВАЕТ его. Цена ошибки
 * известна поимённо: прогон по значениям свёл 111 радиусов, `.checkbox` под
 * 11px получил 17px и стал круглым — радиокнопкой на экране входа. Такой ход
 * этот гард печатает одной строкой.
 *
 * ★ ПОЧЕМУ АГРЕГАЦИЯ ПО КЛАССУ, А НЕ ПО ПРАВИЛУ. Наивный дифф «селектор →
 * объявления» краснеет на ПЕРЕНОСЕ правила из файла в файл с тем же значением —
 * а перенос это ровно то, что делают фазы 04–09 (закон 6: правило переезжает в
 * общий класс). Ложное срабатывание тут дороже пропуска: гард, который красный
 * на каждом правильном ходе, выключают. Поэтому объявления собираются со ВСЕХ
 * файлов и разрешаются каскадом — перенос между файлами невидим, изменение
 * ЗНАЧЕНИЯ видно.
 *
 * ★ ПОЧЕМУ postcss, А НЕ СВОЙ РАЗБОР. `postcss@8` уже прямая зависимость репо
 * (рунг 5 лестницы ponytail). Свой разборщик CSS — это третий парсер в проекте
 * и ровно тот класс подозреваемого, что уже дважды бил по этому эпику: «21
 * сырой радиус» вместо 2 и «163 токена двумя путями, один сломан». Здесь цена
 * тихой ошибки максимальна: гард печатал бы «изменений нет».
 *
 * ЧТО ГАРД НЕ ДЕЛАЕТ. Он НЕ предсказывает рантайм: настоящего победителя
 * каскада показывает только рендер (см. §9 эпика — `.wdg-h h4` бьёт и
 * `index.css`, и `app.css`). Он сравнивает ДВА СВОИХ ЗАМЕРА, посчитанных
 * одинаково с обеих сторон. Этого достаточно, чтобы поймать изменение, и
 * недостаточно, чтобы утверждать «на экране будет 8px».
 *
 * ★ ПЕРЕНОС РАЗМЕТКИ ≠ УДАЛЕНИЕ ПРАВИЛА (TRIP-351). Перенос ключуется на КЛАССЕ,
 * а гард читает только `.css` — разметку он не видит вообще. Поэтому
 * канонический ход фаз 04–06 (класс отдаёт раскладку, элемент уезжает на `.grow--fit`)
 * неотличим от сноса правила и печатается как `− 1`, `− 0`. Это не редкий
 * случай: ряд 250 + колонка 96 + сетка 34 ≈ 380 правил раскладки, то есть гард
 * был бы красным на КАЖДОМ правильном ходе — а выключенный гард не ловит ничего.
 * Перенос поэтому ОБЪЯВЛЯЕТСЯ:
 *
 *     /* visual-diff-move: brow__body -> grow--fit *\/
 *
 * и гард проверяет, что ушедшие с источника объявления ЕСТЬ на цели с теми же
 * значениями (в том же `@media` и состоянии). Перенос со сменой значения
 * («перенёс и заодно поменял 8px на 10px») остаётся красным, и маркер на
 * несуществующую цель — тоже красный, иначе он был бы бланкетным гашением под
 * другим именем.
 *
 * ★★ ИСТОЧНИК ПЕРЕНОСА НАЗЫВАЕТСЯ ЦЕЛИКОМ (TRIP-363). Единица наблюдения — класс,
 * поэтому объявление составного правила `.pro-up--inline .pu-body { flex: 1 }`
 * приписывается ОБОИМ его классам. Само по себе это осознанное огрубление в
 * безопасную сторону — контекстная часть селектора тоже меняет то, что элемент
 * получит, — и переписывать его нельзя: замерено, что единица «подлежащее»
 * уносит из наблюдения 1926 ключей из 10844 и 64 класса целиком (те, что живут
 * в репо только предком), а у `.a.b` подлежащего нет вовсе — оба класса на
 * одном элементе (92 селектора). Дефект был узкий: у МАРКЕРА не было формы,
 * которой источник называется целиком. `visual-diff-move: pu-body -> grow--fit`
 * закрывал ключи `.pu-body`, а `.pro-up--inline flex: − 1` продолжал
 * блокировать, и зелёным гард становился только от ВТОРОГО маркера,
 * утверждающего, что уехал и предок, — то есть от заведомо ложной строки в
 * диффе, ровно про ту разметку, которую маркер и удостоверяет. Поводов солгать
 * в фазе 05 — 133 (составные селекторы с раскладкой), и через два PR маркеры
 * перестали бы читаться как утверждения. Поэтому источником может быть ЦЕЛЫЙ
 * СЕЛЕКТОР:
 *
 *     /* visual-diff-move: .pro-up--inline .pu-body -> grow--fit *\/
 *
 * ★ Такой маркер скоупится САМИМ СЕЛЕКТОРОМ, а не набором его классов: иначе он
 * погасил бы заодно снос НЕЗАВИСИМОГО правила `.pu-body { flex: 1 }` со
 * случайно совпавшим значением — новая дыра того же класса, что и лечится
 * (найдена мутацией, не чтением). Поэтому карта помнит СЕЛЕКТОР-победитель, и
 * он же печатается в строке изменения: без него автор видит `.pro-up--inline
 * flex: − 1` и не знает, из какого правила объявление пришло, то есть не может
 * написать маркер, даже зная его форму. Печатается источник СПРАВА от значения —
 * слева от двоеточия остаётся ровно ключ, потому что это форма `-exempt`.
 * Одиночный класс источником остаётся и адресует ЕДИНИЦУ, как раньше.
 *
 * ⚠️ ГРАНИЦА СКОУПА, названная вслух: он точен настолько, насколько точен каскад.
 * Карта помнит ОДНОГО победителя на ключ, поэтому если то же свойство на той же
 * единице объявляло ещё и НЕЗАВИСИМОЕ правило и оно каскад проиграло
 * (`.wrap .pu {flex:1}` рядом с `.pu {flex:1}`), снос обоих уедет под одним
 * маркером — воспроизведено прогоном. Требовать, чтобы маркер покрыл ВСЕХ
 * вкладчиков ключа, значило бы краснеть на правильном ходе, а такой гард
 * выключают; при разных свойствах ключи разные, и чужое под маркер не попадает.
 *
 * ★ ЗНАЧЕНИЯ ТОКЕНОВ В `:root` (TRIP-360). Гард ключевался на КЛАССЕ, а у `:root`
 * класса нет — и правка `--brand-soft: rgba(…,.14) → rgba(…,.99)` (альфа в семь
 * раз) проезжала ЗЕЛЁНОЙ. Две причины, обе структурные: правило без класса
 * выпадало из наблюдения, а у правил, которые токен потребляют, сравнивается
 * ТЕКСТ объявления — `background: var(--brand-soft)` побайтово одинаков с обеих
 * сторон, что бы ни лежало в самом токене. Смену значения токена не ловил при
 * этом НИ ОДИН гард: 2o сверяет СОСТАВ имён в `:root` и значения не читает,
 * `check:design` ищет сырые литералы (в `:root` литерал легален по построению),
 * SPACING считает величины отступов. А подзадача 04 (тинт) состоит из правок
 * токенов целиком — она поехала бы без визуального гейта вовсе, ровно в фазе,
 * ради которой ярус 2 и строился.
 *
 * Поэтому правило БЕЗ класса тоже под наблюдением — ключом служит сам СЕЛЕКТОР:
 *
 *     :root[data-theme=dark] --brand-soft: rgba(111,178,255,.14) → rgba(…,.99)
 *
 * ★ ПОД НАБЛЮДЕНИЕ ИДЁТ ВСЁ БЕСКЛАССОВОЕ, А НЕ ТОЛЬКО ТОКЕНЫ. Соблазн ограничиться
 * `--*` (ход точечный, два адреса, +253 объявления) отвергнут по трём причинам,
 * и все три — про то же самое «закрыть узкое, оставив широкое»:
 *   1. голый тег — это ОБЩЕЕ в чистом виде: `button {}` и `h2 {}` бьют по всему
 *      приложению разом, шире любого токена;
 *   2. живой дефект уже на руках и он именно там — `index.css:211–219` держит
 *      ВТОРОЙ полный канон типографики на голых тегах, перебивающий `.t-*`
 *      (`<h4>` ×8 Exo 16/600 вместо Golos 13/700, `<h2>` ×16 вес 600 вместо
 *      800, мёртвое `a{color:var(--brand)}`); его снос — отдельный визуальный
 *      PR, и без включения он поехал бы вслепую ровно как тинт без токенов;
 *   3. краснота на таком PR — ЦЕЛЬ, а не издержка: это намеренная правка
 *      общего, и маркер с причиной в диффе — ровно та форма, в которой мы
 *      такое пропускаем (закон 6). Гард, молчащий на сносе канона типографики,
 *      бесполезен именно в тот момент, ради которого строился.
 * Итог на dev: 83 бесклассовых селектора, 576 объявлений ПОСЛЕ каскада — 252
 * токена и 324 прочих; сырых в файлах 623, разница съедена дубликатами, которые
 * каскад схлопывает в один ключ (`--font-display` объявлен в двух `:root`).
 * Печатать надо именно разрешённое число: сырое соблазнительнее (больше), но
 * гард сравнивает разрешённые, и отчёт обязан быть о том, что он сравнил.
 * Обе половины печатаются ОТДЕЛЬНО — по ним видно, что слепая зона была не
 * только про цвет, а ноль в любой из них означает, что ветка перестала мериться.
 *
 * ★★ КЛЮЧ КЕЙФРЕЙМА — ВМЕСТЕ С ИМЕНЕМ АНИМАЦИИ. Шаг `from` сам по себе не
 * единица: в репо 19 анимаций, и `from`/`to` повторяются в них по многу раз,
 * так что ключ по одному шагу склеил бы `fadeIn` и `dockUp` — либо ложная
 * краснота, либо, что хуже, ОДИН маркер гасит обе. Имя приходит из того же
 * поля контекста, что и `@media` (это тоже родительский at-rule), поэтому
 * ключ звучит `to {@keyframes dockUp} opacity`. Это тот же класс дефекта, что
 * `@media` в ключе escape: КЛЮЧ, НАЗВАННЫЙ НЕ ЦЕЛИКОМ, СКЛЕИВАЕТ РАЗНЫЕ ВЕЩИ
 * В ОДНУ. Второй раз за день — значит это свойство любого ключа здесь, а не
 * частный случай; пинится мутацией «правка в одной анимации, маркер на другую».
 *
 * ⚠️ ГРАНИЦА, названная вслух: `@font-face` — не rule, а at-rule с
 * объявлениями напрямую, `walkRules` его не видит, и смена `src` шрифта под
 * наблюдение НЕ попадает. Ключевать его пришлось бы тройкой
 * family+weight+style — это отдельный ключ со своей ценой ошибки, и делать его
 * наполовину здесь значило бы третий раз за день наступить на «ключ назван не
 * целиком». Островной словарь на КЛАССЕ (`login.css .auth`, 4 токена) под
 * наблюдением был всегда — он класс; он запинен тестом, потому что единица
 * наблюдения здесь переписана.
 *
 * ★★ ГРАНИЦА, КОТОРУЮ НЕ НАДО ВЫДАВАТЬ ЗА БОЛЬШЕЕ. Гард сверяет ОБЪЯВЛЕНИЯ, но
 * НЕ то, что элемент действительно получил целевой класс: разметки он не видит.
 * `visual-diff-move` доказывает «значения на цели те же», а не «на экране то же
 * самое». Это слабее полноценной проверки и сильно лучше бланкетного гашения.
 * Что элемент реально переехал — показывает ярус 1 (`cmp` собранного CSS не
 * поможет) и рендер; см. рецепт скриншота в memory/triplanio-visual-check-playwright.
 *
 * ★ `var()` ПО ЦЕПОЧКЕ НЕ РЕЗОЛВИТСЯ. Алиас `--hl-soft: var(--brand-soft)`
 * печатается как есть: его собственное значение сравнится на своей строке, а
 * значение `--brand-soft` — на своей. Вычисленный цвет гард тоже не считает —
 * он сравнивает два своих одинаково посчитанных замера, и этого достаточно,
 * чтобы НАЗВАТЬ изменение.
 *
 * Escape: `visual-diff-exempt: <класс|селектор> [{@media …}] <свойство> — <причина>` в
 * ДОБАВЛЕННЫХ строках диффа (как `floor-exempt` у 2o) — действует ровно один PR
 * и гасит ровно НАЗВАННЫЙ ключ. ★ Бланкетным (`if (exempt) exit(0)`) он был
 * ровно один PR и это был отказ в опасную сторону: один маркер на легитимный
 * перенос пропускал в том же прогоне `.grow--fit padding: + 999px` — правку
 * общего класса, задевающую каждый элемент на нём. Проверено прогоном, не
 * чтением. ★★ Маркер называет ПОЛНЫЙ ключ, включая `@media`: без него escape
 * частично возвращал бы ту самую дыру, ради которой media попал в ключ —
 * мобильное правило стоит ниже по файлу и прячет правку десктопного, и поймала
 * её мутация, а не чтение кода. Маркер без фигурных скобок адресует базовый
 * контекст и только его; мобильное изменение называется отдельной строкой.
 * Форма маркера = ровно то, что гард печатает слева от двоеточия.
 *
 * Env: BASE_REF (по умолчанию origin/dev).
 */
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import postcss from 'postcss';

const BASE_REF = process.env.BASE_REF || 'origin/dev';
const EXEMPT = 'visual-diff-exempt';
const MOVE = 'visual-diff-move';
const SYNTAX = [
  `  ${EXEMPT}: <класс|селектор> [{@media …}] <свойство> — <причина>`,
  `      база:   ${EXEMPT}: .checkbox gap — ступень шкалы`,
  `      media:  ${EXEMPT}: .checkbox {@media (max-width: 640px)} gap — то же на телефоне`,
  `      токен:  ${EXEMPT}: :root[data-theme=dark] --brand-soft — выравнивание тинта`,
  '      Ключ маркера = то, что напечатано в строке изменения слева от двоеточия.',
  `  ${MOVE}: <класс|селектор-источник> -> <класс-цель>`,
  `      класс:    ${MOVE}: brow__body -> grow--fit`,
  `      селектор: ${MOVE}: .pro-up--inline .pu-body -> grow--fit`,
  '      Источник в скобках справа от значения — это и есть селектор для маркера.',
];

const die = (msg, extra = []) => {
  console.error(`::error::check-css-semantics: ${msg}`);
  extra.forEach((l) => console.error(`  ${l}`));
  process.exit(2);
};

const unknown = process.argv.slice(2).filter((a) => a !== '--');
if (unknown.length) {
  die(`unknown flag ${unknown.join(' ')}.`, [
    'Обновлять нечего: потолок — базовая ветка. Разрешить одно изменение:',
    ...SYNTAX,
  ]);
}

const git = (args) =>
  execFileSync('git', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] });

/* --------------------------- порядок каскада ------------------------------
 * Зафиксирован в main.jsx тремя строками (TRIP-339 Р9): app.css первым, экраны,
 * index.css последним. Здесь он ПОВТОРЁН, а не выведен из графа модулей: гард
 * обязан считать одинаково на обеих сторонах, а граф на базе и на HEAD может
 * отличаться. Если пиннинг в main.jsx изменят — сравнение останется честным
 * (обе стороны меряются этим же порядком), изменится лишь то, чьё значение
 * названо победителем.                                                      */
const fileRank = (p) => (p === 'src/design/app.css' ? 0 : p === 'src/index.css' ? 999 : 500);
const orderOf = (p, i) => [fileRank(p), p, i];

/** Специфичность (a,b,c): id · класс/атрибут/псевдокласс · элемент/псевдоэлемент.
 *  Грубее спеки (`:not()` не разворачивается), но одинаково для обеих сторон. */
const specificity = (sel) => {
  const s = sel.replace(/\s*[>+~]\s*/g, ' ');
  const a = (s.match(/#[\w-]+/g) || []).length;
  const b = (s.match(/\.[\w-]+|\[[^\]]+\]|:(?!:)[\w-]+/g) || []).length;
  const c = (s.match(/(^|[\s(])[a-zA-Z][\w-]*/g) || []).length;
  return a * 10000 + b * 100 + c;
};

/** Состояние — ЧАСТЬ КЛЮЧА, а не победитель. Без этого `.btn:hover` (спец. выше)
 *  вытеснял бы базовое значение `.btn` из карты, и правка базы становилась
 *  НЕВИДИМОЙ — известная ловушка «ховер бьёт модификатор». */
const stateOf = (sel) => (sel.match(/:{1,2}[\w-]+(\([^)]*\))?/g) || []).sort().join('');

const classesOf = (sel) => [...new Set((sel.match(/\.(-?[a-zA-Z_][\w-]*)/g) || []).map((c) => c.slice(1)))];

/** Селектор как ЕДИНИЦА наблюдения — для правил без класса (`:root`) — и как
 *  ИСТОЧНИК ПЕРЕНОСА (TRIP-363). Кавычки внутри `[data-theme="dark"]` снимаются,
 *  а пробелы вокруг комбинатора приводятся к одному виду, чтобы маркер и печать
 *  гарда сошлись в одной орфографии: обе стороны нормализуются одинаково,
 *  поэтому сравнение остаётся честным, а автор не ловит «под маркером изменений
 *  нет» из-за кавычки или пробела возле `>`. */
const normSel = (sel) =>
  sel
    .replace(/\s+/g, ' ')
    .replace(/["']/g, '')
    .replace(/\s*([>+~])\s*/g, ' $1 ')
    .trim();

/** Единица наблюдения = `.класс` (с точкой) либо целый селектор. Точка в имени
 *  делает две ветки различимыми БЕЗ отдельного флага в ключе: `.checkbox` и
 *  `:root` не могут столкнуться, а маркер адресует ровно то, что напечатано. */
const unitsOf = (sel) => {
  const cls = classesOf(sel);
  return cls.length ? { units: cls.map((c) => `.${c}`), state: stateOf(sel) } : { units: [normSel(sel)], state: '' };
};

/** media-контекст = все родительские at-rule'ы. Правило внутри `@media` — другой
 *  контекст: иначе мобильное значение схлопнулось бы с десктопным. */
const mediaOf = (node) => {
  const out = [];
  for (let p = node.parent; p; p = p.parent) if (p.type === 'atrule') out.push(`@${p.name} ${p.params}`);
  return out.reverse().join(' ');
};

/* ★ РАЗДЕЛИТЕЛЬ КЛЮЧА — NUL, а не `|`. Пока единицей был класс, `|` был
 * безопасен: в имени класса его быть не может. С TRIP-360 единицей стал
 * ПРОИЗВОЛЬНЫЙ селектор, а `|` в CSS — легальный оператор (`[lang|="en"]`,
 * namespace `svg|a`), и такой ключ порезался бы не по тем границам: изменение
 * напечаталось бы мусором и не гасилось бы НИКАКИМ маркером. Отказ был бы в
 * безопасную сторону (красный, не тишина), но объявить такое изменение автор не
 * смог бы вовсе. NUL в селектор и в имя свойства не попадает по построению —
 * это третий за день случай «ключ, названный не целиком», и лечится он здесь
 * структурно, а не строкой в шапке про то, чего мы не умеем. */
const SEP = '\u0000';

/** Карта: (единица, media, состояние, свойство) → победившее значение.
 *  Единица — `.класс` (с точкой) либо целый селектор, если класса в нём нет
 *  (`:root`, `h2`, шаг кейфрейма). У бесклассового правила под наблюдением ВСЕ
 *  его объявления, а не только токены `--*` — обоснование этой границы в шапке
 *  файла («под наблюдение идёт всё бесклассовое, а не только токены»). */
function semantics(files) {
  const best = new Map();
  const failures = [];
  for (const { path, css } of files) {
    let root;
    try {
      root = postcss.parse(css, { from: path });
    } catch (e) {
      // Непрочитанный файл выглядит как файл без стилей, то есть «изменений
      // нет» — самый дорогой из возможных неверных ответов для этого гарда.
      failures.push(`${path}: ${e.message}`);
      continue;
    }
    let i = 0;
    root.walkRules((rule) => {
      i += 1;
      const media = mediaOf(rule);
      for (const sel of rule.selectors || []) {
        const spec = specificity(sel);
        const { units, state } = unitsOf(sel);
        rule.walkDecls((decl) => {
          const weight = [decl.important ? 1 : 0, spec, ...orderOf(path, i)];
          for (const c of units) {
            const key = [c, media, state, decl.prop].join(SEP);
            const prev = best.get(key);
            if (!prev || cmpWeight(weight, prev.weight) >= 0) {
              // Селектор-победитель хранится не ради ключа (ключ — единица), а
              // ради ИСТОЧНИКА: им печатается строка изменения и им же скоупится
              // перенос из составного правила (TRIP-363).
              best.set(key, { weight, value: decl.value.replace(/\s+/g, ' ').trim(), sel: normSel(sel) });
            }
          }
        });
      }
    });
  }
  return { best, failures };
}

const cmpWeight = (a, b) => {
  for (let i = 0; i < Math.max(a.length, b.length); i += 1) {
    const x = a[i] ?? 0;
    const y = b[i] ?? 0;
    if (x === y) continue;
    return x > y ? 1 : -1;
  }
  return 0;
};

/* ------------------------------ два замера -------------------------------- */

const listCss = (ref) => {
  const out = ref
    ? git(['ls-tree', '-r', '--name-only', ref, '--', 'src']).split('\n')
    : git(['ls-files', '--', 'src']).split('\n');
  return out.filter((p) => p.endsWith('.css'));
};

let baseFiles;
try {
  baseFiles = listCss(BASE_REF).map((p) => ({ path: p, css: git(['show', `${BASE_REF}:${p}`]) }));
} catch (e) {
  // Недостижимая база — КРАСНЫЙ, не пропуск: «нечего проверять» и «проверено,
  // чисто» не должны печатать одинаковый вердикт (правило 2o).
  die(`не могу прочитать ${BASE_REF}: ${e.message}`, ['git fetch origin dev']);
}
/* ★ РАБОЧЕЕ ДЕРЕВО, А НЕ ИНДЕКС. Первая редакция читала HEAD через
 * `git show :<path>` — то есть staging area. В CI разницы нет (там всё
 * закоммичено), поэтому гард выглядел бы исправным; локально он
 * печатал «изменений нет» на ЛЮБОЙ незастейдженной правке. Поймано
 * мутацией (.checkbox gap 9px→17px прошёл насквозь), не чтением кода. */
const headFiles = listCss(null).map((p) => ({ path: p, css: readFileSync(p, 'utf8') }));

const base = semantics(baseFiles);
const head = semantics(headFiles);
const failures = [...base.failures, ...head.failures];
if (failures.length) die(`postcss не разобрал ${failures.length} файл(ов) — замер занижен`, failures);

/* ------------------------------- сравнение -------------------------------- */

/** Ключ карты обратно на четыре поля — тем же порядком, которым он собран. */
const partsOf = (key) => {
  const [unit, media, state, prop] = key.split(SEP);
  return { unit, media, state, prop };
};

/** Изменение = ключ и обе стороны замера; отсутствующая сторона — null, на неё
 *  завязаны и печать (`+ появилось` / `− ушло`), и весь разбор переноса.
 *  `fromSel`/`toSel` — селекторы, объявления которых победили на базе и на HEAD.
 *  Ключ ими НЕ строится (иначе гард краснел бы на косметической перезаписи
 *  селектора); они нужны, чтобы назвать источник в выводе и в маркере переноса. */
const mkChange = (key, was, now) => ({
  key,
  ...partsOf(key),
  from: was?.value ?? null,
  to: now?.value ?? null,
  fromSel: was?.sel ?? null,
  toSel: now?.sel ?? null,
});

const changes = [];
for (const [key, now] of head.best) {
  const was = base.best.get(key);
  if (!was || was.value !== now.value) changes.push(mkChange(key, was, now));
}
for (const [key, was] of base.best) if (!head.best.has(key)) changes.push(mkChange(key, was, null));

/* ------------------------- маркеры: точечные, не бланкетные ----------------
 * Читаются из ДОБАВЛЕННЫХ строк диффа (действуют один PR) — из коммитов ветки
 * И из рабочего дерева, чтобы маркер вёл себя локально так же, как в CI: замер
 * CSS берётся из рабочего дерева, и разъезд источников уже один раз стоил
 * гарду тихого «изменений нет».                                              */
const addedLines = [
  git(['diff', '--unified=0', `${BASE_REF}...HEAD`, '--', 'src']),
  git(['diff', '--unified=0', 'HEAD', '--', 'src']),
]
  .join('\n')
  .split('\n')
  .filter((l) => l.startsWith('+'));

/* ★ Маркер называет ПОЛНЫЙ ключ, включая `@media`. Соблазн опустить его велик
 * (маркер короче), но это частично возвращает дыру, ради которой media вообще
 * попал в ключ: мобильное правило стоит ниже по файлу и прячет правку
 * десктопного. Маркер БЕЗ фигурных скобок адресует базовый контекст и только
 * его — отказ в безопасную сторону, — а мобильное изменение приходится назвать
 * отдельной строкой. Форма маркера = ровно то, что гард печатает слева от
 * двоеточия: `.btn:hover {@media (max-width: 640px)} gap`. */
/* ★ Единица маркера — ЛЮБАЯ непробельная лексема (`\S+`), а не «класс с
 * состояниями»: селектор `:root[data-theme=dark]` под прежний шаблон не
 * подходил. Свобода тут безопасна, потому что имя нормализуется в ту же
 * орфографию, что и ключ, а неразобранный маркер — код 2, не тишина. */
const reExempt = new RegExp(String.raw`${EXEMPT}:\s*(\S+)\s+(?:\{([^}]*)\}\s+)?([-\w]+)`);
/* Перенос — про КЛАССЫ (разметка переезжает с класса на класс), поэтому источник
 * обязан содержать хотя бы один класс: `visual-diff-move: :root -> …` не
 * разберётся и упадёт кодом 2, а не притворится работающим маркером. Голый тег
 * источником тоже не выражается — `h4` прочитается как класс `.h4`, такого
 * класса нет, перенос объяснит НОЛЬ объявлений, и правки `h4` останутся
 * блокирующими: отказ в безопасную сторону. Снос второго канона типографики
 * (Р9) — это и не перенос, а удаление, и объявляется точечным
 * `visual-diff-exempt: h2 font-weight — …`.
 * ★ Источник читается ЖАДНО, до ПОСЛЕДНЕГО `->`: в селекторе легален детский
 * комбинатор (`.a > .b`), поэтому якорем служит цель — она заведомо одно слово. */
const CLS = String.raw`\.?[-\w]+`;
const reMove = new RegExp(String.raw`${MOVE}:\s*(.+)\s*->\s*(${CLS})`);
const reSingleClass = new RegExp(String.raw`^${CLS}$`);
/** Имя класса из маркера ПЕРЕНОСА: `grow--fit` и `.grow--fit` → `grow--fit`
 *  (точка там необязательна — единица переноса заведомо класс). */
const bare = (sel) => classesOf(sel.startsWith('.') ? sel : `.${sel}`)[0];
/** Как маркер адресует источник — ровно одно из двух, и это же различает скоуп
 *  ниже: `unit` (источник из одного класса, форма TRIP-351) закрывает всё, что
 *  ушло с ЕДИНИЦЫ; `sel` (целый селектор) — только то, что объявлял он сам.
 *  Источник без единого класса — не источник переноса вовсе: null → код 2. */
const moveSource = (src) => {
  if (reSingleClass.test(src)) return { unit: `.${bare(src)}` };
  return classesOf(src).length ? { sel: normSel(src) } : null;
};
/** Единица маркера → та же пара (единица, состояние), которой ключуется карта.
 *  Разбирается ТОЙ ЖЕ `unitsOf`, что строит ключ из селектора: пока это одна
 *  функция, орфография маркера и ключа не может разъехаться, а разъезд здесь —
 *  это молча не сработавший escape. Единица у маркера ровно одна, поэтому из
 *  разбора берётся первая.
 *  ★ ТОЧКА ОБЯЗАТЕЛЬНА для класса: прежняя вольность (`checkbox` = `.checkbox`)
 *  стала неоднозначной, как только под наблюдение попали голые теги — `button`
 *  теперь законная единица, и «догадаться» за автора значило бы гасить не то.
 *  Правило одно и проверяемое глазом: ключ маркера = то, что гард НАПЕЧАТАЛ.
 *  У бесклассовой единицы состояние уже внутри имени (`a:hover`, `:root[…]`),
 *  отдельным полем оно не выносится. */
const unitOf = (u) => {
  const { units, state } = unitsOf(u);
  return { unit: units[0], state };
};
/** Пробелы внутри `@media (max-width:640px)` — не смысл: сверяем нормализованно.
 *  Гасятся только пробелы ВОКРУГ пунктуации; между словами (`screen and (…)`)
 *  они остаются границей идентификатора, поэтому два РАЗНЫХ запроса совпасть не
 *  могут. Маркер, отвергнутый из-за пропавшего пробела после двоеточия, — это
 *  маркер, который удаляют в раздражении, а с ним и проверку. */
const normMedia = (s) =>
  (s || '')
    .replace(/\s+/g, ' ')
    .replace(/\s*([:,()])\s*/g, '$1')
    .trim();

const exempts = [];
const moves = [];
const malformed = [];
for (const line of addedLines) {
  if (line.includes(`${EXEMPT}:`)) {
    const m = line.match(reExempt);
    if (m) exempts.push({ ...unitOf(m[1]), media: normMedia(m[2]), prop: m[3], used: false });
    else malformed.push(line.trim());
  }
  if (line.includes(`${MOVE}:`)) {
    const m = line.match(reMove);
    const src = m && moveSource(m[1].trim());
    if (src) moves.push({ ...src, to: `.${bare(m[2])}` });
    else malformed.push(line.trim());
  }
}
// Маркер, который автор считает работающим, а гард не разобрал, — самая дорогая
// из тишин: PR уезжает красным по причине, которой в выводе нет.
if (malformed.length) die('маркер(ы) не разобраны — синтаксис ниже', [...malformed, '', ...SYNTAX]);

/* --------- что из изменений ОБЪЯВЛЕНО: сначала переносы, потом точечные ----- */

/** Ключ так, как его печатает гард, — он же ФОРМА МАРКЕРА (всё, что слева от
 *  двоеточия): единица, состояние, `@media`, свойство. */
const fmtId = (c) => `${c.unit}${c.state}${c.media ? ` {${c.media}}` : ''} ${c.prop}`;
/** `+ значение` — объявление появилось, `− значение` — исчезло, `было → стало` —
 *  сменилось. */
const fmtValue = (c) => {
  if (c.from === null) return `+ ${c.to}`;
  if (c.to === null) return `− ${c.from}`;
  return `${c.from} → ${c.to}`;
};
/** Правило, в котором объявление живёт сейчас (а для исчезнувшего — жило на базе),
 *  печатается СПРАВА от значения: слева от двоеточия обязан остаться ровно ключ
 *  (форма `visual-diff-exempt`). Для составного правила это единственный способ
 *  узнать, что писать в `visual-diff-move` (TRIP-363), а вот когда селектор — это
 *  ровно уже напечатанные единица и состояние (`.checkbox`, `.btn:hover`, `:root`),
 *  подсказка была бы ДОСЛОВНЫМ ПОВТОРОМ ключа, то есть шумом на 2595 строках. */
const fmt = (c) => {
  const sel = c.to !== null ? c.toSel : c.fromSel;
  const rule = sel && sel !== `${c.unit}${c.state}` ? `   (правило ${sel})` : '';
  return `  ${fmtId(c)}: ${fmtValue(c)}${rule}`;
};

const headUnits = new Set([...head.best.keys()].map((k) => partsOf(k).unit));
const byKey = new Map(changes.map((c) => [c.key, c]));
const declared = new Set();
const notes = [];
const rejected = [];

for (const mv of moves) {
  // Как источник назван в маркере — единицей или целым селектором; ровно одно
  // из двух заполнено, оно же различает скоуп ниже.
  const src = mv.sel || mv.unit;
  if (!headUnits.has(mv.to)) {
    rejected.push(`${MOVE}: ${src} → ${mv.to} — у цели на HEAD нет ни одного объявления`);
    continue;
  }
  let moved = 0;
  for (const c of changes) {
    // Переносом объясняются только объявления, УШЕДШИЕ с источника (`to === null`);
    // всё остальное на нём — обычное изменение и разбирается точечным маркером.
    if (c.to !== null) continue;
    // Одиночный класс закрывает всё, что ушло С ЭТОЙ ЕДИНИЦЫ; целый селектор —
    // ровно то, что объявлял ОН САМ. Скоуп по НАБОРУ его классов погасил бы
    // заодно снос независимого правила на том же классе (см. шапку, TRIP-363).
    if (mv.sel ? c.fromSel !== mv.sel : c.unit !== mv.unit) continue;
    const dstKey = [mv.to, c.media, c.state, c.prop].join(SEP);
    const dst = head.best.get(dstKey);
    if (!dst) rejected.push(`${fmtId(c)}: ${c.from} — на ${mv.to} этого объявления нет`);
    else if (dst.value !== c.from) rejected.push(`${fmtId(c)}: ${c.from} → ${dst.value} — перенос на ${mv.to} СО СМЕНОЙ значения`);
    else {
      declared.add(c.key);
      moved += 1;
      // Цель, ТОЛЬКО ПРИОБРЁТШУЮ объявление, покрывает тот же перенос. Если у
      // цели значение было другим — это правка живого класса, её не гасим.
      if (byKey.get(dstKey)?.from === null) declared.add(dstKey);
    }
  }
  notes.push(`перенос ${src} → ${mv.to}: объявлений ${moved}`);
}

for (const c of changes) {
  if (declared.has(c.key)) continue;
  const ex = exempts.find(
    (e) => e.unit === c.unit && e.media === normMedia(c.media) && e.state === c.state && e.prop === c.prop,
  );
  if (!ex) continue;
  ex.used = true;
  declared.add(c.key);
}
for (const e of exempts) {
  const id = `${EXEMPT}: ${e.unit}${e.state}${e.media ? ` {${e.media}}` : ''} ${e.prop}`;
  notes.push(e.used ? `${id} — изменение объявлено намеренным` : `${id} — под маркером изменений нет`);
}

const blocking = changes.filter((c) => !declared.has(c.key));

/* Бесклассовый ярус печатается ОТДЕЛЬНО и с разбивкой «токены · прочее»: по
 * ней видно, что слепая зона была не только про цвет, а ноль в любой из
 * половин — внятный сигнал, что ветка перестала измеряться. Суммарное число
 * такую пропажу растворило бы в тысяче классов. */
const nClasses = [...headUnits].filter((u) => u.startsWith('.')).length;
const looseKeys = [...head.best.keys()].filter((k) => !k.startsWith('.'));
const nTokens = looseKeys.filter((k) => partsOf(k).prop.startsWith('--')).length;
console.log(`check-css-semantics (2p): HEAD vs ${BASE_REF}`);
console.log(`  классов под наблюдением: ${nClasses}`);
console.log(
  `  бесклассовых селекторов: ${headUnits.size - nClasses}` +
    ` (объявлений ${looseKeys.length}: токенов ${nTokens} · прочих ${looseKeys.length - nTokens})`,
);
console.log(`  объявлений сравнено:     ${head.best.size}`);
if (changes.length) console.log(`  изменений: ${changes.length} · объявлено: ${declared.size} · блокирует: ${blocking.length}`);
notes.forEach((n) => console.log(`  ${n}`));

/* Список блокирующих печатается ДО проверки переносов, а выход по ним — ПОСЛЕ:
 * если разом сломаны и маркер переноса, и что-то ещё, автор видит обе половины,
 * а не только ту, что уронила прогон первой. */
if (blocking.length) {
  console.log('');
  blocking.slice(0, 60).sort((a, b) => a.key.localeCompare(b.key)).forEach((c) => console.log(fmt(c)));
  if (blocking.length > 60) console.log(`  … и ещё ${blocking.length - 60}`);
}
if (rejected.length) {
  console.log('');
  rejected.forEach((r) => console.log(`  ${r}`));
  console.error(
    `::error::check-css-semantics: объявленный ${MOVE} не сошёлся, случаев: ${rejected.length}. ` +
      'На цели либо нет этого объявления, либо значение при переносе изменилось.',
  );
  process.exit(1);
}
if (blocking.length) {
  console.error(
    `::error::check-css-semantics: итоговые объявления изменились у ${blocking.length} ключ(ей). ` +
      `Если это намеренно — объяви каждое изменение отдельной строкой в диффе:\n` +
      SYNTAX.join('\n'),
  );
  process.exit(1);
}
console.log(
  changes.length
    ? `  необъявленных изменений нет: все ${changes.length} объявлены переносом или исключением.`
    : '  итоговые объявления не изменились ни у одного класса и ни у одного токена.',
);
process.exit(0);
