/** Ключ карты обратно на четыре поля — тем же порядком, которым он собран. */
const partsOf = (key) => {
  const [unit, media, state, prop] = key.split(SEP);
  return { unit, media, state, prop };
};

/** Изменение = ключ и обе стороны замера; отсутствующая сторона — null, на неё
 *  завязаны и печать (`+ появилось` / `− ушло`), и весь разбор переноса.
 *  `fromSel`/`toSel` — селекторы, объявления которых победили на базе и на HEAD.
 *  Ключ ими НЕ строится (иначе гард краснел бы на косметической перезаписи
 *  селектора); они нужны, чтобы назвать источник в выводе и в маркере переноса. */
const mkChange = (key, was, now) => ({
  key,
  ...partsOf(key),
  from: was?.value ?? null,
  to: now?.value ?? null,
  fromSel: was?.sel ?? null,
  toSel: now?.sel ?? null,
});

const changes = [];
for (const [key, now] of head.best) {
  const was = base.best.get(key);
  if (!was || was.value !== now.value) changes.push(mkChange(key, was, now));
}
for (const [key, was] of base.best) if (!head.best.has(key)) changes.push(mkChange(key, was, null));

/* ------------------- значения переноса: `var()` разворачивается ------------
 * ★ ТОЛЬКО ВНУТРИ СВЕРКИ ПЕРЕНОСА, и это главное ограничение. Значения гард
 * сравнивает ТЕКСТОМ (см. шапку) — и это правильно для основного сравнения:
 * разверни `var()` глобально, и правка ОДНОГО токена зажгла бы сотню его
 * потребителей, у которых в тексте не изменилось ничего. Но у переноса текст
 * значения — не то, что проверяется: канонический ход фаз 04–09 переносит сырой
 * `16px` на `var(--sp-7)`, то есть ровно то, ради чего шкала и заведена, а
 * текстовое сравнение читает это как «перенос СО СМЕНОЙ значения». Цена
 * известна поимённо: в зоне 1 пришлось объявить 117 НЕПРОВЕРЯЕМЫХ исключений
 * вместо проверяемых переносов, то есть ярус 2 не проверил ядро того PR.
 *
 * ★★ КАЖДАЯ СТОРОНА РАЗВОРАЧИВАЕТСЯ ПО СВОЕМУ `:root`: источник (база) — по
 * базовому, цель (HEAD) — по HEAD'овому. Правку самого токена это НЕ маскирует:
 * с TRIP-360 у токена свой ключ, и его изменение печатается и блокирует
 * отдельной строкой; а если токен изменился, перенос на него станет красным
 * ещё и здесь — отказ в безопасную сторону.
 *
 * ГРАНИЦЫ, названные вслух:
 *   · берётся словарь ровно `:root` в БАЗОВОМ контексте — без `@media` и без
 *     `:root[data-theme=dark]`: тема это ВТОРОЙ словарь, и сверять перенос по
 *     двум сразу значило бы выбирать, какой из них «настоящий»;
 *   · цепочка разворачивается до 6 проходов и до неподвижной точки; цикл или
 *     неизвестное имя оставляют `var()` в тексте — тогда сравнение остаётся
 *     текстовым, то есть строгим;
 *   · `var(--x, 8px)`: известное имя побеждает фолбэк (как в CSS), неизвестное
 *     отдаёт фолбэк; вложенность в фолбэке разбирается на один уровень;
 *   · вычисленного значения гард по-прежнему не считает: `calc()` не считается,
 *     `16px` и `1rem` — разные значения;
 *   · подстановка не разбирает КАВЫЧКИ: `content: "var(--q)"` в CSS остаётся
 *     литералом, а тут развернётся. Ложное совпадение возможно только внутри
 *     сверки переноса и только у строкового значения — граница названа, чтобы
 *     не считаться проверенной.                                              */
const rootTokensOf = (sem) => {
  const map = new Map();
  for (const [key, v] of sem.best) {
    const { unit, media, state, prop } = partsOf(key);
    if (unit === ':root' && !media && !state && prop.startsWith('--')) map.set(prop, v.value);
  }
  return map;
};
const baseTokens = rootTokensOf(base);
const headTokens = rootTokensOf(head);

/* ── ручки плитки: резолв ВЫЧИСЛЕННОГО в сверке переноса (TRIP-391 объект 3) ────
 * Канон плитки переводит скин с прямых значений на ступень/канал: `.statbar .ic
 * { width:42px; background:var(--brand-soft) }` → элемент уезжает на примитив
 * `<Tile>` (`.tile { width:var(--tile,34px); background:var(--hl-soft) }`), а
 * контекст задаёт РУЧКУ: `.statbar .tile { --tile:42px }`. Текст объявления при
 * этом меняется (`42px` → `var(--tile,34px)`, `background`↔`--hl-soft`), а
 * ВЫЧИСЛЕННОЕ — нет. `resolveVars` знает только `:root`, ручку же ставит КОНТЕКСТ,
 * поэтому перенос читался «СО СМЕНОЙ значения» и канон-миграция была НЕВОЗМОЖНА.
 *
 * ★ Ручка резолвится с ТОЧНОГО правила `<контекст> .tile` (ключ = нормализованный
 * селектор + media), НЕ по классу: `.statbar .s.c-city .tile` и `.sfig.c-city
 * .tile` пишут `--hl-soft` под общий класс `.c-city` и по классу склеились бы.
 * ★★ Безопасность держит САМ перенос, а не пропуск: значение сверяется
 * ВЫЧИСЛЕННЫМ на обеих сторонах, поэтому правка ручки (`--tile` 42→40, иной тон
 * `--hl-soft`) даёт ДРУГОЙ результат → перенос отвергается красным (условие Г37:
 * умнее, не слепее). Ручка-ДЕКЛАРАЦИЯ на цели (`--tile:42px`) снимается с
 * блокировки ТОЛЬКО когда её употребил состоявшийся перенос — стой она сама по
 * себе, осталась бы блокирующей (иначе `--tile:99px` втихую менял бы размер). */
const TILE_HANDLES = new Set(['--tile', '--tile-r', '--tile-ic', '--hl-soft', '--hl-ink']);
// ★ Длинные имена ПЕРВЫМИ: альтернация жадна по порядку, и `--tile` матчил бы
// префикс `--tile-r`/`--tile-ic`, оставляя их декларацию неучтённой (найдено
// мутацией: --tile-r блокировал зелёный перенос).
const HANDLE_RE = /var\(\s*(--tile-r|--tile-ic|--tile|--hl-soft|--hl-ink)\b/g;
const handlesBySel = (files) => {
  const map = new Map();
  for (const { path, css } of files) {
    let root;
    try { root = postcss.parse(css, { from: path }); } catch { continue; }
    root.walkRules((rule) => {
      const media = mediaOf(rule);
      for (const sel of rule.selectors || []) {
        rule.walkDecls((d) => {
          if (!TILE_HANDLES.has(d.prop)) return;
          const k = normSel(sel) + SEP + media;
          if (!map.has(k)) map.set(k, new Map());
          map.get(k).set(d.prop, d.value.replace(/\s+/g, ' ').trim());
        });
      }
    });
  }
  return map;
};
const headHandles = handlesBySel(headFiles);
/** Целевой контекст переноса плитки = исходный селектор с подлежащим на `.tile`
 *  (элемент тот же контекст, но уехал на примитив). `.statbar .s.c-city .ic` →
 *  `.statbar .s.c-city .tile`. Комбинаторы у плитки — только потомок (пробел). */
const tileTargetSel = (sel) => {
  const c = compoundsOf(sel);
  if (!c.length) return null;
  c[c.length - 1] = '.tile';
  return c.join(' ');
};

const reVar = /var\(\s*(--[\w-]+)\s*(?:,([^()]*(?:\([^()]*\)[^()]*)*))?\)/g;
const resolveVars = (value, tokens) => {
  let out = value;
  for (let i = 0; i < 6 && out.includes('var('); i += 1) {
    const next = out.replace(reVar, (all, name, fallback) => {
      const known = tokens.get(name);
      if (known !== undefined) return known;
      return fallback === undefined ? all : fallback.trim();
    });
    if (next === out) break;
    out = next;
  }
  return out.replace(/\s+/g, ' ').trim();
};
/** Значение на цели совпало с ушедшим с источника — дословно ЛИБО после
 *  разворачивания токенов. Порядок важен только для скорости: дословное
 *  совпадение и так победит. */
const sameMovedValue = (from, to) =>
  from === to || resolveVars(from, baseTokens) === resolveVars(to, headTokens);

/* ------------------------- маркеры: точечные, не бланкетные ----------------
 * Читаются из ДОБАВЛЕННЫХ строк диффа (действуют один PR) — из коммитов ветки
 * И из рабочего дерева, чтобы маркер вёл себя локально так же, как в CI: замер
 * CSS берётся из рабочего дерева, и разъезд источников уже один раз стоил
 * гарду тихого «изменений нет».                                              */
const addedLines = [
  git(['diff', '--unified=0', `${BASE_REF}...HEAD`, '--', 'src']),
  git(['diff', '--unified=0', 'HEAD', '--', 'src']),
]
  .join('\n')
  .split('\n')
  .filter((l) => l.startsWith('+'));

/* ★ Маркер называет ПОЛНЫЙ ключ, включая `@media`. Соблазн опустить его велик
 * (маркер короче), но это частично возвращает дыру, ради которой media вообще
 * попал в ключ: мобильное правило стоит ниже по файлу и прячет правку
 * десктопного. Маркер БЕЗ фигурных скобок адресует базовый контекст и только
 * его — отказ в безопасную сторону, — а мобильное изменение приходится назвать
 * отдельной строкой. Форма маркера = ровно то, что гард печатает слева от
 * двоеточия: `.btn:hover {@media (max-width: 640px)} gap`. */
/* ★ Единица маркера — ЛЮБАЯ непробельная лексема (`\S+`), а не «класс с
 * состояниями»: селектор `:root[data-theme=dark]` под прежний шаблон не
 * подходил. Свобода тут безопасна, потому что имя нормализуется в ту же
 * орфографию, что и ключ, а неразобранный маркер — код 2, не тишина.
 *
 * ★★ КЛЮЧ РАЗБИРАЕТСЯ СПРАВА НАЛЕВО (TRIP-366). Прежний шаблон читал единицу
 * слева как ОДНУ лексему, поэтому бесклассовую единицу из нескольких лексем
 * объявить было нельзя ничем: гард печатает `h1 em color: …`, а маркер с этой
 * же строкой разбирался как единица `h1` и свойство `em` — то есть контракт
 * «ключ маркера = то, что гард напечатал» переставал выполняться ровно там, где
 * он и нужен. Слева направо эта строка неразрешима в принципе: границу «где
 * кончилась единица и началось свойство» из неё не вывести. Справа налево она
 * однозначна — СВОЙСТВО ЭТО ПОСЛЕДНЯЯ ЛЕКСЕМА КЛЮЧА, перед ним необязательный
 * `{@media …}`, остальное — единица.
 *
 * Чтобы «последняя лексема» была определена, ключ обязан чем-то кончаться —
 * поэтому ПРИЧИНА СТАЛА ОБЯЗАТЕЛЬНОЙ. Это не новый синтаксис: `— <причина>`
 * записана в SYNTAX с первого дня, её носят все 271 живых маркера в `src` и все
 * остальные escape-маркеры репо (`floor-exempt`, `prefix-exempt`,
 * `orphan-exempt`). Маркер без причины теперь код 2 с подсказкой, а не тихо
 * разобранный не туда. Разделителем принимается и ASCII-дефис в пробелах
 * (« - ») — в имени свойства и в селекторе такой последовательности нет, а
 * правило репо по контенту просит именно дефис.
 * ⚠️ Цена ASCII-дефиса, названная вслух: ключ режется по ПЕРВОМУ разделителю,
 * поэтому единица, СОДЕРЖАЩАЯ ` - ` (например `[data-x=a - b]`), станет
 * необъявляемой — гард напечатает её ключ, а маркер разберётся не туда. В `src`
 * таких селекторов ноль (проверено прогоном), отказ громкий («под маркером
 * изменений нет» + изменение продолжает блокировать), и лечится он выбором
 * длинного тире. Если такой селектор появится — разделителем оставить только «—». */
const reExemptKey = /\s(?:[—–]|-)\s/;
const reExemptTail = /^(.*?)\s*(?:\{([^}]*)\}\s*)?([-\w]+)$/;
/** Текст маркера до причины — он же ключ. `null` = причины нет, разбирать нечего. */
const exemptKeyPart = (line) => {
  const at = line.indexOf(`${EXEMPT}:`);
  const raw = line.slice(at + EXEMPT.length + 1);
  const m = raw.match(reExemptKey);
  return m ? raw.slice(0, m.index).trim() : null;
};
/* Перенос — про КЛАССЫ (разметка переезжает с класса на класс), поэтому источник
 * обязан содержать хотя бы один класс: `visual-diff-move: :root -> …` не
 * разберётся и упадёт кодом 2, а не притворится работающим маркером. Голый тег
 * источником тоже не выражается — `h4` прочитается как класс `.h4`, такого
 * класса нет, перенос объяснит НОЛЬ объявлений, и правки `h4` останутся
 * блокирующими: отказ в безопасную сторону. Снос второго канона типографики
 * (Р9) — это и не перенос, а удаление, и объявляется точечным
 * `visual-diff-exempt: h2 font-weight — …`.
 * ★ Источник читается ЖАДНО, до ПОСЛЕДНЕГО `->`: в селекторе легален детский
 * комбинатор (`.a > .b`), поэтому якорем служит цель.
 * ★★ ЦЕЛЕЙ МОЖЕТ БЫТЬ НЕСКОЛЬКО. Раскладка уезжает не на класс, а на КОМПОЗИЦИЮ
 * (`.row` + `.row--g7` + `.row--wrap`), и одной целью её не назвать. Второй
 * маркер эту дыру не закрывает, а УХУДШАЕТ: каждый маркер требует ВСЕ ушедшие
 * объявления на СВОЕЙ цели, поэтому «объявить обе» делает проверку строже, а не
 * полнее — замерено на зоне 1, 44 несошедшихся переноса становились 91. Список
 * целей после `->` разделяется пробелами и кончается на первой лексеме, которая
 * не может быть ИДЕНТИФИКАТОРОМ: на закрывающей скобке комментария, на скобке,
 * на кириллице. Английское слово идентификатором быть может, поэтому проза
 * после списка целей уедет в цели — и гард скажет об этом поимённо («у цели
 * .see на HEAD нет ни одного объявления»), а не проглотит молча. */
const CLS = String.raw`\.?[-\w]+`;
const reMove = new RegExp(String.raw`${MOVE}:\s*(.+)\s*->\s*((?:${CLS}\s*)+)`);
const reSingleClass = new RegExp(String.raw`^${CLS}$`);
/** Имя класса из маркера ПЕРЕНОСА: `grow--fit` и `.grow--fit` → `grow--fit`
 *  (точка там необязательна — единица переноса заведомо класс). */
const bare = (sel) => classesOf(sel.startsWith('.') ? sel : `.${sel}`)[0];
/** Как маркер адресует источник — ровно одно из двух, и это же различает скоуп
 *  ниже: `unit` (источник из одного класса, форма TRIP-351) закрывает всё, что
 *  ушло с ЕДИНИЦЫ; `sel` (целый селектор) — только то, что объявлял он сам.
 *  Источник без единого класса — не источник переноса вовсе: null → код 2. */
const moveSource = (src) => {
  if (reSingleClass.test(src)) return { unit: `.${bare(src)}` };
  return classesOf(src).length ? { sel: normSel(src) } : null;
};
/** Единица маркера → та же пара (единица, состояние), которой ключуется карта.
 *  Разбирается ТОЙ ЖЕ `unitsOf`, что строит ключ из селектора: пока это одна
 *  функция, орфография маркера и ключа не может разъехаться, а разъезд здесь —
 *  это молча не сработавший escape. Единица у маркера ровно одна, поэтому из
 *  разбора берётся первая.
 *  ★ ТОЧКА ОБЯЗАТЕЛЬНА для класса: прежняя вольность (`checkbox` = `.checkbox`)
 *  стала неоднозначной, как только под наблюдение попали голые теги — `button`
 *  теперь законная единица, и «догадаться» за автора значило бы гасить не то.
 *  Правило одно и проверяемое глазом: ключ маркера = то, что гард НАПЕЧАТАЛ.
 *  У бесклассовой единицы состояние уже внутри имени (`a:hover`, `:root[…]`),
 *  отдельным полем оно не выносится. */
const unitOf = (u) => unitsOf(u)[0];
/** Пробелы внутри `@media (max-width:640px)` — не смысл: сверяем нормализованно.
 *  Гасятся только пробелы ВОКРУГ пунктуации; между словами (`screen and (…)`)
 *  они остаются границей идентификатора, поэтому два РАЗНЫХ запроса совпасть не
 *  могут. Маркер, отвергнутый из-за пропавшего пробела после двоеточия, — это
 *  маркер, который удаляют в раздражении, а с ним и проверку. */
const normMedia = (s) =>
  (s || '')
    .replace(/\s+/g, ' ')
    .replace(/\s*([:,()])\s*/g, '$1')
    .trim();

const exempts = [];
const moves = [];
const malformed = [];
for (const line of addedLines) {
  if (line.includes(`${EXEMPT}:`)) {
    const key = exemptKeyPart(line);
    const m = key && key.match(reExemptTail);
    const u = m && m[1].trim();
    /* Правило одно и то же с двух сторон: ЕДИНИЦА = ТО, ЧТО ГАРД НАПЕЧАТАЛ. У
     * правила С КЛАССОМ В ПОДЛЕЖАЩЕМ напечатанная единица — всегда ОДИН класс
     * (ключ заводится на каждый), у правила с БЕСКЛАССОВЫМ подлежащим —
     * весь селектор. Поэтому многолексемная единица законна ровно когда её
     * ПОДЛЕЖАЩЕЕ бесклассовое: `h1 em` (голые теги) и `.pro-up .lockmsg svg`
     * (подлежащее `svg` класса не несёт, хоть предки и классы) — обе гард
     * печатает ЦЕЛЫМ селектором, и разбор справа налево для того и делался.
     * А `.pro-up--inline .pu-body` (подлежащее `.pu-body` — КЛАСС) гард не
     * печатает никогда: он печатает `.pro-up--inline` и `.pu-body` порознь, а
     * составной селектор — справа от значения, как подсказку для `visual-diff-move`.
     * ★ ГРАНИЦА ИМЕННО ПО ПОДЛЕЖАЩЕМУ, А НЕ «ЕСТЬ ЛИ КЛАСС ГДЕ-НИБУДЬ» (TRIP-366).
     * Прежний предикат `classesOf(u).length > 0` отвергал `.pro-up .lockmsg svg`
     * как составной — а это ровно та бесклассовая единица из нескольких лексем,
     * которую гард печатает и которую нечем было объявить (снос `.lockmsg`).
     * Предикат теперь ПОВТОРЯЕТ развилку `unitsOf` (классы подлежащего): несёт
     * класс → per-class ключи, маркер «про `.pu-body`» молча гасил бы правку на
     * ПРЕДКЕ (дыра TRIP-363, найдена `code-simplifier`), поэтому такой остаётся
     * malformed. Единица без пробела не трогается — у `.a.b` поведение «первый
     * класс» было и до этого. */
    const subjectClassless = u && classesOf(stripFnPseudo(subjectOf(u))).length === 0;
    const compound = u && /\s/.test(u) && !subjectClassless;
    // Единица обязана быть непустой: `visual-diff-exempt: gap — …` адресует
    // пустую строку, не совпадает ни с чем и был бы маркером-пустышкой.
    if (u && !compound) exempts.push({ ...unitOf(u), media: normMedia(m[2]), prop: m[3], used: false });
    else malformed.push(line.trim());
  }
  if (line.includes(`${MOVE}:`)) {
    const m = line.match(reMove);
    const src = m && moveSource(m[1].trim());
    const to = m ? m[2].trim().split(/\s+/).map(bare) : [];
    if (src && to.length && to.every(Boolean)) moves.push({ ...src, to: [...new Set(to)].map((c) => `.${c}`) });
    else malformed.push(line.trim());
  }
}
// Маркер, который автор считает работающим, а гард не разобрал, — самая дорогая
// из тишин: PR уезжает красным по причине, которой в выводе нет.
if (malformed.length) die('маркер(ы) не разобраны — синтаксис ниже', [...malformed, '', ...SYNTAX]);

/* --------- что из изменений ОБЪЯВЛЕНО: сначала переносы, потом точечные ----- */

/** Ключ так, как его печатает гард, — он же ФОРМА МАРКЕРА (всё, что слева от
 *  двоеточия): единица, состояние, `@media`, свойство. */
const fmtId = (c) => `${c.unit}${c.state}${c.media ? ` {${c.media}}` : ''} ${c.prop}`;
/** `+ значение` — объявление появилось, `− значение` — исчезло, `было → стало` —
 *  сменилось. */
const fmtValue = (c) => {
  if (c.from === null) return `+ ${c.to}`;
  if (c.to === null) return `− ${c.from}`;
  return `${c.from} → ${c.to}`;
};
/** Правило, в котором объявление живёт сейчас (а для исчезнувшего — жило на базе),
 *  печатается СПРАВА от значения: слева от двоеточия обязан остаться ровно ключ
 *  (форма `visual-diff-exempt`). Для составного правила это единственный способ
 *  узнать, что писать в `visual-diff-move` (TRIP-363), а вот когда селектор — это
 *  ровно уже напечатанные единица и состояние (`.checkbox`, `.btn:hover`, `:root`),
 *  подсказка была бы ДОСЛОВНЫМ ПОВТОРОМ ключа, то есть шумом на 2595 строках. */
const fmt = (c) => {
  const sel = c.to !== null ? c.toSel : c.fromSel;
  const rule = sel && sel !== `${c.unit}${c.state}` ? `   (правило ${sel})` : '';
  return `  ${fmtId(c)}: ${fmtValue(c)}${rule}`;
};

const headUnits = new Set([...head.best.keys()].map((k) => partsOf(k).unit));
const byKey = new Map(changes.map((c) => [c.key, c]));
const declared = new Set();
const notes = [];
const rejected = [];

for (const mv of moves) {
  // Как источник назван в маркере — единицей или целым селектором; ровно одно
  // из двух заполнено, оно же различает скоуп ниже.
  const src = mv.sel || mv.unit;
  const dst = mv.to.join(' ');
  const empty = mv.to.filter((t) => !headUnits.has(t));
  if (empty.length) {
    rejected.push(`${MOVE}: ${src} → ${dst} — у цели ${empty.join(' ')} на HEAD нет ни одного объявления`);
    continue;
  }
  let moved = 0;
  let unfolded = 0;
  for (const c of changes) {
    // Переносом объясняются только объявления, УШЕДШИЕ с источника (`to === null`);
    // всё остальное на нём — обычное изменение и разбирается точечным маркером.
    if (c.to !== null) continue;
    // Одиночный класс закрывает всё, что ушло С ЭТОЙ ЕДИНИЦЫ; целый селектор —
    // ровно то, что объявлял ОН САМ. Скоуп по НАБОРУ его классов погасил бы
    // заодно снос независимого правила на том же классе (см. шапку, TRIP-363).
    if (mv.sel ? c.fromSel !== mv.sel : c.unit !== mv.unit) continue;
    /* ★ ПОБЕДИТЕЛЬ ПО ВЕСУ СРЕДИ НАЗВАННЫХ ЦЕЛЕЙ, А НЕ «ЕСТЬ ХОТЬ У ОДНОЙ».
     * Элемент носит все классы композиции сразу, и достаётся ему то, что
     * выиграло каскад, — а «есть хоть у одной» приняло бы значение с проигравшей
     * цели, то есть завело бы новую дыру ровно того класса, который мутация
     * нашла в TRIP-363 (маркер, гасящий не то, что удостоверяет). Вес — та же
     * пятёрка [important, специфичность, файл, путь, номер правила], которой
     * карта выбирает победителя внутри единицы, поэтому сравнение целей идёт
     * той же меркой, что и всё остальное. */
    let win = null;
    let winKey = null;
    for (const t of mv.to) {
      const k = [t, c.media, c.state, c.prop].join(SEP);
      const d = head.best.get(k);
      if (d && (!win || cmpWeight(d.weight, win.weight) > 0)) {
        win = d;
        winKey = k;
      }
    }
    // Перенос сходится ВЫЧИСЛЕННЫМ. Если у цели есть контекст-правило <контекст>
    // .tile с ручками плитки — резолвим СТРОГО через него (не через :root-фолбэк:
    // тот проглядел бы ctx-override, `var(--tile-r, --r-sm)` при `--tile-r:20px`
    // вернул бы фолбэк и ослеп). Без ручек-контекста — прежняя сверка sameMovedValue.
    const tsel = win && c.fromSel && tileTargetSel(c.fromSel);
    const ctx = tsel && headHandles.get(normSel(tsel) + SEP + (c.media || ''));
    const ok = win && (ctx
      ? resolveVars(c.from, baseTokens) === resolveVars(win.value, new Map([...headTokens, ...ctx]))
      : sameMovedValue(c.from, win.value));
    if (!win) rejected.push(`${fmtId(c)}: ${c.from} — на ${dst} этого объявления нет`);
    else if (!ok) {
      rejected.push(`${fmtId(c)}: ${c.from} → ${win.value} — перенос на ${partsOf(winKey).unit} СО СМЕНОЙ значения`);
    } else {
      declared.add(c.key);
      moved += 1;
      if (c.from !== win.value) unfolded += 1;
      // Цель, ТОЛЬКО ПРИОБРЁТШУЮ объявление, покрывает тот же перенос. Если у
      // цели значение было другим — это правка живого класса, её не гасим.
      // ★ Гасится приобретение ровно у ПОБЕДИТЕЛЯ: у проигравшей цели новое
      // объявление элементу не достаётся, значит и переносом не объясняется —
      // оно объявляется своей строкой. Это намеренно, а не недосмотр.
      if (byKey.get(winKey)?.from === null) declared.add(winKey);
      // Ручки, что резолвер УПОТРЕБИЛ (встречаются в значении цели И заданы
      // контекстом), — их декларация-приобретение (`--tile:42px`) снимается с
      // блокировки на ВСЕХ классах целевого селектора (`.statbar`+`.tile`+
      // `.c-city`…): безопасность на сверке ВЫЧИСЛЕННОГО выше, не на декларации.
      // Ручка без переноса остаётся блокирующей — `--tile:99px` втихую не пройдёт.
      if (ctx) {
        const used = [...win.value.matchAll(HANDLE_RE)].map((m) => m[1]).filter((h) => ctx.has(h));
        const targetClasses = classesOf(tsel).map((cl) => `.${cl}`);
        for (const h of used) {
          for (const u of targetClasses) {
            const hk = [u, c.media, c.state, h].join(SEP);
            if (byKey.get(hk)?.from === null) declared.add(hk);
          }
        }
      }
    }
  }
  // Число «сошлось через токен» печатается ОТДЕЛЬНО: разворачивание `var()` —
  // это ослабление сверки, и его цена обязана стоять рядом с результатом, а не
  // растворяться в общем счёте.
  notes.push(
    `перенос ${src} → ${dst}: объявлений ${moved}` + (unfolded ? ` (из них ${unfolded} сошлись через токен)` : ''),
  );
}

for (const c of changes) {
  if (declared.has(c.key)) continue;
  const ex = exempts.find(
    (e) => e.unit === c.unit && e.media === normMedia(c.media) && e.state === c.state && e.prop === c.prop,
  );
  if (!ex) continue;
  ex.used = true;
  declared.add(c.key);
}
for (const e of exempts) {
  const id = `${EXEMPT}: ${e.unit}${e.state}${e.media ? ` {${e.media}}` : ''} ${e.prop}`;
  notes.push(e.used ? `${id} — изменение объявлено намеренным` : `${id} — под маркером изменений нет`);
}

const blocking = changes.filter((c) => !declared.has(c.key));

/* Бесклассовый ярус печатается ОТДЕЛЬНО и с разбивкой «токены · прочее»: по
 * ней видно, что слепая зона была не только про цвет, а ноль в любой из
 * половин — внятный сигнал, что ветка перестала измеряться. Суммарное число
 * такую пропажу растворило бы в тысяче классов. */
const nClasses = [...headUnits].filter((u) => u.startsWith('.')).length;
const looseKeys = [...head.best.keys()].filter((k) => !k.startsWith('.'));
const nTokens = looseKeys.filter((k) => partsOf(k).prop.startsWith('--')).length;
console.log(`check-css-semantics (2p): HEAD vs ${BASE_REF}`);
console.log(`  классов под наблюдением: ${nClasses}`);
console.log(
  `  бесклассовых селекторов: ${headUnits.size - nClasses}` +
    ` (объявлений ${looseKeys.length}: токенов ${nTokens} · прочих ${looseKeys.length - nTokens})`,
);
console.log(`  объявлений сравнено:     ${head.best.size}`);
if (changes.length) console.log(`  изменений: ${changes.length} · объявлено: ${declared.size} · блокирует: ${blocking.length}`);
notes.forEach((n) => console.log(`  ${n}`));

/* Список блокирующих печатается ДО проверки переносов, а выход по ним — ПОСЛЕ:
 * если разом сломаны и маркер переноса, и что-то ещё, автор видит обе половины,
 * а не только ту, что уронила прогон первой. */
if (blocking.length) {
  console.log('');
  blocking.slice(0, 60).sort((a, b) => a.key.localeCompare(b.key)).forEach((c) => console.log(fmt(c)));
  if (blocking.length > 60) console.log(`  … и ещё ${blocking.length - 60}`);
}
if (rejected.length) {
  console.log('');
  rejected.forEach((r) => console.log(`  ${r}`));
  console.error(
    `::error::check-css-semantics: объявленный ${MOVE} не сошёлся, случаев: ${rejected.length}. ` +
      'На цели либо нет этого объявления, либо значение при переносе изменилось.',
  );
  process.exit(1);
}
if (blocking.length) {
  console.error(
    `::error::check-css-semantics: итоговые объявления изменились у ${blocking.length} ключ(ей). ` +
      `Если это намеренно — объяви каждое изменение отдельной строкой в диффе:\n` +
      SYNTAX.join('\n'),
  );
  process.exit(1);
}
console.log(
  changes.length
    ? `  необъявленных изменений нет: все ${changes.length} объявлены переносом или исключением.`
    : '  итоговые объявления не изменились ни у одного класса и ни у одного токена.',
);
process.exit(0);
